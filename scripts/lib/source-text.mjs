/**
 * Исходник без комментариев — для охран, которые его читают.
 *
 * В репозитории пятьдесят пять тестов читают исходный код и проверяют, что в
 * нём что-то есть: вызов, условие, класс. Комментарий при этом такой же текст,
 * и охрана, ищущая подстроку, не отличает работающую строку от закомментированной.
 *
 * Проверено поломкой 24.09.2026, а не выведено рассуждением: строку
 * `onSwitchCashier={handleLogout}` завернули в `{/* … *\/}` — кнопка передачи
 * кассы перестала быть подключённой, тупик вернулся, и все пять тестов её
 * охраны остались зелёными.
 *
 * Отсюда правило: охрана, требующая наличия, читает исходник через эту
 * функцию. Охране, ищущей нарушителей, она не нужна и даже вредна —
 * закомментированное нарушение и есть отсутствующее нарушение.
 *
 * Строки не трогаем: `'// это не комментарий'` внутри строкового литерала
 * встречается в текстах отказов, и вырезать его значило бы врать в другую
 * сторону. Разбор нарочно простой — задача не разобрать JavaScript, а не
 * принять комментарий за код.
 *
 * Регулярные выражения пришлось выучить отдельно — 29.09.2026, поломкой.
 * Охрана содержала `/url\(\s*['"]?([^'")]+)/g`; кавычка внутри класса символов
 * открывала «строку», которая не закрывалась никогда, и дальше по файлу
 * комментарии переставали сниматься вовсе. Заметили это громко — пример
 * `requireSecret('SENDGRID_API_KEY')` из комментария той же охраны был прочитан
 * как настоящий вызов, — но ошибка эта умеет и молчать: незакрытая строка
 * оставляет закомментированный код видимым, а это ровно тот случай, ради
 * которого весь файл и написан.
 */

/**
 * @param {string} source
 * @param {{ lineComments?: boolean }} [options] `lineComments: false` — для CSS:
 *   строчных комментариев там не бывает, а `//` встречается внутри `url(https://…)`,
 *   и съесть из-за него остаток строки значило бы уронить охрану на исправном файле.
 * @returns {string} тот же текст, где комментарии заменены пробелами
 */
/**
 * Слово, после которого слэш начинает регулярное выражение, а не деление.
 *
 * `return /x/` — выражение, `a / b` — деление. Различить их без разбора
 * грамматики нельзя, но можно по предыдущему значимому символу: после имени,
 * числа, `)` или `]` слэш делит, после всего остального — открывает регулярку.
 */
const BEFORE_REGEX = /(^|[^\w$)\]])(return|typeof|instanceof|case|in|of|new|delete|void|yield|await|do|else)$/;

function startsRegex(before) {
  const trimmed = before.replace(/\s+$/, '');
  if (trimmed === '') return true;
  const last = trimmed[trimmed.length - 1];
  if ('=(,:[!&|?{};+-*%~^<>'.includes(last)) return true;
  return BEFORE_REGEX.test(trimmed);
}

export function withoutComments(source, options = {}) {
  const lineComments = options.lineComments !== false;
  let out = '';
  let i = 0;
  /** @type {null | '"' | "'" | '`'} */
  let quote = null;
  while (i < source.length) {
    const ch = source[i];
    const next = source[i + 1];

    if (quote) {
      out += ch;
      if (ch === '\\') {
        out += next ?? '';
        i += 2;
        continue;
      }
      if (ch === quote) quote = null;
      i += 1;
      continue;
    }

    if (ch === '"' || ch === "'" || ch === '`') {
      quote = /** @type {'"' | "'" | '`'} */ (ch);
      out += ch;
      i += 1;
      continue;
    }

    if (lineComments && ch === '/' && next === '/') {
      while (i < source.length && source[i] !== '\n') i += 1;
      continue;
    }

    /* Регулярное выражение — не деление и не комментарий.

       Внутри него кавычка кавычкой не является, а `//` не начинает
       комментарий: `/^(https?:)?\/\//` — это адрес, а не пустая регулярка с
       хвостом. Класс символов `[...]` считается отдельно, потому что `/`
       внутри него закрывать выражение не должен. */
    if (ch === '/' && next !== '/' && next !== '*' && startsRegex(out)) {
      out += ch;
      i += 1;
      let inClass = false;
      while (i < source.length) {
        const c = source[i];
        if (c === '\\') {
          out += c + (source[i + 1] ?? '');
          i += 2;
          continue;
        }
        // Не закрылась до конца строки — значит это всё-таки было деление.
        if (c === '\n') break;
        out += c;
        i += 1;
        if (c === '[') inClass = true;
        else if (c === ']') inClass = false;
        else if (c === '/' && !inClass) break;
      }
      // Флаги.
      while (i < source.length && /[a-z]/.test(source[i])) {
        out += source[i];
        i += 1;
      }
      continue;
    }

    if (ch === '/' && next === '*') {
      i += 2;
      while (i < source.length && !(source[i] === '*' && source[i + 1] === '/')) {
        // Переводы строк сохраняются: охраны считают по ним номера строк.
        if (source[i] === '\n') out += '\n';
        i += 1;
      }
      i += 2;
      continue;
    }

    out += ch;
    i += 1;
  }
  return out;
}
