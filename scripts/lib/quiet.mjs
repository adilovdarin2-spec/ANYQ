/**
 * Лог, который молчит про рутину, но не молчит совсем.
 *
 * Планировщик обслуживания просыпается каждую минуту, и почти всегда ему нечего
 * сказать: очередь пуста, просроченных ключей нет, сводки не ко времени. Если
 * говорить об этом каждый раз, получается больше четырёх тысяч строк в сутки, в
 * которых настоящая — одна. Такой лог не читают, а значит его нет.
 *
 * Но и молчать насовсем нельзя, и это вторая половина задачи: лог — единственное
 * окно в работу, которую никто не видит, и тишина остановившегося планировщика
 * выглядит ровно как тишина спокойной ночи. Поэтому рутина печатается в двух
 * случаях: когда изменилась и раз в час. Час — чтобы в сутках осталось двадцать
 * четыре доказательства жизни вместо четырёх тысяч.
 *
 * Разделение по ключу, а не одним флагом на весь тик: «очередь пуста» и «сводки
 * не ко времени» меняются независимо, и изменение одного не должно прятать или
 * показывать другое.
 *
 * `now` и `write` передаются снаружи, потому что иначе это поведение нельзя
 * проверить: проверка «раз в час» с настоящими часами это проверка длиной в час.
 */
export function createQuietLog({ write, heartbeatMs = 60 * 60 * 1000, now = () => Date.now() }) {
  const lastRoutine = new Map();
  let lastHeartbeat = 0;
  // Первый тик — всегда полная картина: человек, только что запустивший службу,
  // должен увидеть её состояние, а не пустой экран.
  let heartbeatDue = true;

  return {
    /** Начало тика: решаем один раз, пришёл ли час подтвердить, что мы живы. */
    beginTick() {
      const at = now();
      heartbeatDue = at - lastHeartbeat >= heartbeatMs;
      if (heartbeatDue) lastHeartbeat = at;
    },

    /**
     * Произошло что-то настоящее или что-то сломалось. Видно всегда.
     *
     * И сбрасывает память о рутине — это не мелочь, а вторая половина смысла.
     * Без сброса лог после строки FAILED замолкал бы до конца часа, потому что
     * «удалено 0» формально не изменилось, — и человек, читающий этот лог,
     * видел бы сбой и тишину после него. Тишина после сбоя читается как «всё
     * ещё сломано», хотя на следующей же минуте всё уже работало.
     */
    say(line) {
      lastRoutine.clear();
      write(line);
    },

    /** Обычное состояние. Видно, когда изменилось, и раз в час. */
    routine(key, line) {
      const changed = lastRoutine.get(key) !== line;
      lastRoutine.set(key, line);
      if (changed || heartbeatDue) write(line);
    },
  };
}
