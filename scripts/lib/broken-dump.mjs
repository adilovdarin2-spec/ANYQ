/**
 * Порченая копия — словами, а не строкой из zlib.
 *
 * Копия, скачанная наполовину, выглядит как копия: тот же вид, то же
 * расширение, правдоподобный размер. Разворачивают её обычно не от хорошей
 * жизни, и именно в эту минуту человек получал «invalid code -- missing
 * end-of-block» — внутреннее сообщение zlib, в котором не сказано ни что за
 * файл, ни что с ним делать.
 *
 * Разбор шёл по тексту сообщения, и в этом была ошибка: текстов у zlib
 * несколько, в списке было три, а пришёл четвёртый. Код ошибки — `err.code` —
 * поле, а не проза: он переживает и перевод, и версию Node. Поток отдаёт
 * ошибку как есть, поэтому поле доходит до обработчика нетронутым.
 *
 * Ошибка базы сюда не попадает намеренно: «нет прав», «такой роли нет» и
 * «кончилось место» — это не про файл, и назвать их порчей копии значило бы
 * отправить человека искать новую копию вместо того, чтобы чинить сервер.
 */

/** Коды zlib, которые означают «этот файл не разворачивается». */
const ZLIB_BROKEN = new Set([
  'Z_DATA_ERROR', // битые байты внутри
  'Z_BUF_ERROR', // оборвался на середине
]);

/** Тексты — на случай, если ошибка пришла уже обёрнутой и поля не осталось. */
const BROKEN_TEXT = /Z_DATA_ERROR|Z_BUF_ERROR|incorrect header check|unexpected end of file|invalid (code|distance|stored block|block type)/i;

/**
 * Сообщение для человека — или `null`, если дело не в файле.
 *
 * @param {unknown} err ошибка, как её отдал поток
 * @param {string} file путь к копии, чтобы было сказано, о какой речь
 * @returns {string | null}
 */
export function brokenDumpMessage(err, file) {
  const code = err && typeof err === 'object' ? /** @type {{code?: unknown}} */ (err).code : undefined;
  const message = err && typeof err === 'object' ? String(/** @type {{message?: unknown}} */ (err).message ?? '') : '';
  if (!ZLIB_BROKEN.has(String(code)) && !BROKEN_TEXT.test(message)) return null;
  return (
    `Файл «${file}» не разворачивается: это не gzip или он скачан не полностью. ` +
    'Возьмите другую копию — эту считать негодной.' +
    // Техническая строка остаётся: она нужна тому, кто будет разбираться,
    // почему копия испортилась, а не тому, кому сейчас надо восстановиться.
    (message ? `\n(${message})` : '')
  );
}
