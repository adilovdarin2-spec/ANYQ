import { describe, it, expect } from 'vitest';
import { buildImportPlan } from '../apps/api/src/import';
import { sameArticle as serverSameArticle } from '../apps/api/src/barcode';
import { resolveScannedBarcode } from '../apps/pos/src/utils';
import { readScannedMarking } from '../apps/pos/src/marking-scan';

/**
 * Что импорт записал — то касса и находит. Обоими сканерами.
 *
 * Сканеров два, и они ищут по-разному. Обычный сравнивает строку точно:
 * `resolveScannedBarcode`. Сканер маркировки достаёт из Data Matrix
 * четырнадцатизначный GTIN и отбрасывает ведущие нули: `readScannedMarking`.
 *
 * Каталог заводится импортом, и записанный им артикул обязан подойти обоим.
 * Запиши импорт четырнадцать знаков — и получится товар, который находится
 * сканером маркировки и не находится обычным; запиши он их по-своему — и
 * наоборот. Ни то, ни другое у прилавка не объяснить: сигареты пробивают весь
 * день, и «иногда не находится» читается как сломанная касса.
 *
 * Проверяется поведением, а не чтением исходников: обе стороны переписывались
 * бы независимо, а здесь одна кормит другую настоящим ответом.
 */

/** Как касса видит товар из каталога. */
const каталог = (barcode: string) => [{ id: 'p1', barcode, packagings: [] }];

function ввезти(header: string[], строка: string[]): string | null {
  const plan = buildImportPlan([header, строка], []);
  expect(plan.rows, JSON.stringify(строка)).toHaveLength(1);
  return plan.rows[0].barcode;
}

/** Код маркировки, как он приходит со сканера: GS1 с GTIN и серийником. */
const датаматрикс = (gtin14: string) => `01${gtin14}21ABCDEF`;

describe('товар из выгрузки и два сканера', () => {
  it('файл со штрихкодом: находится обычным сканером', () => {
    const записано = ввезти(['Наименование', 'Штрихкод', 'Цена'], ['Чай', '4006381333931', '500']);
    expect(resolveScannedBarcode('4006381333931', каталог(записано!))).toEqual({
      productId: 'p1',
      unitsPerPack: 1,
    });
  });

  it('файл только с GTIN: находится обоими', () => {
    /* Ради чего вся эта часть. 1С выгружает GTIN вместо штрихкода, и до
       25.09.2026 такой товар заводился без кода вовсе. */
    const записано = ввезти(['Наименование', 'GTIN', 'Цена'], ['Сигареты', '04006381333931', '1400']);

    // Обычный сканер: на пачке напечатаны тринадцать знаков.
    expect(resolveScannedBarcode('4006381333931', каталог(записано!)), 'обычный сканер не нашёл').toEqual({
      productId: 'p1',
      unitsPerPack: 1,
    });

    // Сканер маркировки: в Data Matrix артикул в четырнадцать знаков.
    const скан = readScannedMarking(датаматрикс('04006381333931'), [{ id: 'p1', barcode: записано! }]);
    expect(скан, 'код маркировки не разобрался').not.toBeNull();
    expect(скан!.productId, 'сканер маркировки не нашёл').toBe('p1');
  });

  it('и записанное четырнадцатью знаками нашлось бы только одним — поэтому так не пишем', () => {
    /* Обратная сторона: показано, что выбор формы записи не вкусовщина.
       Товар, заведённый с нулём впереди, сканер маркировки найдёт, а обычный —
       нет, и половина пачек в магазине станет «не найдена». */
    const какБылоБы = '04006381333931';
    expect(resolveScannedBarcode('4006381333931', каталог(какБылоБы))).toBeNull();
    const скан = readScannedMarking(датаматрикс('04006381333931'), [{ id: 'p1', barcode: какБылоБы }]);
    expect(скан!.productId).toBe('p1');
  });

  it('коробка из файла находится своим кодом', () => {
    const plan = buildImportPlan(
      [
        ['Наименование', 'Штрихкод', 'Цена', 'В упаковке', 'Упаковка', 'Штрихкод упаковки'],
        ['Сок', '4006381333931', '500', '12', 'Ящик', '4870123456789'],
      ],
      [],
    );
    const row = plan.rows[0];
    const товары = [
      {
        id: 'p1',
        barcode: row.barcode!,
        packagings: [{ id: 'k1', unitsPerPack: row.packaging!.unitsPerPack, barcode: row.packaging!.barcode! }],
      },
    ];
    // Скан короба на приёмке кладёт двенадцать штук, а не одну.
    expect(resolveScannedBarcode('4870123456789', товары)).toEqual({ productId: 'p1', unitsPerPack: 12 });
    // А скан пачки — одну.
    expect(resolveScannedBarcode('4006381333931', товары)).toEqual({ productId: 'p1', unitsPerPack: 1 });
  });
});

describe('два одинаковых правила в двух приложениях', () => {
  it('«один ли это артикул» отвечает одинаково на обеих сторонах', () => {
    /* `sameArticle` есть и в кассе (`marking-scan`), и на сервере (`barcode`):
       касса решает, что пробить, сервер решает, что записать. Разойдись они — и
       импорт записал бы код, который касса своим не считает.

       Касса своего правила наружу не отдаёт, поэтому серверное сверяется с
       ответом настоящего поиска кассы. */
    const пары: [string, string][] = [
      ['04006381333931', '4006381333931'],
      ['00000096385074', '96385074'],
      ['4006381333931', '4006381333931'],
      ['4006381333931', '4006381333932'],
      ['14006381333931', '4006381333931'],
      ['0000', '0'],
    ];
    for (const [gtin, barcode] of пары) {
      const скан = readScannedMarking(датаматрикс(gtin.padStart(14, '0')), [{ id: 'p1', barcode }]);
      const касса = скан?.productId === 'p1';
      const сервер = serverSameArticle(gtin.padStart(14, '0'), barcode);
      expect(сервер, `${gtin} против ${barcode}`).toBe(касса);
    }
  });
});
