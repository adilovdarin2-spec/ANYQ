/**
 * Спецификация производства — что и сколько уходит на одну партию.
 *
 * До 15.09.2026 её негде было завести. Экран производства в кассе был, маршрут
 * запуска был, тариф со складом её продавал — а список спецификаций приходил
 * пустым и остаться пустым был обязан: ни одного маршрута, который создаёт
 * рецепт, в продукте не существовало. Владелец открывал «Производство» и читал
 * «Нет спецификаций», сколько бы раз ни зашёл.
 *
 * Здесь только правила, которые можно проверить, не открывая базу. Всё
 * остальное — в маршруте.
 */

export interface RecipeLineInput {
  ingredientId: string;
  quantity: number;
}

/**
 * Что не так со спецификацией — словами, или `null`, если всё в порядке.
 *
 * Возвращает готовую фразу, а не флаг, по той же причине, что и везде здесь:
 * место, которое решает «нельзя», и место, которое объясняет почему, должны
 * быть одним местом.
 */
export function recipeRefusal(
  productId: string,
  portionYield: number,
  lines: RecipeLineInput[],
  knownProductIds: ReadonlySet<string>,
): string | null {
  if (!knownProductIds.has(productId)) return 'Товар не найден';

  // Выход партии — это то, на что делят при расчёте: сколько партий варить,
  // чтобы получить нужное количество. Ноль здесь — деление на ноль.
  if (!Number.isFinite(portionYield) || portionYield <= 0) {
    return 'Выход партии должен быть больше нуля';
  }

  if (lines.length === 0) return 'Добавьте хотя бы одну составляющую';

  const seen = new Set<string>();
  for (const line of lines) {
    // Товар, сделанный из самого себя. Расчёт от этого не зациклится — он
    // разворачивает рецепт на один шаг, — но производство будет списывать то
    // же, что производит, и остаток останется на месте при израсходованном
    // сырье. Это не спецификация, это опечатка.
    if (line.ingredientId === productId) return 'Товар не может быть составляющей самого себя';
    if (!knownProductIds.has(line.ingredientId)) return 'Составляющая не найдена';
    // Дважды один и тот же ингредиент — это не «сложить», а промах пальцем:
    // сложив молча, мы запишем расход, которого никто не задавал.
    if (seen.has(line.ingredientId)) return 'Одна составляющая указана дважды';
    seen.add(line.ingredientId);
    if (!Number.isFinite(line.quantity) || line.quantity <= 0) {
      return 'Количество составляющей должно быть больше нуля';
    }
  }

  return null;
}
