import { describe, it, expect } from 'vitest';
import { buildImportPlan, detectColumns } from './import';
import { articleFromGtin, sameArticle } from './barcode';

/**
 * GTIN из выгрузки — тот же артикул, записанный четырнадцатью знаками.
 *
 * 1С и системы маркировки выгружают именно его, и в файле он бывает **вместо**
 * штрихкода, а не рядом. Пропустив такой столбец, каталог заводится совсем без
 * кодов — а сигареты, на которых держится заметная часть выручки продуктового,
 * не находятся тогда ни одним сканером.
 *
 * Записывается он в напечатанном виде, и это не косметика. Обычный поиск
 * сравнивает строки точно (`resolveScannedBarcode` в кассе), а сканер
 * маркировки отбрасывает нули сам (`sameArticle`). Четырнадцать знаков в
 * каталоге означали бы товар, который находит один сканер и не находит другой,
 * — и объяснить это у прилавка было бы нечем.
 */

const план = (header: string[], строки: string[][]) => buildImportPlan([header, ...строки], []);

describe('артикул из GTIN', () => {
  it('у пачки — это тот же код без ведущих нулей', () => {
    expect(articleFromGtin('04006381333931')).toBe('4006381333931');
    expect(articleFromGtin('00000096385074')).toBe('96385074');
  });

  it('а у короба — остаётся как есть', () => {
    /* Первая цифра GTIN-14 означает уровень упаковки, и контрольная у короба
       своя. Отбросив её, мы выдали бы код короба за код пачки — и приёмка
       положила бы на полку не тот товар. */
    expect(articleFromGtin('14006381333931')).toBe('14006381333931');
    expect(articleFromGtin('54006381333931')).toBe('54006381333931');
  });

  it('и короткое число не трогается вовсе', () => {
    expect(articleFromGtin('4006381333931')).toBe('4006381333931');
    expect(articleFromGtin('96385074')).toBe('96385074');
  });

  it('один ли это артикул — с точностью до нулей', () => {
    expect(sameArticle('04006381333931', '4006381333931')).toBe(true);
    expect(sameArticle('4006381333931', '4006381333932')).toBe(false);
    // Пустое не совпадает ни с чем: иначе первый товар без кода стал бы ответом
    // на любой скан.
    expect(sameArticle('', '4006381333931')).toBe(false);
    expect(sameArticle('0000', '')).toBe(false);
  });
});

describe('столбец GTIN в чужом заголовке', () => {
  it('узнаётся', () => {
    for (const имя of ['GTIN', 'gtin', 'GTIN-14', 'Код GTIN', 'Глобальный код товара']) {
      const columns = detectColumns(['Наименование', имя, 'Цена']);
      expect(columns.gtin, имя).toBe(1);
    }
  });

  it('и не путается со штрихкодом', () => {
    const columns = detectColumns(['Наименование', 'GTIN', 'Штрихкод', 'Цена']);
    expect(columns.gtin).toBe(1);
    expect(columns.barcode).toBe(2);
  });
});

describe('GTIN в строке', () => {
  const ТОЛЬКО_GTIN = ['Наименование', 'GTIN', 'Цена'];
  const ОБА = ['Наименование', 'Штрихкод', 'GTIN', 'Цена'];

  it('становится штрихкодом, когда штрихкода нет', () => {
    /* Ради чего всё: файл из 1С часто несёт только его, и без этого сигареты
       заводились бы без кода вовсе. */
    const p = план(ТОЛЬКО_GTIN, [['Сигареты «Астана»', '04006381333931', '1400']]);
    expect(p.rows[0].barcode).toBe('4006381333931');
    expect(p.problems).toEqual([]);
  });

  it('и пачка после этого находится обоими сканерами', () => {
    /* Обычный сканер сравнивает строку точно, сканер маркировки отбрасывает
       нули. Записанный артикул обязан подойти обоим — иначе получится товар,
       который находится одним и не находится другим. */
    const p = план(ТОЛЬКО_GTIN, [['Сигареты', '04006381333931', '1400']]);
    const записано = p.rows[0].barcode!;
    // Обычный скан того, что напечатано на пачке.
    expect(записано).toBe('4006381333931');
    // Скан кода маркировки: внутри него артикул в четырнадцать знаков.
    expect(sameArticle('04006381333931', записано)).toBe(true);
  });

  it('а при своём штрихкоде — не спорит с ним, если это один товар', () => {
    const p = план(ОБА, [['Сигареты', '4006381333931', '04006381333931', '1400']]);
    expect(p.rows[0].barcode).toBe('4006381333931');
    expect(p.problems, 'одно и то же число названо разногласием').toEqual([]);
  });

  it('и говорит, когда они про разные товары', () => {
    // Решить, какое верное, может только магазин: оба выглядят настоящими.
    const p = план(ОБА, [['Сигареты', '4006381333931', '04870123456789', '1400']]);
    expect(p.rows[0].barcode, 'штрихкод печатают на ценнике — он и остаётся').toBe('4006381333931');
    expect(p.problems).toHaveLength(1);
    expect(p.problems[0].severity).toBe('warning');
    expect(p.problems[0].message).toContain('4870123456789');
    expect(p.problems[0].message).toContain('разные товары');
  });

  it('грязный GTIN чистится так же, как штрихкод', () => {
    const p = план(ТОЛЬКО_GTIN, [['Сигареты', "'0400 6381 333931", '1400']]);
    expect(p.rows[0].barcode).toBe('4006381333931');
  });

  it('и про испорченный Excel говорят — но только если заменить его нечем', () => {
    const один = план(ТОЛЬКО_GTIN, [['Сигареты', '4.87012E+13', '1400']]);
    expect(один.rows[0].barcode).toBeNull();
    expect(один.problems).toHaveLength(1);
    expect(один.problems[0].severity).toBe('error');

    /* А когда штрихкод есть, замечание про неиспользуемый столбец только
       отвлекает: человеку нечего с ним делать. */
    const оба = план(ОБА, [['Сигареты', '4006381333931', '4.87012E+13', '1400']]);
    expect(оба.rows[0].barcode).toBe('4006381333931');
    expect(оба.problems).toEqual([]);
  });

  it('и код короба не выдаётся за код пачки', () => {
    // GTIN-14, начинающийся не с нуля, записывается как есть: это другой код.
    const p = план(ТОЛЬКО_GTIN, [['Сигареты', '14006381333931', '1400']]);
    expect(p.rows[0].barcode).toBe('14006381333931');
  });

  it('а файл без столбца GTIN разбирается ровно как раньше', () => {
    const p = buildImportPlan(
      [
        ['Наименование', 'Штрихкод', 'Цена'],
        ['Чай', '4006381333931', '500'],
      ],
      [],
    );
    expect(p.rows[0].barcode).toBe('4006381333931');
    expect(p.problems).toEqual([]);
  });
});
