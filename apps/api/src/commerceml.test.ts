import { describe, it, expect } from 'vitest';
import {
  FALLBACK_UNIT_CODE,
  SCHEMA_VERSION,
  catalogXml,
  commerceTimestamp,
  escapeXml,
  groupId,
  offersXml,
  unitOf,
} from './commerceml';
import type { CommerceOffer, CommerceProduct } from './commerceml';

/**
 * Выгрузка, которую 1С откроет, а бухгалтер узнает.
 *
 * Проверить по-настоящему это можно только загрузкой в живую 1С, и здесь этого
 * не делается — тест сторожит то, что проверяемо без неё: разметка не
 * ломается, кодировка объявлена, казахские буквы доходят целыми, а
 * идентификаторы не меняются от выгрузки к выгрузке, иначе повторная загрузка
 * заведёт второй каталог рядом с первым.
 */

const meta = {
  companyId: 'cmpny1',
  companyName: 'Магазин «Аян»',
  at: new Date('2026-09-15T00:20:00.000Z'),
};

const продукты: CommerceProduct[] = [
  { id: 'p1', name: 'Хлеб «Бородинский»', unit: 'шт', barcode: '4870001234567', category: 'Бакалея' },
  { id: 'p2', name: 'Сахар', unit: 'кг', barcode: null, category: 'Бакалея' },
  { id: 'p3', name: 'Су & Сүт', unit: 'мешок', barcode: null, category: null },
];

describe('каталог', () => {
  const xml = catalogXml(meta, продукты);

  it('объявляет кодировку и версию схемы', () => {
    // Без объявленной кодировки 1С читает файл по-своему, и казахские буквы
    // превращаются в вопросительные знаки.
    expect(xml.startsWith('<?xml version="1.0" encoding="UTF-8"?>')).toBe(true);
    expect(xml).toContain(`ВерсияСхемы="${SCHEMA_VERSION}"`);
  });

  it('несёт каждый товар', () => {
    for (const p of продукты) {
      expect(xml, p.name).toContain(`<Ид>${p.id}</Ид>`);
    }
  });

  it('казахские и русские буквы доходят целыми', () => {
    // Ровно та причина, по которой выгрузка идёт в UTF-8, а не в cp1251:
    // «Сүт» в cp1251 не записывается.
    expect(xml).toContain('Сүт');
    expect(xml).toContain('Хлеб «Бородинский»');
  });

  it('амперсанд не ломает разметку', () => {
    expect(xml).toContain('Су &amp; Сүт');
    expect(xml).not.toContain('Су & Сүт');
  });

  it('группы заводятся по категориям и только по ним', () => {
    expect(xml).toContain('<Наименование>Бакалея</Наименование>');
    // Товар без категории просто не попадает ни в какую группу — выдумывать
    // ему «Прочее» значит завести в 1С группу, которой у магазина нет.
    const группы = xml.slice(xml.indexOf('<Группы>'), xml.indexOf('</Группы>'));
    expect(группы).not.toContain('Прочее');
  });

  it('штрихкод выгружается, когда он есть, и не выдумывается, когда нет', () => {
    expect(xml).toContain('<Штрихкод>4870001234567</Штрихкод>');
    expect(xml.match(/<Штрихкод>/g)).toHaveLength(1);
  });

  it('открывающих и закрывающих тегов поровну', () => {
    // Дешёвая проверка на то, что склейка строк не потеряла закрытие: файл с
    // непарным тегом 1С не открывает вовсе, и сообщение об этом — про строку
    // и столбец, а не про то, чего в нём не хватает.
    for (const tag of ['КоммерческаяИнформация', 'Классификатор', 'Каталог', 'Товары', 'Товар']) {
      const open = xml.match(new RegExp(`<${tag}[ >]`, 'g')) ?? [];
      const close = xml.match(new RegExp(`</${tag}>`, 'g')) ?? [];
      expect(open.length, tag).toBe(close.length);
    }
  });

  it('пустой каталог остаётся правильным файлом', () => {
    const empty = catalogXml(meta, []);
    expect(empty).toContain('<Товары>');
    expect(empty).toContain('</КоммерческаяИнформация>');
  });
});

describe('предложения', () => {
  const предложения: CommerceOffer[] = [
    { id: 'p1', name: 'Хлеб', unit: 'шт', price: 280, quantity: 24 },
    { id: 'p2', name: 'Сахар', unit: 'кг', price: 540, quantity: 12.5 },
  ];
  const xml = offersXml(meta, предложения);

  it('цена и остаток стоят у каждого предложения', () => {
    expect(xml).toContain('<ЦенаЗаЕдиницу>280</ЦенаЗаЕдиницу>');
    expect(xml).toContain('<Количество>24</Количество>');
  });

  it('дробный остаток не округляется', () => {
    // Весовой товар: 12,5 кг — это 12,5 кг, а не 12 и не 13.
    expect(xml).toContain('<Количество>12.5</Количество>');
  });

  it('валюта названа, а не подразумевается', () => {
    expect(xml).toContain('<Валюта>KZT</Валюта>');
  });

  it('ссылается на тот же каталог, что и import.xml', () => {
    // Иначе 1С загрузит цены, не найдёт к чему их привязать и промолчит.
    expect(xml).toContain(`<ИдКаталога>${meta.companyId}-catalog</ИдКаталога>`);
    expect(xml).toContain(`<ИдКлассификатора>${meta.companyId}</ИдКлассификатора>`);
  });

  it('тип цены объявлен и совпадает со ссылкой на него', () => {
    const объявлен = xml.slice(xml.indexOf('<ТипыЦен>'), xml.indexOf('</ТипыЦен>'));
    const id = объявлен.match(/<Ид>([^<]+)<\/Ид>/)?.[1];
    expect(id).toBeTruthy();
    expect(xml).toContain(`<ИдТипаЦены>${id}</ИдТипаЦены>`);
  });
});

describe('единицы измерения', () => {
  it('известные переводятся кодом ОКЕИ', () => {
    expect(unitOf('шт').code).toBe('796');
    expect(unitOf('кг').code).toBe('166');
    expect(unitOf('л').code).toBe('112');
  });

  it('регистр и пробелы не мешают', () => {
    expect(unitOf(' Кг ').code).toBe('166');
  });

  it('незнакомая уходит штукой, но со своим названием', () => {
    // Придумать код — значит тихо превратить мешок в штуку уже внутри 1С.
    // Название сохраняется, чтобы бухгалтер увидел своё слово и поправил код,
    // если это важно для его учёта.
    const мешок = unitOf('мешок');
    expect(мешок.code).toBe(FALLBACK_UNIT_CODE);
    expect(мешок.short).toBe('мешок');
    expect(мешок.full).toBe('мешок');
  });

  it('пустая единица не даёт пустого названия', () => {
    expect(unitOf('   ').short).toBe('шт');
  });
});

describe('идентификатор группы', () => {
  it('один и тот же для одной и той же категории', () => {
    // 1С сопоставляет группы по `Ид`. Если он меняется между выгрузками,
    // вторая загрузка заводит вторую «Бакалею» рядом с первой.
    expect(groupId('Бакалея')).toBe(groupId('Бакалея'));
  });

  it('не зависит от регистра и лишних пробелов', () => {
    expect(groupId(' бакалея ')).toBe(groupId('Бакалея'));
  });

  it('у разных категорий разный', () => {
    expect(groupId('Бакалея')).not.toBe(groupId('Молочка'));
  });
});

describe('мелочи разметки', () => {
  it('экранируются все пять опасных символов', () => {
    expect(escapeXml(`<&>"'`)).toBe('&lt;&amp;&gt;&quot;&apos;');
  });

  it('дата формирования — местная и без буквы Z', () => {
    // Выгрузка, помеченная пятью часами раньше, — это выгрузка, про которую
    // бухгалтер скажет «вчерашняя».
    expect(commerceTimestamp(new Date('2026-09-15T00:20:00.000Z'))).toBe('2026-09-15T05:20:00');
    expect(commerceTimestamp(new Date())).not.toContain('Z');
  });
});
