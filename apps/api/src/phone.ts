/**
 * Телефон как имя человека в базе.
 *
 * Клиента и поставщика ANYQ узнаёт по номеру: по нему находятся баллы, долг и
 * кредитный лимит. Сравнивался номер буквально — строка со строкой. А один и
 * тот же человек пишет его каждый раз иначе: на витрине оставил
 * «+7 700 123 45 67», кассир ищет «87001234567», в накладной записано
 * «7001234567». Для базы это три разных человека.
 *
 * Стоит это не аккуратности, а денег: баллы, накопленные под одним написанием,
 * не находятся под другим; долг оптовика разъезжается по двум карточкам, и ни
 * в одной из них он не виден целиком; кредитный лимит, поставленный на одну,
 * не ограничивает вторую.
 *
 * Поэтому номер приводится к одному виду и при записи, и при поиске. Казахстан:
 * `+7 700 …`, `8 700 …` и `700 …` — это один номер.
 */

/**
 * Номер в том виде, в каком он ложится в базу и по которому ищется.
 *
 * Что специально **не** делается: короткий или непонятный номер не
 * достраивается. «+7700» — это чья-то недописанная строка, и превращать её в
 * правдоподобный номер значит придумать за человека. Такое возвращается как
 * есть, только без пробелов по краям: пусть лучше будет видно, что там мусор.
 */
export function phoneKey(raw: string | null | undefined): string {
  if (!raw) return '';
  const trimmed = String(raw).trim();
  const digits = trimmed.replace(/\D/g, '');

  // 8 700 123 45 67 — та же запись, что +7 700 …; восьмёрка досталась от
  // городской телефонии и в базе означает ровно то же самое.
  if (digits.length === 11 && digits.startsWith('8')) return `+7${digits.slice(1)}`;
  if (digits.length === 11 && digits.startsWith('7')) return `+${digits}`;
  // 700 123 45 67 — без кода страны. В Казахстане мобильный всегда начинается
  // с семёрки, так что десять цифр — это номер без кода.
  if (digits.length === 10) return `+7${digits}`;

  // Чужая страна: длина другая, а плюс есть — значит человек знал, что писал.
  if (digits.length > 11 && trimmed.startsWith('+')) return `+${digits}`;

  return trimmed;
}

/** Совпадают ли два номера, как бы они ни были записаны. */
export function samePhone(a: string | null | undefined, b: string | null | undefined): boolean {
  const left = phoneKey(a);
  const right = phoneKey(b);
  return left !== '' && left === right;
}
