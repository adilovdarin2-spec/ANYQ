import { describe, it, expect } from 'vitest';
import { buildImportPlan, detectColumns } from './import';

/**
 * Коробки из выгрузки.
 *
 * Упаковки заводили по одной руками, и для каталога в три тысячи позиций это
 * означало, что их не заводят вовсе. Половина товара приходит коробками, и без
 * них приёмка считается в штуках: кладовщик принимает двадцать коробок и
 * вбивает двести сорок, умножая в уме каждый раз.
 *
 * Правило одно и оно здесь главное: **ни одна ошибка в упаковке не отбрасывает
 * товар**. Товар настоящий и нужен в каталоге; коробку можно завести и потом,
 * руками. Потерять товар из-за числа в соседнем столбце нельзя.
 */

const план = (header: string[], строки: string[][]) => buildImportPlan([header, ...строки], []);

describe('столбцы упаковки в чужом заголовке', () => {
  it('узнаются в тех видах, в каких их пишут', () => {
    const заголовки = [
      ['Наименование', 'Цена', 'В упаковке', 'Упаковка', 'Штрихкод упаковки'],
      ['Наименование', 'Цена', 'Кол-во в упаковке', 'Вид упаковки', 'ШК короба'],
      ['Наименование', 'Цена', 'Кратность', 'Тара', 'Штрихкод коробки'],
      ['Наименование', 'Цена', 'В блоке', 'Қаптама', 'Штрихкод блока'],
    ];
    for (const header of заголовки) {
      const columns = detectColumns(header);
      expect(columns.unitsPerPack, header.join(' | ')).toBe(2);
      expect(columns.packName, header.join(' | ')).toBe(3);
      expect(columns.packBarcode, header.join(' | ')).toBe(4);
    }
  });

  it('и штрихкод коробки не крадёт столбец у штрихкода штуки', () => {
    /* Заголовки разбираются в три прохода, и третий берёт поле, чей синоним
       оказался *началом* заголовка. «Штрихкод коробки» начинается со «штрихкод»,
       и в порядке по умолчанию он достался бы штуке: касса искала бы единицу по
       коду короба и не находила бы ни того, ни другого. */
    const columns = detectColumns(['Наименование', 'Штрихкод коробки', 'Штрихкод', 'Цена']);
    expect(columns.packBarcode).toBe(1);
    expect(columns.barcode, 'штрихкод штуки потерян').toBe(2);
  });

  it('а простой «Штрихкод» не достаётся коробке', () => {
    // Обратная сторона той же перестановки.
    const columns = detectColumns(['Наименование', 'Штрихкод', 'Цена']);
    expect(columns.barcode).toBe(1);
    expect(columns.packBarcode).toBeUndefined();
  });
});

describe('коробка из строки', () => {
  const HEADER = ['Наименование', 'Цена', 'В упаковке', 'Упаковка', 'Штрихкод упаковки'];

  it('заводится с именем, числом и своим штрихкодом', () => {
    const p = план(HEADER, [['Сигареты', '1400', '10', 'Блок', '4006381333931']]);
    expect(p.rows[0].packaging).toEqual({ name: 'Блок', unitsPerPack: 10, barcode: '4006381333931' });
    expect(p.problems).toEqual([]);
  });

  it('без названия получает своё', () => {
    // «Упаковка» — не выдумка, а то слово, которым её назовут руками.
    const p = план(HEADER, [['Сок', '500', '12', '', '']]);
    expect(p.rows[0].packaging).toEqual({ name: 'Упаковка', unitsPerPack: 12, barcode: null });
  });

  it('а без числа не заводится, и про это говорят', () => {
    /* Название без числа — не коробка: приёмка по ней посчитала бы ноль. */
    const p = план(HEADER, [['Сок', '500', '', 'Ящик', '']]);
    expect(p.rows[0].packaging).toBeNull();
    expect(p.rows, 'товар потерян из-за упаковки').toHaveLength(1);
    expect(p.problems[0].severity).toBe('warning');
    expect(p.problems[0].message).toContain('Ящик');
  });

  it('и мусор вместо числа тоже не отбрасывает товар', () => {
    for (const мусор of ['много', '-3', '0', 'нет']) {
      const p = план(HEADER, [['Сок', '500', мусор, 'Ящик', '']]);
      expect(p.rows, мусор).toHaveLength(1);
      expect(p.rows[0].packaging, мусор).toBeNull();
      expect(p.problems.length, мусор).toBeGreaterThan(0);
    }
  });

  it('дробное количество принимается — вес фасуют не штуками', () => {
    // Полкило сахара в пакете: `unitsPerPack` в схеме `Float` ровно за этим.
    const p = план(HEADER, [['Сахар', '450', '0,5', 'Пакет', '']]);
    expect(p.rows[0].packaging?.unitsPerPack).toBe(0.5);
  });

  it('коробка из одной штуки без своего кода не заводится', () => {
    // Считать ей нечего: это та же штука под другим именем.
    const p = план(HEADER, [['Ручка', '150', '1', 'Штука', '']]);
    expect(p.rows[0].packaging).toBeNull();
    expect(p.problems[0].message).toContain('ничего не даёт');
  });

  it('но с собственным кодом — заводится, это второй код той же штуки', () => {
    const p = план(HEADER, [['Ручка', '150', '1', 'Штука', '4006381333931']]);
    expect(p.rows[0].packaging).toEqual({ name: 'Штука', unitsPerPack: 1, barcode: '4006381333931' });
  });
});

describe('штрихкод коробки', () => {
  const HEADER = ['Наименование', 'Цена', 'В упаковке', 'Упаковка', 'Штрихкод упаковки', 'Штрихкод'];

  it('чистится так же, как штрихкод штуки', () => {
    const p = план(HEADER, [['Сок', '500', '12', 'Ящик', "'4006 3813 33931", '']]);
    expect(p.rows[0].packaging?.barcode).toBe('4006381333931');
  });

  it('и про испорченный Excel говорят, не теряя ни товара, ни коробки', () => {
    const p = план(HEADER, [['Сок', '500', '12', 'Ящик', '4.87012E+12', '']]);
    expect(p.rows[0].packaging).toEqual({ name: 'Ящик', unitsPerPack: 12, barcode: null });
    expect(p.problems[0].message).toContain('штрихкод упаковки');
    expect(p.problems[0].severity).toBe('error');
  });

  it('совпадающий с кодом штуки — убирается', () => {
    /* Иначе одно сканирование значило бы то штуку, то двенадцать, и разобраться
       по остатку было бы нельзя. */
    const p = план(HEADER, [['Сок', '500', '12', 'Ящик', '4006381333931', '4006381333931']]);
    expect(p.rows[0].barcode).toBe('4006381333931');
    expect(p.rows[0].packaging?.barcode).toBeNull();
    expect(p.problems[0].message).toContain('совпадает со штрихкодом штуки');
  });

  it('и повторившийся у двух товаров — тоже, у второго', () => {
    // Приёмка по такому коду положила бы на полку не тот товар.
    const p = план(HEADER, [
      ['Сок', '500', '12', 'Ящик', '4006381333931', ''],
      ['Вода', '300', '6', 'Ящик', '4006381333931', ''],
    ]);
    expect(p.rows[0].packaging?.barcode).toBe('4006381333931');
    expect(p.rows[1].packaging?.barcode, 'два товара с одним кодом короба').toBeNull();
    expect(p.rows[1].packaging?.unitsPerPack, 'коробка потеряна целиком').toBe(6);
    expect(p.problems.some((x) => x.message.includes('уже был в строке 2'))).toBe(true);
  });
});

describe('файл без упаковок', () => {
  it('разбирается ровно как раньше', () => {
    // Половина каталога штучная, и ни одного лишнего замечания там быть не должно.
    const p = buildImportPlan(
      [
        ['Наименование', 'Штрихкод', 'Цена'],
        ['Чай', '4006381333931', '500'],
        ['Кофе', '', '900'],
      ],
      [],
    );
    expect(p.rows.map((r) => r.packaging)).toEqual([null, null]);
    expect(p.problems).toEqual([]);
  });
});
