import { findDuplicate, markingRefusalMessage, readLineCodes } from './marking-service';
import type { MarkedCode } from './marking';

/**
 * Промаркировать то, что уже лежит на полке.
 *
 * Это первое, обо что спотыкается магазин, переходящий на маркировку, и до
 * сегодняшнего дня выхода у него не было. Владелец ставит товару признак
 * «продаётся только по коду» — и сорок пачек, купленных на прошлой неделе,
 * перестают продаваться: касса требует код, а кодов у них нет и завести их
 * негде. Ни продать, ни объяснить.
 *
 * Между тем это не край случай, а обычный порядок: когда категория переходит
 * под маркировку, остатки маркируют — берут коробку, сканируют каждую пачку и
 * заявляют, что вот они, вот их коды, и лежат они здесь.
 *
 * Заявление это проверяемое, и проверяется оно одним: кодов не может стать
 * больше, чем упаковок на полке. Иначе «маркировка остатка» превращается в
 * способ завести коды из воздуха — а по ним потом продают.
 */

export type StockCodesResult =
  | { ok: true; codes: MarkedCode[] }
  | { ok: false; message: string };

export function resolveStockCodes(input: {
  productId: string;
  /** Что поднесли сканером. */
  codes: string[];
  /** Сколько упаковок этого товара лежит на этой точке. */
  onHand: number;
  /** Сколько из них уже имеют код. */
  alreadyCoded: number;
  /** Серийники, уже известные этой компании, — среди поднесённых. */
  knownSerials: string[];
}): StockCodesResult {
  if (input.codes.length === 0) {
    return { ok: false, message: 'Отсканируйте коды упаковок, которые лежат на полке' };
  }

  // Количеством считается само число поднесённых кодов: человек заявляет
  // столько упаковок, сколько отсканировал, а не отдельно названное число.
  const read = readLineCodes({ productId: input.productId, codes: input.codes }, input.codes.length);
  if (!read.ok) return { ok: false, message: markingRefusalMessage(read.refusal) };

  const duplicate = findDuplicate(read.value);
  if (duplicate) {
    return { ok: false, message: 'Один и тот же код поднесён дважды — каждая упаковка сканируется один раз' };
  }

  /* Код, который уже где-то есть, здесь заводить нельзя.
     Он либо лежит на другой точке, либо продан, либо списан — и в каждом из
     этих случаев «зарегистрировать его как остаток здесь» значит завести вторую
     жизнь одной упаковке. */
  if (input.knownSerials.length > 0) {
    return {
      ok: false,
      message: 'Этот код уже заведён — упаковка либо принята раньше, либо продана',
    };
  }

  /* Больше, чем лежит на полке, промаркировать нельзя.
     Без этой границы маркировка остатка становится способом завести коды из
     воздуха: сорок пачек на полке и шестьдесят кодов — это двадцать упаковок,
     которых нет, и продавать их будут по настоящим с виду кодам. */
  const room = input.onHand - input.alreadyCoded;
  if (read.value.length > room) {
    return {
      ok: false,
      message: `На полке ${input.onHand}, из них уже с кодом ${input.alreadyCoded} — промаркировать можно не больше ${Math.max(room, 0)}`,
    };
  }

  return { ok: true, codes: read.value };
}
