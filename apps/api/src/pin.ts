import { createHmac, hkdfSync, timingSafeEqual } from 'node:crypto';
import { requireSecret } from './secrets';

/**
 * PIN кассира не лежит в базе тем, что кассир набирает.
 *
 * Модель данных в `docs/PRODUCT_READINESS.md` обещала «PIN-хэш» с первого дня.
 * В базе лежали сами цифры: `select "posPin" from users` возвращал `1111`,
 * `2223`, `5679` — все PIN-ы всех магазинов платформы, читаемые глазами.
 *
 * Цена такой строки не в том, что PIN — пароль. Он не пароль: четыре цифры,
 * набираемые на виду у очереди. Цена в том, что PIN — **единственный** ключ к
 * кассе, и по нему продают, возвращают, списывают товар и открывают отчёты
 * владельца. Одна утёкшая выгрузка базы — и это есть у всех, без подбора, без
 * следов и сразу для всей платформы.
 *
 * Обычный `bcrypt` здесь помог бы мало и сломал бы нужное. Мало — потому что
 * четыре цифры перебираются за мгновение, и соль от этого не спасает. Сломал бы
 * — потому что PIN на платформе уникален (`@unique` на колонке, вход идёт без
 * выбора компании), а две bcrypt-строки от одного PIN-а разные, и уникальность
 * перестала бы работать вовсе.
 *
 * Поэтому — HMAC с общим секретом: одно и то же значение для одного PIN-а, так
 * что `@unique` работает как раньше, и бесполезное без секрета, которого в
 * выгрузке базы нет. Перебор упирается не в четыре цифры, а в сам секрет.
 */

/** Сколько цифр может быть в PIN-е. Отпечаток заведомо длиннее и из hex. */
const FINGERPRINT_LENGTH = 64;

let cached: Buffer | null = null;

/**
 * Секрет, которым подписывается PIN.
 *
 * `POS_PIN_PEPPER`, если задан. Если нет — выводится из `JWT_SECRET`, который и
 * так обязателен и живёт там же, в секретах Railway.
 *
 * Вывод, а не четвёртый обязательный секрет, — чтобы выкладка этой правки
 * ничего не уронила и ничего не требовала руками. Забытая переменная у секрета,
 * без которого сервер не стартует, — это остановленная торговля в магазине, и
 * менять ею плохое хранение PIN-а на гарантированный простой не стоит.
 *
 * Плата за вывод одна, и она записана в `PRODUCTION_RUNBOOK`: смена
 * `JWT_SECRET` меняет и подпись PIN-ов, то есть после ротации PIN-ы придётся
 * выдать заново. Чтобы этого избежать, `POS_PIN_PEPPER` задают **до** ротации —
 * тогда подпись от неё не зависит.
 */
function pepper(): Buffer {
  if (cached) return cached;
  const explicit = process.env.POS_PIN_PEPPER;
  if (explicit && explicit.trim()) {
    cached = Buffer.from(explicit.trim(), 'utf8');
    return cached;
  }
  // Отдельная соль и назначение: из одного и того же JWT_SECRET получаются
  // разные ключи для разных целей, и подпись PIN-а не совпадает с подписью
  // токена ни при каких обстоятельствах.
  cached = Buffer.from(
    hkdfSync('sha256', Buffer.from(requireSecret('JWT_SECRET'), 'utf8'), Buffer.from('anyq-pos-pin'), Buffer.from('pin-fingerprint'), 32),
  );
  return cached;
}

/** Только для тестов: сбросить запомненный секрет после подмены переменной. */
export function forgetPepper(): void {
  cached = null;
}

/** То, что кладётся в базу вместо PIN-а. Одинаковое для одного PIN-а — уникальность жива. */
export function pinFingerprint(pin: string): string {
  return createHmac('sha256', pepper()).update(pin, 'utf8').digest('hex');
}

/**
 * Отличает отпечаток от PIN-а, записанного до этой правки.
 *
 * Нужно ровно затем, чтобы вход умел принять старое значение один раз и тут же
 * заменить его отпечатком: иначе выкладка оставила бы без входа всех, кто уже
 * работает, а «выдайте всем PIN-ы заново» — это магазин, который утром не
 * открылся.
 */
export function looksLikeFingerprint(stored: string): boolean {
  return stored.length === FINGERPRINT_LENGTH && /^[0-9a-f]+$/.test(stored);
}

/**
 * Фильтр «этот PIN уже занят» — по обоим видам записи сразу.
 *
 * Пока в базе есть PIN-ы, записанные до подписи, проверять занятость только по
 * отпечатку нельзя. Иначе так: у кассира A лежат цифры `1234`, владелец другой
 * компании заводит себе `1234`, проверка ищет отпечаток, старого A не видит и
 * разрешает. Дальше A приходит утром, вход находит его по цифрам и пытается
 * заменить их отпечатком — а отпечаток уже занят. Уникальность в базе честная,
 * поэтому запись падает, и падает она на кассире, который ничего не делал.
 *
 * Убирается вместе с самой веткой перехода, когда цифр в колонке не останется.
 */
export function pinTakenBy(pin: string): { posPin: string }[] {
  return [{ posPin: pinFingerprint(pin) }, { posPin: pin }];
}

/** Сравнение отпечатков без зависимости времени от совпавших символов. */
export function sameFingerprint(a: string, b: string): boolean {
  if (a.length !== b.length) return false;
  return timingSafeEqual(Buffer.from(a, 'utf8'), Buffer.from(b, 'utf8'));
}
