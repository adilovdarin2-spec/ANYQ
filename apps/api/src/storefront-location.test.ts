import { describe, it, expect } from 'vitest';
import { storefrontLocation } from './routes/supply';

/**
 * С какой точки витрина продаёт.
 *
 * Было — «первая по списку», а список отсортирован по названию. Оптовик с
 * двумя точками, «Магазин» и «Склад», торговал на витрине остатками магазина:
 * «М» раньше «С». Бронь под заказ вставала туда же, а отгружали со склада.
 * Переименование точки меняло то, чем торгует витрина, и нигде об этом не
 * было сказано ни слова.
 *
 * Угадывать по типу точки («витрина — значит склад») — хуже: у компании,
 * которая держит товар в магазине и завела пустой склад, витрина молча
 * опустела бы. Поэтому выбирает владелец, а пустое значение означает ровно
 * прежнее поведение: ни у одной заведённой компании ничего не меняется.
 */

const точка = (id: string, name: string) => ({ id, name });

describe('точка витрины', () => {
  it('без выбора — первая по списку, как было всегда', () => {
    const выбрана = storefrontLocation([точка('l1', 'Магазин'), точка('l2', 'Склад')]);
    expect(выбрана?.name).toBe('Магазин');
  });

  it('выбранная владельцем выигрывает', () => {
    const выбрана = storefrontLocation([точка('l1', 'Магазин'), точка('l2', 'Склад')], 'l2');
    expect(выбрана?.name).toBe('Склад');
  });

  it('выбранная и удалённая точка не ломает витрину', () => {
    // Точку могли удалить после выбора. Витрина обязана продолжать работать —
    // так же, как работала до появления этой настройки.
    const выбрана = storefrontLocation([точка('l1', 'Магазин')], 'удалённая');
    expect(выбрана?.name).toBe('Магазин');
  });

  it('одна точка — она и есть', () => {
    expect(storefrontLocation([точка('l1', 'Магазин')])?.name).toBe('Магазин');
  });

  it('точек нет вовсе — витрина об этом и говорит', () => {
    expect(storefrontLocation([])).toBeUndefined();
  });
});
