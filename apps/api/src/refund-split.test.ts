import { describe, it, expect } from 'vitest';
import { refundSplit, cashPortion } from './payments';
import type { PaymentLine } from './payments';

/**
 * Возврат раскладывается теми же способами, какими чек был оплачен.
 *
 * Сверка смены считает приход по частям чека и расход — тоже по частям. До
 * 25.09.2026 расход считался целиком: чек на 400, где 200 наличными и 200
 * картой, при полном возврате вычитал из ящика все 400. Кассир, отдавший
 * наличными только наличную половину, закрывал смену с излишком в 200.
 *
 * Излишек кассир объяснить не может, недостачу — оплачивает. И то и другое
 * система придумала бы сама, а это худший род неверного числа, какой она может
 * выдать: ему верят.
 */

const пополам: PaymentLine[] = [
  { method: 'cash', amount: 200 },
  { method: 'card', amount: 200 },
];

describe('разложить возврат по способам чека', () => {
  it('половину чека возвращает половиной каждой части', () => {
    expect(refundSplit(пополам, 400)).toEqual([
      { method: 'cash', amount: 200 },
      { method: 'card', amount: 200 },
    ]);
    expect(refundSplit(пополам, 200)).toEqual([
      { method: 'cash', amount: 100 },
      { method: 'card', amount: 100 },
    ]);
  });

  it('и в ящик уходит только наличная часть', () => {
    // Ради чего всё: это то самое число, на которое сверка уменьшает ящик.
    expect(cashPortion(refundSplit(пополам, 400))).toBe(200);
  });

  it('части всегда складываются ровно в сумму возврата', () => {
    /* Округление по частям не обязано сойтись само. Разойдётся — ящик и журнал
       разойдутся тихо, на тенге, и объяснить это будет нечем. Проверяется на
       неудобных долях и на каждой сумме подряд, а не на одной подобранной. */
    const неровно: PaymentLine[] = [
      { method: 'cash', amount: 333 },
      { method: 'card', amount: 333 },
      { method: 'kaspi', amount: 334 },
    ];
    for (let refund = 1; refund <= 1000; refund++) {
      const части = refundSplit(неровно, refund);
      const сумма = части.reduce((s, l) => s + l.amount, 0);
      expect(сумма, `возврат ${refund}`).toBe(refund);
      expect(части.every((l) => l.amount > 0), `возврат ${refund}`).toBe(true);
    }
  });

  it('остаток от округления не сваливается на наличные', () => {
    // Иначе правило «складывается ровно» чинило бы сумму, смещая ящик.
    const крупнаяКарта: PaymentLine[] = [
      { method: 'cash', amount: 1 },
      { method: 'card', amount: 999 },
    ];
    const части = refundSplit(крупнаяКарта, 333);
    expect(части.reduce((s, l) => s + l.amount, 0)).toBe(333);
    // Наличная доля — 1/1000 от 333, то есть ноль после округления; строки с
    // нулём не остаётся вовсе, и в ящик не уходит ничего.
    expect(cashPortion(части)).toBe(0);
  });

  it('чек с одним способом — это разбивка из одного', () => {
    expect(refundSplit([{ method: 'cash', amount: 500 }], 300)).toEqual([{ method: 'cash', amount: 300 }]);
  });

  it('а делить нечего — молчит, и зовущий подставляет способ сам', () => {
    // Строка, написанная до появления разбивки, и чек на ноль.
    expect(refundSplit([], 400)).toEqual([]);
    expect(refundSplit([{ method: 'cash', amount: 0 }], 400)).toEqual([]);
    expect(refundSplit(пополам, 0)).toEqual([]);
  });
});
