/**
 * Лимиты тарифа — те, что до сих пор были только числом в карточке.
 *
 * В тарифе есть «лимит точек», «лимит пользователей» и «лимит SKU»: они
 * хранятся, показываются в админке и правятся там же — и не значат ничего.
 * Демо-компании заведены с лимитами (одна точка, пять человек, две тысячи
 * товаров), то есть так и задумывалось. Ничего из этого не проверялось при
 * создании, поэтому уровни тарифа были украшением: компания на «Базовой»
 * получала столько же, сколько на «Персональном менеджере».
 *
 * Три правила, которые делают это честным:
 *
 * **Пусто — значит без ограничения.** Колонки нullable, и `null` читается
 * буквально. Молчаливое «ну наверное десять» превратило бы отсутствие решения
 * в решение.
 *
 * **Проверяется только создание.** Компания, оказавшаяся сверх лимита — потому
 * что лимит опустили после, — продолжает работать: продавать, принимать,
 * считать. Отказ на продаже был бы остановленным магазином, а это никогда не
 * стоит того, о чём здесь речь.
 *
 * **В отказе стоит число и то, что с ним делать.** «Превышен лимит» — это
 * тупик; «тариф допускает 3 точки, лимит поднимает менеджер» — это следующий
 * шаг.
 */

/** Русский счёт: 1 точка, 2 точки, 5 точек. */
function plural(count: number, one: string, few: string, many: string): string {
  const mod10 = Math.abs(count) % 10;
  const mod100 = Math.abs(count) % 100;
  if (mod10 === 1 && mod100 !== 11) return one;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few;
  return many;
}

export type LimitKind = 'locations' | 'users' | 'products';

const NOUN: Record<LimitKind, (n: number) => string> = {
  locations: (n) => plural(n, 'точку', 'точки', 'точек'),
  users: (n) => plural(n, 'сотрудника', 'сотрудников', 'сотрудников'),
  products: (n) => plural(n, 'товар', 'товара', 'товаров'),
};

/**
 * Можно ли создать ещё `adding` штук — и если нет, что сказать.
 *
 * Возвращает готовую фразу, а не флаг: место, которое решает «нельзя», и
 * место, которое объясняет почему, должны быть одним местом, иначе второе рано
 * или поздно отстанет от первого.
 *
 * Форма фразы постоянная — «Тариф допускает N штук — сейчас M[, добавляется
 * K]. Поднять лимит может менеджер ANYQ.» — и это не украшение: касса
 * переводит ответы сервера, узнавая их по тексту, и разнобой означал бы
 * сообщение, которое на казахском останется русским.
 */
export function limitRefusal(
  kind: LimitKind,
  limit: number | null | undefined,
  current: number,
  adding = 1,
): string | null {
  if (limit === null || limit === undefined) return null;
  // Ноль и отрицательное — не лимит, а незаполненное поле или опечатка.
  // Запирать компанию наглухо по такому значению нельзя.
  if (!Number.isFinite(limit) || limit <= 0) return null;
  if (current + adding <= limit) return null;

  const сколько = `${limit} ${NOUN[kind](limit)}`;
  const сейчас = adding > 1 ? `сейчас ${current}, добавляется ${adding}` : `сейчас ${current}`;
  return `Тариф допускает ${сколько} — ${сейчас}. Поднять лимит может менеджер ANYQ.`;
}
