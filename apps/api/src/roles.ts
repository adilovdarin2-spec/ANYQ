/**
 * Кто что может делать со складом.
 *
 * У ролей до сих пор было ровно два состояния: «владелец или менеджер» — для
 * настроек, цен, устройств и сверки — и «любой вошедший» для всего остального.
 * Всё остальное — это списание, инвентаризация, перемещение между точками и
 * возврат поставщику, то есть все способы изменить остаток, не пробивая чек.
 *
 * Так не задумывалось. В описании продукта у кассира «продажа, возврат, смена,
 * очередь синхронизации. Никаких настроек», а у кладовщика — «получить,
 * разместить, собрать, переместить, пересчитать». Списания там нет ни у того,
 * ни у другого, и это не случайность: списание и пересчёт — единственные две
 * операции, которыми недостача превращается в норму задним числом. Именно их
 * в рознице и подписывает старший.
 *
 * Что эта проверка не делает: не мешает торговать. Продажа, возврат, открытие
 * и закрытие смены доступны любому, кто вошёл, — иначе роль превращается в
 * препятствие на пути очереди у кассы.
 */

export type Capability = 'receive' | 'moveStock' | 'count' | 'writeOff' | 'produce';

/**
 * Кому что доступно.
 *
 * Неизвестная роль не получает ничего: новая роль, о которой эта таблица ещё
 * не знает, должна упереться в отказ с понятным текстом, а не получить права
 * владельца по умолчанию.
 */
const BY_ROLE: Record<string, Capability[]> = {
  owner: ['receive', 'moveStock', 'count', 'writeOff', 'produce'],
  manager: ['receive', 'moveStock', 'count', 'writeOff', 'produce'],
  // Кладовщик: получить, разместить, собрать, переместить, пересчитать.
  // Списания нет намеренно — см. выше.
  warehouse_staff: ['receive', 'moveStock', 'count', 'produce'],
  cashier: [],
  pharmacist: [],
};

/**
 * Текст отказа — с именами тех, к кому идти.
 *
 * «Недостаточно прав» — тупик: человек стоит перед задачей, которую ему
 * поручили, и не знает, кого звать. Здесь сказано, кого.
 */
const REFUSALS: Record<Capability, string> = {
  receive: 'Приёмку проводит владелец, менеджер или кладовщик',
  moveStock: 'Перемещение товара проводит владелец, менеджер или кладовщик',
  count: 'Инвентаризацию проводит владелец, менеджер или кладовщик',
  writeOff: 'Списание проводит владелец или менеджер',
  produce: 'Производство проводит владелец, менеджер или кладовщик',
};

export function can(role: string | null | undefined, capability: Capability): boolean {
  if (!role) return false;
  return (BY_ROLE[role] ?? []).includes(capability);
}

/** Отказ словами, либо `null`, если можно. */
export function capabilityRefusal(role: string | null | undefined, capability: Capability): string | null {
  return can(role, capability) ? null : REFUSALS[capability];
}

/**
 * Всё, что эта роль может, — одним списком.
 *
 * Отдаётся кассе при входе, чтобы экран не предлагал того, что сервер потом
 * отклонит. Список считает сервер, а не касса: две копии одной таблицы прав
 * расходятся ровно в тот день, когда одну из них поправят, и разойдутся они в
 * сторону «на экране есть, а делать нельзя».
 */
export function capabilitiesOf(role: string | null | undefined): Capability[] {
  if (!role) return [];
  return [...(BY_ROLE[role] ?? [])];
}
