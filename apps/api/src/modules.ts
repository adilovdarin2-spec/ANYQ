/**
 * Какие модули вообще бывают.
 *
 * Список проверяется здесь, потому что модуль — это не подпись в карточке, а
 * строка, по которой касса и сервер решают, показывать ли скидки, склад,
 * витрину заказов. Строка, которой нет в этом списке, не включает ничего и
 * никогда не включит: она просто лежит в тарифе и выглядит как включённый
 * модуль.
 *
 * Так и случилось с «shop». Он предлагался в админке, стоял по умолчанию у
 * каждой новой компании — и не проверялся ни одной строкой кода. Магазин,
 * заведённый обычным способом, получал кассу без скидок, без лояльности и без
 * весового товара, а в карточке было написано «Магазин». Опечатка в названии
 * модуля выглядела бы точно так же, и найти её можно было только чтением
 * JSON-а в базе.
 */
export const KNOWN_MODULES = [
  'retail',
  'stock',
  'warehouse',
  'terminal',
  'supply',
  'pharmacy',
  'restaurant',
] as const;

/**
 * Почему «склад» — это два модуля, а не один.
 *
 * До 15.09.2026 `warehouse` открывал всё сразу: и приёмку с инвентаризацией, и
 * ячейки с перемещениями и закупками. Из-за этого не существовало тарифа для
 * обычного магазина: магазин без приёмки не работает — товар приходит, и
 * остаток обязан подняться, — а включить приёмку значило отдать заодно
 * адресное хранение, перемещения между точками, заказы поставщику и
 * производство. То есть весь склад целиком, бесплатно, вместе с кассой.
 *
 * Граница проходит там же, где она проходит в голове у владельца:
 *
 *   `stock` — товар приходит и уходит. Приёмка, инвентаризация, списание,
 *             карантин, возврат поставщику. Это нужно любому магазину.
 *   `warehouse` — товар лежит в разных местах, и его надо находить и двигать.
 *             Ячейки, пересчёт по ячейкам, перемещения между точками, заказы
 *             поставщику с частичной поставкой, цены поставщиков, производство.
 *
 * Склад без учёта прихода бессмыслен, поэтому `warehouse` без `stock` не
 * принимается — см. `moduleListRefusal`. Обратное осмысленно: магазин с одной
 * точкой и без ячеек.
 */
export const WAREHOUSE_REQUIRES: readonly string[] = ['stock'];

/**
 * Модули, которые без другого модуля не работают.
 *
 * Здесь их два, и попали они сюда по разным причинам.
 *
 * `warehouse` — потому что ячейки без приёмки некуда наполнить.
 *
 * `pharmacy` — потому что он сам создаёт то, что убрать умеет только `stock`.
 * Аптечный модуль делает ровно одно полезное дело: не даёт продать
 * просроченное. Но остановленный товар не исчезает — он остаётся на полке и в
 * остатке, и списать его может только списание, а списание живёт в `stock`.
 * Тариф `pharmacy` без `stock` проверен вживую 15.09.2026: 8 просроченных
 * ибупрофена и 12 упаковок угля нельзя ни продать, ни списать, ни пересчитать,
 * ни вернуть поставщику. Остаток, из которого нет выхода, — это не
 * ограничение тарифа, а испорченная книга.
 */
export const MODULE_REQUIRES: Readonly<Record<string, readonly string[]>> = {
  warehouse: WAREHOUSE_REQUIRES,
  pharmacy: ['stock'],
};

/**
 * Отказ целиком, а не собранный из кусков.
 *
 * Собрать его шаблоном было бы короче и ровно поэтому неправильно: эти строки
 * переводятся на казахский по самому тексту (`apps/pos/src/i18n`), а фраза,
 * склеенная из половин, не переводится — порядок слов в казахском не русский,
 * и половина отдельно не значит ничего. Поэтому каждый модуль называет свою
 * причину целой фразой.
 *
 * Цена этого — зависимость записана дважды: списком в `MODULE_REQUIRES` и
 * словами здесь. Расходиться им не даёт тест: он читает список и требует,
 * чтобы отказ называл каждую зависимость по имени.
 */
const REQUIREMENT_REFUSAL: Readonly<Record<string, string>> = {
  warehouse: 'Модуль «warehouse» не работает без «stock»: приёмка и инвентаризация живут там',
  pharmacy: 'Модуль «pharmacy» не работает без «stock»: просроченную партию нужно чем-то списывать, а списание живёт там',
};

/**
 * Модули, которые больше не продают, но которые у кого-то записаны.
 *
 * Принимаются на запись: иначе карточку такой компании нельзя было бы
 * сохранить, не сняв модуль, — а снять его и значит сохранить карточку.
 */
export const LEGACY_MODULES = ['shop'] as const;

export type KnownModule = (typeof KNOWN_MODULES)[number];

const ACCEPTED = new Set<string>([...KNOWN_MODULES, ...LEGACY_MODULES]);

/**
 * Что не так со списком модулей — словами, или `null`, если всё в порядке.
 *
 * Отказ называет и то, чего не бывает, и то, что бывает: тот, кто ошибся в
 * названии, должен увидеть правильное, а не «некорректные данные».
 */
export function moduleListRefusal(value: unknown): string | null {
  if (value === undefined || value === null) return null;
  if (!Array.isArray(value)) return 'Модули передаются списком';

  const unknown = value.filter((item) => typeof item !== 'string' || !ACCEPTED.has(item));
  if (unknown.length > 0) {
    const named = unknown.map((item) => (typeof item === 'string' ? `«${item}»` : 'пустое значение')).join(', ');
    return `Таких модулей нет: ${named}. Доступны: ${KNOWN_MODULES.join(', ')}`;
  }

  // Отказ здесь, а не молчаливое добавление недостающего: тариф должен
  // говорить правду о том, что в нём включено, иначе галочка снова начнёт
  // означать не то, что написано.
  for (const [module, requires] of Object.entries(MODULE_REQUIRES)) {
    if (!value.includes(module)) continue;
    if (requires.every((m) => value.includes(m))) continue;
    return REQUIREMENT_REFUSAL[module];
  }

  return null;
}
