/**
 * В какой ящик легли деньги, прошедшие мимо чека.
 *
 * Возврат и расчёт с контрагентом — это наличные, вынутые из ящика или
 * положенные в него, и сверка смены обязана их ждать. Ссылку на смену касса
 * прислать не может: возврат оформляют и с устройства, где смены нет вовсе, —
 * владелец со своего телефона, пока за кассой стоит кассир. Поэтому её выбирает
 * сервер.
 *
 * Правило: сначала своя открытая смена, потом единственная открытая на точке.
 * Если открытых несколько и ни одна не твоя — пусто: у каждой кассы свой ящик,
 * и угадывать, в какой из них положили деньги, не по чему.
 *
 * **Своих открытых смен бывает две.** Это не сбой и не редкость: кассир забыл
 * закрыть вчерашнюю, ушёл, утром открыл новую — ровно тот случай, ради которого
 * две открытые смены на точке и разрешены. Оба маршрута выбирали из них первую
 * попавшуюся: `findMany` без сортировки отдаёт строки в порядке, который решает
 * база. Возврат в 198 ₸, выданный сегодня, лёг в ящик позавчерашней смены — у
 * сегодняшнего кассира недостача ровно на эту сумму, у позавчерашней смены
 * излишек. Недостачу кассир оплачивает.
 *
 * Правильный ответ известен и записан в этом же файле двумя функциями ниже по
 * коду (`resolveUnlinkedShift`): «открытая последней и есть тот планшет, за
 * которым человек стоит». Здесь он теперь тот же.
 *
 * Найдено 30.09.2026 вторым прогоном дня магазина: касса показала на закрытии
 * на 198 ₸ больше, чем лежало в ящике.
 */
export interface OpenShiftRow {
  id: string;
  userId: string | null;
  openedAt: Date;
}

export function drawerShiftFor(openHere: OpenShiftRow[], userId: string | null): string | null {
  const mine = openHere.filter((shift) => shift.userId && shift.userId === userId);
  if (mine.length > 0) {
    /* Та же сортировка, что у разбора записей без ссылки: открытая последней
       первой, при равном времени — меньший id. Одинаковый выбор в обоих местах
       важнее «правильного»: разошедшись, они дали бы пару чисел про один ящик,
       которую никто не сможет объяснить. */
    const sorted = [...mine].sort(
      (a, b) => b.openedAt.getTime() - a.openedAt.getTime() || a.id.localeCompare(b.id),
    );
    return sorted[0].id;
  }
  return openHere.length === 1 ? openHere[0].id : null;
}
