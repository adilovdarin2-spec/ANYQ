import { describe, it, expect } from 'vitest';
import { receiptDayWindow } from './receipt-day';
import { localDay } from './kz-time';

/**
 * Найти чек недельной давности.
 *
 * Список для возврата отдавал последние пятьдесят чеков и ничего больше — в
 * продуктовом это до обеда. Покупатель, пришедший через неделю, своего чека в
 * списке не находил, и сделать с этим было нечего.
 *
 * Границы дня — местные. Вечерний чек в 21:00 по Алматы в UTC уже следующего
 * дня: окно по UTC отдало бы его «завтрашним», и кассир, ищущий вчерашний
 * вечер, не нашёл бы ровно те чеки, которые и приносят обратно.
 *
 * Найдено 30.09.2026 при разборе пункта плана про возврат по старому чеку.
 */

describe('окно одного дня магазина', () => {
  it('начинается в местную полночь, а не в UTC', () => {
    const window = receiptDayWindow('2026-09-23')!;
    expect(window.gte.toISOString()).toBe('2026-09-22T19:00:00.000Z');
    expect(window.lt.toISOString()).toBe('2026-09-23T19:00:00.000Z');
  });

  it('и вмещает ровно двадцать четыре часа', () => {
    const window = receiptDayWindow('2026-09-23')!;
    expect(window.lt.getTime() - window.gte.getTime()).toBe(24 * 60 * 60 * 1000);
  });

  it('вечерний чек попадает в свой день, а не в следующий', () => {
    /* 21:00 в магазине — это 16:00 UTC того же дня, но чек, пробитый в 23:30,
       в UTC уже завтрашний. Оба должны найтись за «двадцать третье». */
    const window = receiptDayWindow('2026-09-23')!;
    for (const местное of ['2026-09-23T00:05', '2026-09-23T21:00', '2026-09-23T23:59']) {
      const utc = new Date(new Date(`${местное}:00.000Z`).getTime() - 5 * 60 * 60 * 1000);
      expect(localDay(utc), `${местное}: разошлось с localDay`).toBe('2026-09-23');
      expect(utc >= window.gte && utc < window.lt, `${местное} не попал в своё окно`).toBe(true);
    }
  });

  it('и чек соседнего дня в него не попадает', () => {
    const window = receiptDayWindow('2026-09-23')!;
    const заПолночь = new Date('2026-09-23T19:00:00.000Z'); // 00:00 двадцать четвёртого
    expect(заПолночь >= window.lt).toBe(true);
  });

  it('согласовано с тем, какой день считает магазин', () => {
    // Свойством: любой момент внутри окна должен называться тем же днём.
    for (const day of ['2026-01-01', '2026-06-15', '2026-12-31']) {
      const window = receiptDayWindow(day)!;
      for (const доля of [0, 0.25, 0.5, 0.99]) {
        const at = new Date(window.gte.getTime() + доля * (window.lt.getTime() - window.gte.getTime()));
        expect(localDay(at), `${day} + ${доля}`).toBe(day);
      }
    }
  });

  it('мусор и пустоту отбрасывает, а не угадывает', () => {
    // Иначе кассир получил бы пустой список вместо привычных последних чеков.
    for (const bad of [undefined, null, '', 'вчера', '23.09.2026', '2026-9-3', 42, {}]) {
      expect(receiptDayWindow(bad as unknown)).toBeNull();
    }
  });
});
