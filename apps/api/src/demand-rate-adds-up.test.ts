import { describe, it, expect } from 'vitest';
import { buildDailyClosingBalances, estimateDailyDemand } from './replenishment';
import type { DailyMovement } from './replenishment';

/**
 * Скорость продаж складывается из двух чисел, и они сходятся.
 *
 * Автозаказ показывал одно: «продаёте 2,9 в день, запаса на 4 дн., заказать
 * 40». Проверить это число владелец не мог ничем — а по нему он решает, везти
 * сорок штук или сто.
 *
 * Теперь рядом стоит «продано ÷ дней на полке», и деление обязано давать
 * скорость **в точности**. Иначе строка не помогает, а опровергает: владелец
 * делит, получает не то, что в шапке, и перестаёт верить обоим числам.
 *
 * Держится это на том, что числитель — проданное в дни на полке
 * (`soldInStock`), а не итог за окно. Итог за окно считает и возврат,
 * принесённый в день, когда полка стояла пустой: такой день в знаменатель не
 * попадает, и деление разошлось бы молча — на том самом экране, по которому
 * тратят деньги.
 */

const продажа = (dayIndex: number, quantity: number): DailyMovement => ({ dayIndex, quantity: -quantity });
const возврат = (dayIndex: number, quantity: number): DailyMovement => ({ dayIndex, quantity });
const всёСчитается = () => true;

function оценка(остаток: number, движения: DailyMovement[], окно: number) {
  return estimateDailyDemand(buildDailyClosingBalances(остаток, движения, окно), движения, всёСчитается);
}

describe('продано ÷ дней на полке', () => {
  it('даёт скорость на обычном товаре', () => {
    const d = оценка(12, [продажа(0, 3), продажа(1, 3), продажа(2, 3)], 7);
    expect(d.soldInStock / d.daysInStock).toBe(d.perDay);
  });

  it('и когда товар кончался посреди окна', () => {
    /* Самое место, ради которого знаменатель вообще считают: делить на всё окно
       — значит занижать спрос ровно тем товарам, которые кончаются. */
    const d = оценка(0, [продажа(5, 10), продажа(4, 10)], 10);
    expect(d.soldInStock / d.daysInStock).toBe(d.perDay);
    expect(d.daysOutOfStock).toBeGreaterThan(0);
  });

  it('и когда возврат пришёл в день с пустой полкой', () => {
    /* Тот самый случай, ради которого числитель отделён от итога за окно.
       Возврат в день без остатка в знаменатель не попадает — и не должен
       попадать в числитель. */
    const d = оценка(0, [продажа(9, 8), возврат(3, 2)], 10);
    expect(d.soldInStock / d.daysInStock).toBe(d.perDay);
    expect(d.soldInWindow).not.toBe(d.soldInStock);
  });

  it('и на товаре, которого на полке не было ни дня', () => {
    const d = оценка(0, [], 10);
    expect(d.perDay).toBeNull();
    expect(d.daysInStock).toBe(0);
    expect(d.soldInStock).toBe(0);
  });

  it('и на любом наборе движений подряд', () => {
    /* Свойством, а не подобранным примером: строка на экране обязана сходиться
       на всех товарах, а не на тех, что попали в тест. */
    for (let остаток = 0; остаток <= 30; остаток += 7) {
      for (let сколько = 1; сколько <= 9; сколько += 2) {
        for (const день of [0, 3, 6]) {
          const d = оценка(остаток, [продажа(день, сколько), продажа(день + 1, сколько + 1), возврат(день + 2, 1)], 10);
          if (d.perDay === null) continue;
          expect(d.soldInStock / d.daysInStock, `${остаток}/${сколько}/${день}`).toBe(d.perDay);
        }
      }
    }
  });

  it('и числитель никогда не уходит в минус', () => {
    // Отрицательное «продано» рядом с рекомендацией — это не число, а опечатка.
    const d = оценка(5, [возврат(0, 4), возврат(1, 3)], 5);
    expect(d.soldInStock).toBeGreaterThanOrEqual(0);
  });
});
