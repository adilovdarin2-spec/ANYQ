import { UNKNOWN_DEVICE_LABEL } from './devices';

/**
 * Какая это касса.
 *
 * Магазин с двумя кассами на входе говорит номерами: «пробей на второй», «в
 * первой не сходится ящик», «сменный отчёт с какой кассы». В базе до
 * 15.09.2026 номеров не было — были «Windows · Chrome» и «Android · Chrome»,
 * угаданные по браузеру, то есть два одинаковых планшета давали две
 * неразличимые строки, и владелец, выключающий украденный, выключал наугад.
 *
 * Здесь только счёт и название. Всё, что про доступ, — в маршрутах.
 */

/** Как касса называется, пока её не переименовали. */
export function registerName(number: number): string {
  return `Касса №${number}`;
}

/**
 * Как касса называется, пока её не переименовали, — целиком.
 *
 * Сначала номер, потом чем она работает: «Касса №2 · Android». Номер — то,
 * чем касса зовётся в зале, и он идёт первым. Планшет приписан не для
 * полноты: владелец, ищущий украденное устройство, читает список из
 * одинаковых строк, и «Android» рядом с номером — единственное, что отличает
 * две кассы, купленные в один день.
 *
 * Если браузер ничего внятного о себе не сказал, приписки нет: «Касса №2 ·
 * Устройство» не говорит ничего и мешает читать.
 */
export function initialRegisterLabel(number: number, deviceHint: string | null | undefined): string {
  const name = registerName(number);
  if (!deviceHint || deviceHint === UNKNOWN_DEVICE_LABEL) return name;
  return `${name} · ${deviceHint}`;
}

/**
 * Номер для новой кассы.
 *
 * Максимум плюс один, а не первая дырка. Сменный отчёт подписан номером, и
 * если номер выключенной второй кассы достанется завтра новому планшету,
 * вчерашний отчёт станет непроверяемым — две разные кассы под одним именем в
 * одной книге.
 *
 * Работает это ровно постольку, поскольку кассу выключают, а не удаляют:
 * выключенная строка остаётся в списке и держит свой номер за собой. Маршрута
 * удаления нет и не должно появиться — строка, вычищенная из базы, номер
 * вернёт, и вот тогда две кассы под номером 2 в одной книге и сойдутся.
 *
 * Отсюда и цена: номера растут, и у магазина, сменившего пять планшетов,
 * шестой будет «Касса №6» при двух рабочих местах. Это неудобно ровно один
 * раз — при переименовании, — и честно всегда.
 */
export function nextRegisterNumber(taken: readonly number[]): number {
  let highest = 0;
  for (const number of taken) {
    if (Number.isFinite(number) && number > highest) highest = Math.floor(number);
  }
  return highest + 1;
}

/**
 * Можно ли этому устройству занять чужой номер — и если нет, почему.
 *
 * Занять можно только живую кассу своей компании. Выключенную — нельзя:
 * владелец выключил её, чтобы украденный планшет не вернулся, и «войди и
 * назовись второй кассой» было бы обходом ровно этого запрета.
 */
export function claimRefusal(
  register: { companyId: string; revokedAt: Date | null } | null,
  companyId: string,
): string | null {
  if (!register || register.companyId !== companyId) return 'Касса не найдена';
  if (register.revokedAt) return 'Эта касса отключена — обратитесь к владельцу';
  return null;
}
