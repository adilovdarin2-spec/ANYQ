/**
 * Штрихкод из чужого файла.
 *
 * Каталог заводят выгрузкой из той программы, в которой магазин работал раньше,
 * и это первое, что новый владелец делает с ANYQ. Штрихкод из такого файла почти
 * никогда не бывает чистым: Excel добавляет апостроф, ставит пробелы по три
 * цифры, дописывает `.0` — или, хуже, показывает тринадцать цифр как
 * `4.87012E+12`.
 *
 * До 25.09.2026 всё это попадало в каталог дословно и без единого замечания.
 * Замерено на двенадцати видах мусора: ни один не был ни поправлен, ни назван.
 * Кассир сканирует пачку, касса отвечает «не найден», и объяснить это нечем —
 * импорт сказал, что всё хорошо.
 *
 * Здесь три разных случая, и путать их нельзя.
 *
 * **Косметика.** Апостроф, пробелы, дефисы, `.0` на конце. Цифры целы, и правка
 * очевидна: убрать и не беспокоить человека.
 *
 * **Потерянные цифры.** `4.87012E+12` — это не запись числа, а его остаток:
 * Excel сохранил шесть значащих цифр из тринадцати. Восстановить нельзя, и
 * догадаться тоже: `4870120000000` — не тот код, который на пачке. Такой
 * штрихкод надо отказать и сказать, что делать: отформатировать столбец как
 * текст и выгрузить заново.
 *
 * **Не сойдётся при сканировании.** Последняя цифра штрихкода — контрольная, и
 * сканер её проверяет. Код, у которого она не сходится, ни на одной пачке не
 * напечатан: значит в файле опечатка или обрезанная цифра. Товар при этом
 * настоящий, поэтому строку не отбрасываем — предупреждаем.
 */

export type BarcodeProblem =
  /** Excel превратил цифры в экспоненту; восстановить их нельзя. */
  | 'excel-notation'
  /** Контрольная цифра не сходится: сканер такой код не найдёт. */
  | 'check-digit';

export interface BarcodeReading {
  /** Что писать в каталог, или `null` — если штрихкода нет или он негоден. */
  barcode: string | null;
  problem: BarcodeProblem | null;
}

/** Длины, у которых есть контрольная цифра по правилам GS1. */
const CHECKED_LENGTHS = new Set([8, 12, 13, 14]);

/**
 * Сходится ли контрольная цифра.
 *
 * Правило GS1 одно на все длины: цифры слева от контрольной берутся справа
 * налево с весами 3 и 1 попеременно, начиная с 3; контрольная дополняет сумму
 * до кратной десяти.
 */
export function hasValidCheckDigit(code: string): boolean {
  if (!/^\d+$/.test(code) || !CHECKED_LENGTHS.has(code.length)) return false;
  const digits = code.split('').map(Number);
  const check = digits.pop()!;
  let sum = 0;
  // Справа налево: самая правая из оставшихся цифр весит 3.
  for (let i = digits.length - 1, weight = 3; i >= 0; i--, weight = weight === 3 ? 1 : 3) {
    sum += digits[i] * weight;
  }
  return (10 - (sum % 10)) % 10 === check;
}

/** Похоже ли это на число, которое Excel показал экспонентой. */
function looksLikeExcelNotation(raw: string): boolean {
  return /^\d+(?:[.,]\d+)?[eE][+-]?\d+$/.test(raw);
}

export function normaliseBarcode(raw: string): BarcodeReading {
  const trimmed = (raw ?? '').trim();
  if (!trimmed) return { barcode: null, problem: null };

  // До всякой чистки: в экспоненте и точка, и цифры — часть записи числа, а не
  // мусор, и вычистив их мы получили бы правдоподобный, но неверный код.
  if (looksLikeExcelNotation(trimmed)) return { barcode: null, problem: 'excel-notation' };

  const cleaned = trimmed
    // Апостроф Excel ставит сам, помечая «это текст, а не число».
    .replace(/^['`’]/, '')
    // Пробелы любого рода, включая неразрывный, и дефисы — это разделители для
    // глаза: на пачке их нет.
    .replace(/[\s ‑-]/g, '')
    // `.0` и точка на конце — след числового формата, а не часть кода.
    .replace(/[.,]0*$/, '');

  // Ноль и одни нули — это «штрихкода нет», записанное числом. Такой код не
  // ищут и не сканируют, а в каталоге он мешает: два товара с кодом «0»
  // выглядят как один и тот же.
  if (!cleaned || /^0+$/.test(cleaned)) return { barcode: null, problem: null };

  // Буквы допустимы: Code 128 их кодирует, и внутренний артикул магазина тоже
  // штрихкод, если он напечатан на полке. Контрольной цифры у такого кода нет,
  // и проверять её нечем — молчим.
  if (!/^\d+$/.test(cleaned)) return { barcode: cleaned, problem: null };

  if (CHECKED_LENGTHS.has(cleaned.length) && !hasValidCheckDigit(cleaned)) {
    return { barcode: cleaned, problem: 'check-digit' };
  }

  return { barcode: cleaned, problem: null };
}

/** Что сказать человеку про каждый случай. Словами про его файл, а не про код. */
export function barcodeProblemMessage(problem: BarcodeProblem, name: string, raw: string): string {
  if (problem === 'excel-notation') {
    return `«${name}»: Excel сохранил штрихкод как ${raw} — цифры потеряны, восстановить их нельзя. Отформатируйте столбец со штрихкодами как текст и выгрузите файл заново. Товар заведём без штрихкода.`;
  }
  return `«${name}»: в штрихкоде ${raw} не сходится контрольная цифра — сканер такой код не найдёт. Проверьте по пачке.`;
}
