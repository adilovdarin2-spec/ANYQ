import { describe, it, expect } from 'vitest';
import { buildImportPlan } from './import';

/**
 * Грязный штрихкод из выгрузки — от файла до каталога.
 *
 * Разбор проверен отдельно, в `barcode.test.ts`. Здесь — то, чего он доказать не
 * может: что импорт его зовёт, что замечание доезжает до человека с номером
 * строки, и что товар при негодном коде всё равно заводится.
 *
 * Замерено 25.09.2026 на двенадцати видах мусора: до этой правки все двенадцать
 * попадали в каталог дословно и ни одного замечания импорт не давал.
 */

const ЗАГОЛОВОК = ['Наименование', 'Штрихкод', 'Цена'];

const план = (строки: string[][]) => buildImportPlan([ЗАГОЛОВОК, ...строки], []);

describe('импорт и грязный штрихкод', () => {
  it('косметику чистит молча', () => {
    const p = план([['Чай', "'4006 3813 33931", '500']]);
    expect(p.rows[0].barcode).toBe('4006381333931');
    expect(p.problems, 'человека беспокоят из-за очевидной правки').toEqual([]);
    expect(p.skipped).toBe(0);
  });

  it('а про экспоненту говорит и заводит товар без штрихкода', () => {
    const p = план([['Чай «Асем»', '4.87012E+12', '500']]);
    expect(p.rows).toHaveLength(1);
    expect(p.rows[0].name).toBe('Чай «Асем»');
    expect(p.rows[0].barcode, 'правдоподобный, но неверный код хуже отсутствия').toBeNull();
    expect(p.skipped, 'товар потерян из-за штрихкода').toBe(0);

    expect(p.problems).toHaveLength(1);
    expect(p.problems[0].severity).toBe('error');
    expect(p.problems[0].line, 'без номера строки замечание бесполезно').toBe(2);
    expect(p.problems[0].message).toContain('4.87012E+12');
    expect(p.problems[0].message).toContain('как текст');
  });

  it('и про несходящуюся контрольную цифру — предупреждением, код оставляя', () => {
    const p = план([['Сигареты', '4006381333932', '1400']]);
    expect(p.rows[0].barcode).toBe('4006381333932');
    expect(p.problems).toHaveLength(1);
    expect(p.problems[0].severity, 'из-за опечатки в коде товар не отбрасывают').toBe('warning');
    expect(p.problems[0].message).toContain('сканер');
  });

  it('ноль в столбце штрихкода — это «нет штрихкода», а не код', () => {
    /* Иначе сто товаров получили бы один и тот же код, и первое же сканирование
       нашло бы не тот товар — а сказать об этом было бы уже нечем. */
    const p = план([
      ['Пакет', '0', '20'],
      ['Спички', '0', '30'],
    ]);
    expect(p.rows.map((r) => r.barcode)).toEqual([null, null]);
    expect(p.problems, 'отсутствие штрихкода — не проблема, о которой надо писать').toEqual([]);
    expect(p.rows, 'два нуля приняты за один и тот же штрихкод').toHaveLength(2);
  });

  it('и дубликат ловится уже после чистки, а не до неё', () => {
    /* Два написания одного кода — это один код. Сравнивая сырые ячейки, импорт
       завёл бы два товара на одну пачку, и остаток разошёлся бы вдвое. */
    const p = план([
      ['Чай', '4006381333931', '500'],
      ['Чай в коробке', "'4006 3813 33931", '520'],
    ]);
    expect(p.rows, 'дубликат прошёл, потому что сравнивали сырые строки').toHaveLength(1);
    expect(p.skipped).toBe(1);
    expect(p.problems.some((x) => x.message.includes('уже был в строке 2'))).toBe(true);
  });

  it('а негодный код не считается дубликатом другого негодного', () => {
    // Оба отказаны, у обоих штрихкода нет — и это два разных товара.
    const p = план([
      ['Чай', '4.87012E+12', '500'],
      ['Кофе', '1.23456E+12', '900'],
    ]);
    expect(p.rows).toHaveLength(2);
    expect(p.rows.map((r) => r.name)).toEqual(['Чай', 'Кофе']);
    expect(p.problems.filter((x) => x.severity === 'error')).toHaveLength(2);
  });

  it('и весь файл разбирается, а не до первой плохой строки', () => {
    /* Человек должен увидеть всё сразу: импорт, показывающий по одной ошибке за
       заход, превращает починку файла в десять заходов. */
    const p = план([
      ['Чай', "'4006381333931", '500'],
      ['Кофе', '4.87012E+12', '900'],
      ['Сахар', '4006381333932', '300'],
      ['Соль', '0', '100'],
    ]);
    expect(p.rows).toHaveLength(4);
    expect(p.problems.map((x) => x.line)).toEqual([3, 4]);
  });
});
