import { prisma } from '@anyq/db';
import { tariffState, tariffDenialMessage } from './tariff';

/**
 * Магазин, за который не заплатили, перестаёт писать в свои книги.
 *
 * До 15.09.2026 это держалось на дисциплине: каждый маршрут проверял тариф сам,
 * и двадцать семь из пятидесяти пишущих не проверяли. Граница между тем, что
 * закрыто, и тем, что открыто, не была ничьим решением — она была тем, что
 * успели дописать. Создать заказ поставщику было нельзя, а согласовать и
 * принять по нему поставку — можно. Провести инвентаризацию нельзя, а
 * изолировать товар в карантин — можно. Выдать заказ витрины, то есть списать
 * остаток, — можно. Открыть покупателю долг — можно.
 *
 * Держалось это не тридцать секунд, а тридцать дней: вход тариф проверяет, но
 * токен кассы живёт месяц, а `requirePosAuth` смотрит только версию токена и
 * устройство.
 *
 * Теперь вопрос задаётся один раз, там же, где разбирается токен. Новый маршрут
 * оказывается защищён тем, что ничего для этого не сделал, — а это единственный
 * способ не забыть.
 *
 * Чтение сюда не попадает намеренно. Где оно закрыто, оно закрыто самим
 * маршрутом — так было и до сегодняшнего дня; переносить это сюда значило бы
 * менять поведение заодно с починкой. Здесь только запись, то есть ровно то,
 * из-за чего граница и была дырявой.
 *
 * Ничего при этом не теряется навсегда: заплатили — всё вернулось таким, каким
 * было. Тариф — это дата, а не удаление.
 */

/**
 * Исключения, и каждое названо поимённо.
 *
 * Их два рода, и оба — не про торговлю.
 *
 * Первое: свернуться. Смена, открытая до конца тарифа, — это деньги в ящике.
 * Отказ закрыть её не откладывает работу, а портит счёт: каждый следующий день
 * делает пересчёт менее точным, а кассир, который считал ящик, уже ушёл домой.
 *
 * Второе: закрыть за собой дверь. Планшет украли, ссылку на кабинет
 * переслали — и то и другое случается независимо от того, заплачено ли за
 * месяц. Опасны они именно тем, что переживают тариф: токен кассы живёт
 * тридцать дней, а `requirePosAuth` проверяет отзыв устройства независимо от
 * счёта, — то есть отзыв и есть то единственное, что эту дыру закрывает.
 * Запретить его значит держать её открытой, ничего за это не получив:
 * продавать с отозванного устройства всё равно нельзя.
 *
 * Возврат устройства (`restore`) сюда не входит и не должен: это не «закрыть
 * дверь», а «открыть обратно».
 *
 * Списком, а не правилом вида «всё под /devices можно»: правило разрешит и то,
 * что напишут под этим путём завтра, а список — нет. Новый пишущий маршрут
 * упирается в отказ, и это тот момент, когда стоит подумать, а не дописать.
 */
const WIND_DOWN: readonly { method: string; pattern: RegExp }[] = [
  { method: 'PATCH', pattern: /^\/shifts\/[^/]+\/close$/ },
  { method: 'POST', pattern: /^\/devices\/[^/]+\/revoke$/ },
  { method: 'POST', pattern: /^\/cabinet\/reset$/ },
];

export function isWindDown(method: string, path: string): boolean {
  return WIND_DOWN.some((rule) => rule.method === method.toUpperCase() && rule.pattern.test(path));
}

/** Нужен ли этому запросу действующий тариф. */
export function needsActiveTariff(method: string, path: string): boolean {
  if (method.toUpperCase() === 'GET') return false;
  return !isWindDown(method, path);
}

/**
 * Чем отказать — или `null`, если тариф в порядке и спрашивать нечего.
 *
 * Отвечает словами про тариф, а не про права. Кассир, услышавший «недостаточно
 * прав», пойдёт искать владельца, чтобы тот дал ему прав, — а дело не в правах
 * и не в нём.
 */
export async function tariffRefusal(
  companyId: string,
  method: string,
  path: string,
): Promise<{ error: string; reason: 'tariff' } | null> {
  if (!needsActiveTariff(method, path)) return null;

  const tariff = await prisma.tariff.findUnique({ where: { companyId } });
  const state = tariffState(tariff);
  if (state === 'active') return null;

  // `reason` — чтобы касса отличила это от отказа по правам, не разбирая
  // текст. Разница для кассира велика: «недостаточно прав» он понесёт
  // владельцу, а «кончился тариф» значит, что работать нечем и надо
  // возвращаться ко входу, а не нажимать ту же кнопку ещё раз.
  return { error: tariffDenialMessage(state), reason: 'tariff' };
}
