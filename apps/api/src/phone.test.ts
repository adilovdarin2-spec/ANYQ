import { describe, it, expect } from 'vitest';
import { phoneKey, samePhone } from './phone';

/**
 * Один человек — один номер, как бы он его ни написал.
 *
 * Это не про красоту записи. По номеру находятся баллы, долг и кредитный
 * лимит; пока номера сравнивались буквально, один и тот же покупатель был для
 * базы тремя разными — с тремя разными долгами и баллами, которые не
 * находятся.
 */

describe('номер телефона', () => {
  it('одинаково записывает все привычные написания', () => {
    const тот_же = '+77001234567';
    for (const написание of [
      '+7 700 123 45 67',
      '+7(700)123-45-67',
      '8 700 123 45 67',
      '8-700-123-45-67',
      '87001234567',
      '77001234567',
      '7001234567',
      '  +7 700 123 45 67  ',
    ]) {
      expect(phoneKey(написание), написание).toBe(тот_же);
    }
  });

  it('короткое и непонятное не достраивает', () => {
    // «+7700» — это чья-то недописанная строка. Превратить её в правдоподобный
    // номер значит придумать за человека, и тогда мусор перестанет быть видно.
    expect(phoneKey('+7700')).toBe('+7700');
    expect(phoneKey('не знаю')).toBe('не знаю');
    expect(phoneKey('123')).toBe('123');
  });

  it('пустое остаётся пустым', () => {
    expect(phoneKey('')).toBe('');
    expect(phoneKey(null)).toBe('');
    expect(phoneKey(undefined)).toBe('');
    expect(phoneKey('   ')).toBe('');
  });

  it('чужую страну не переделывает в казахстанскую', () => {
    // Киргизия, Узбекистан, Россия — партнёры бывают и оттуда, и восьмёрку
    // спереди у них отрезать нельзя.
    expect(phoneKey('+996 555 123 456')).toBe('+996555123456');
    expect(phoneKey('+998 90 123 45 67')).toBe('+998901234567');
  });

  it('сравнение отвечает на тот вопрос, ради которого написано', () => {
    expect(samePhone('+7 700 123 45 67', '87001234567')).toBe(true);
    expect(samePhone('7001234567', '+77001234567')).toBe(true);
    expect(samePhone('+77001234567', '+77007654321')).toBe(false);
  });

  it('два пустых — не один и тот же человек', () => {
    // Иначе все безномерные контрагенты слились бы в одного.
    expect(samePhone('', '')).toBe(false);
    expect(samePhone(null, undefined)).toBe(false);
  });
});
