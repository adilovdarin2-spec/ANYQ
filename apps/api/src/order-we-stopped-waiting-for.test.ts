import { describe, it, expect } from 'vitest';
import { splitOnOrder, recommendOrder } from './replenishment';
import type { OpenOrderLine } from './replenishment';

/**
 * Заказ, которого уже не будет, перестаёт держать полку пустой.
 *
 * Автозаказ вычитает заказанное из потребности — и это правильно: заказывать
 * поверх опаздывающей поставки значит набрать трёхмесячный запас одного товара,
 * и делает так магазин как раз тогда, когда встревожен.
 *
 * Срока у вычитания не было никакого. Заказ, отправленный в марте и не
 * пришедший, вычитался в сентябре: полка пустая, а экран отвечал «заказано 40,
 * заказывать не надо». И не говорил этого никто — ни строкой, ни цветом.
 *
 * Молчит эта ошибка именно там, где она дорогая. Пустая полка — потерянная
 * продажа и ушедший покупатель; двойной заказ — замороженные деньги. Второе
 * лечится, первое нет.
 *
 * Теперь у ожидания есть срок: обещанная дата, а без неё — день заказа плюс
 * срок поставки, и сверху запас на обычное опоздание, равный сроку поставки, но
 * не меньше трёх дней. Поставщик, опоздавший на целый свой срок, не опаздывает:
 * его заказа не будет.
 */

const день = 86_400_000;
const СЕГОДНЯ = new Date('2026-09-28T09:00:00Z');
const заказ = (сколько: number, дняНазад: number, обещали: Date | null = null): OpenOrderLine => ({
  outstanding: сколько,
  orderedAt: new Date(СЕГОДНЯ.getTime() - дняНазад * день),
  expectedAt: обещали,
});

describe('едет или уже не будет', () => {
  it('вчерашний заказ едет', () => {
    expect(splitOnOrder([заказ(40, 1)], 3, СЕГОДНЯ)).toEqual({ coming: 40, overdue: 0 });
  });

  it('и опоздавший на день — тоже едет', () => {
    /* Срок три дня, прошло четыре. Поставщик, задержавшийся на день, — обычное
       дело, и заказывать второй раз из-за этого значит завалить склад. */
    expect(splitOnOrder([заказ(40, 4)], 3, СЕГОДНЯ)).toEqual({ coming: 40, overdue: 0 });
  });

  it('а опоздавший на целый свой срок — уже не будет', () => {
    // Срок три дня, запас три дня, прошло семь.
    expect(splitOnOrder([заказ(40, 7)], 3, СЕГОДНЯ)).toEqual({ coming: 0, overdue: 40 });
  });

  it('и мартовский заказ — тем более', () => {
    expect(splitOnOrder([заказ(40, 190)], 3, СЕГОДНЯ)).toEqual({ coming: 0, overdue: 40 });
  });

  it('длинный срок поставки получает пропорционально длинный запас', () => {
    /* Две недели ожидания — это не то же, что три дня. Поставщик с месячным
       циклом не становится пропавшим на восьмой день. */
    expect(splitOnOrder([заказ(40, 20)], 14, СЕГОДНЯ)).toEqual({ coming: 40, overdue: 0 });
    expect(splitOnOrder([заказ(40, 29)], 14, СЕГОДНЯ)).toEqual({ coming: 0, overdue: 40 });
  });

  it('обещанная дата важнее расчётной', () => {
    /* Поставщик сказал «привезём двадцатого» — считаем от его слова, а не от дня
       заказа. Заказ мог лежать месяц именно потому, что так договорились. */
    const обещали = new Date(СЕГОДНЯ.getTime() - 1 * день);
    expect(splitOnOrder([заказ(40, 60, обещали)], 3, СЕГОДНЯ)).toEqual({ coming: 40, overdue: 0 });

    const обещалиДавно = new Date(СЕГОДНЯ.getTime() - 30 * день);
    expect(splitOnOrder([заказ(40, 60, обещалиДавно)], 3, СЕГОДНЯ)).toEqual({ coming: 0, overdue: 40 });
  });

  it('и один заказ едет, пока другой пропал', () => {
    // Иначе одна старая строка похоронила бы весь свежий заказ того же товара.
    expect(splitOnOrder([заказ(40, 190), заказ(12, 1)], 3, СЕГОДНЯ)).toEqual({ coming: 12, overdue: 40 });
  });

  it('привезённое целиком не считается ни едущим, ни пропавшим', () => {
    expect(splitOnOrder([заказ(0, 190)], 3, СЕГОДНЯ)).toEqual({ coming: 0, overdue: 0 });
  });

  it('и пустой срок поставки не ломает счёт', () => {
    // Политики может не быть вовсе; три дня — то же значение по умолчанию, что и в маршруте.
    expect(splitOnOrder([заказ(40, 7)], 0, СЕГОДНЯ)).toEqual({ coming: 0, overdue: 40 });
    expect(splitOnOrder([заказ(40, 2)], Number.NaN, СЕГОДНЯ)).toEqual({ coming: 40, overdue: 0 });
  });
});

describe('рекомендация после этого', () => {
  it('на пропавший заказ больше не рассчитывает', () => {
    /* Это и есть сама ошибка, целиком: полка пустая, продаётся два в день,
       мартовский заказ на сорок. До 28.09.2026 экран отвечал «ничего не надо». */
    const пропал = splitOnOrder([заказ(40, 190)], 3, СЕГОДНЯ);
    const было = recommendOrder({
      available: 0,
      inTransit: 0,
      onOrder: 40,
      demandPerDay: 2,
      leadTimeDays: 3,
      minQuantity: 0,
      targetQuantity: 0,
    });
    const стало = recommendOrder({
      available: 0,
      inTransit: 0,
      onOrder: пропал.coming,
      demandPerDay: 2,
      leadTimeDays: 3,
      minQuantity: 0,
      targetQuantity: 0,
    });

    expect(было.quantity, 'старое поведение уже не воспроизводится — проверять нечего').toBe(0);
    expect(стало.quantity, 'полка пустая, а заказывать по-прежнему нечего').toBeGreaterThan(0);
  });

  it('а на едущий — рассчитывает по-прежнему', () => {
    // Двойной заказ поверх идущей поставки — та самая ошибка, которую вычитание и лечит.
    const едет = splitOnOrder([заказ(40, 1)], 3, СЕГОДНЯ);
    const r = recommendOrder({
      available: 0,
      inTransit: 0,
      onOrder: едет.coming,
      demandPerDay: 2,
      leadTimeDays: 3,
      minQuantity: 0,
      targetQuantity: 0,
    });
    expect(r.quantity).toBe(0);
  });
});
