/**
 * Сколько по чеку получено на самом деле.
 *
 * Одна формула: позиции минус скидка минус баллы. Считать её умеют девять
 * мест — чек, возврат, выручка смены, сменный отчёт поддержки, долг
 * покупателя, фискальная очередь, отчёт по кассирам, — и все девять до
 * 16.09.2026 писали её руками.
 *
 * Дважды за один день оказалось, что не все пишут одинаково. Долг покупателя
 * складывался по одним позициям: со скидкой 10% на чеке 675, а в долгах 750, и
 * заплативший по чеку оставался должен. А проверка кредитного лимита считала
 * без баллов — то есть отказывала за долг, которого не будет.
 *
 * Функция маленькая до неловкости, и не в экономии строк смысл: у формулы
 * появляется имя, по которому её видно, и место, где написано, из чего она
 * состоит. Что новое место обязано звать именно её, проверяет
 * `receipt-total.test.ts`, читая исходник.
 */
export function receiptTotal(
  /** Сумма позиций: то, что было бы к оплате без разговора у кассы. */
  lines: number,
  discountAmount: number,
  pointsRedeemed: number | null | undefined,
): number {
  return lines - discountAmount - (pointsRedeemed ?? 0);
}
