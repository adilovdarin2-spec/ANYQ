/**
 * Чего владелец не должен сделать со своими сотрудниками, даже нарочно.
 *
 * До 15.09.2026 сотрудников заводили только из панели ANYQ, и обеих этих
 * защит там не было — по простой причине: администратор платформы не входит в
 * компанию, и запереть себя в ней не может. Владелец может. Теперь список
 * сотрудников ведёт он сам, и оба случая перестали быть теоретическими.
 *
 * Вынесено из маршрута, потому что это решение, а не проводка: правило,
 * которое запирает человека из собственной кассы, должно быть проверяемым без
 * поднятого сервера.
 */

export interface StaffMember {
  id: string;
  role: string;
}

/**
 * Последнего владельца понижать нельзя.
 *
 * Сотрудников заводит и правит владелец. Если он снимет владельца с
 * единственного владельца — с себя, — в компании не останется никого, кто
 * может это отменить: ни кассир, ни менеджер, ни кладовщик не заводят людей.
 * Дальше только звонок нам и правка руками в базе, то есть ровно то, ради
 * отсутствия чего сотрудники и переехали в кассу.
 *
 * Проверяется по составу, а не по «это ты сам»: второй владелец, понижающий
 * первого, оставляет компанию с владельцем и вправе так сделать.
 */
export function lastOwnerRefusal(staff: StaffMember[], changingId: string, nextRole: string): string | null {
  const target = staff.find((person) => person.id === changingId);
  if (!target || target.role !== 'owner' || nextRole === 'owner') return null;

  const owners = staff.filter((person) => person.role === 'owner').length;
  if (owners > 1) return null;
  return 'В магазине должен остаться хотя бы один владелец';
}

/**
 * Себе роль не меняют.
 *
 * Отдельно от правила про последнего владельца, потому что случай другой:
 * владелец, снимающий с себя роль при втором владельце, компанию не ломает —
 * но и не понимает, что делает. Такое делают чужими руками: второй владелец
 * или мы.
 *
 * А заодно это закрывает путь наверх, которого быть не должно: если завтра
 * список сотрудников откроют менеджеру, «поменять себе роль на владельца»
 * станет одним нажатием.
 */
export function selfRoleRefusal(actorId: string, changingId: string, currentRole: string, nextRole: string): string | null {
  if (actorId !== changingId || currentRole === nextRole) return null;
  return 'Свою роль менять нельзя — попросите второго владельца или нас';
}

/**
 * Себя не увольняют.
 *
 * Тот же довод, короче: человек, убравший собственный доступ, выходит из
 * кассы посреди смены и возвращается только через нас.
 */
export function selfRemovalRefusal(actorId: string, removingId: string): string | null {
  return actorId === removingId ? 'Себя удалить нельзя — попросите второго владельца или нас' : null;
}
