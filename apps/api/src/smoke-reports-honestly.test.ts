import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

/**
 * Дымовой тест обязан доходить до конца и не красить в красное чужой тариф.
 *
 * Это тот скрипт, который по инструкции запускают перед тем, как отдать
 * магазин людям, и запускают ровно один раз. Дважды он подвёл на одном прогоне.
 *
 * Во-первых, падал. `JSON.stringify(undefined)` возвращает `undefined`, а не
 * строку, и `.slice` на нём бросает — то есть скрипт умирал именно тогда, когда
 * шаг отказал и поля в ответе не оказалось. Вместо строки «FAIL … — {error:…}»
 * и сводки оператор получал стек-трейс, а всё, что ниже, не выполнялось вовсе —
 * включая проверки инвариантов: сходится ли остаток с журналом и не больше ли
 * партий, чем товара. Самое важное в скрипте стояло последним и оказывалось за
 * местом падения.
 *
 * Во-вторых, показывал шесть «поломок» там, где сервер отвечал правильно:
 * магазин на тарифе «розница и склад» не покупал ни ячейки, ни закупки. Партии
 * скрипт в такой же ситуации пропускал. Красный цвет, которому нельзя верить,
 * хуже отсутствия цвета: рядом стоят настоящие отказы.
 */

const smoke = readFileSync(resolve(__dirname, '../../../scripts/smoke.mjs'), 'utf8').replace(/\r\n/g, '\n');

describe('дымовой тест доходит до конца', () => {
  it('выжимка значения не бросает на отсутствующем поле', () => {
    expect(smoke).toContain('function brief(');
    expect(smoke, 'сырой stringify с .slice — это падение на первом же пустом поле').not.toMatch(
      /JSON\.stringify\([^)]*\)\.slice\(/,
    );
  });

  it('а проверки инвариантов стоят после всех необязательных модулей', () => {
    // Порядок и есть причина, по которой падение было дорогим: упав раньше,
    // скрипт не проверял главного.
    const инвариант = smoke.indexOf('stock equals the ledger');
    expect(инвариант, 'не нашлась проверка инварианта — разошёлся разбор').toBeGreaterThan(0);
    expect(smoke.indexOf('== bins ==')).toBeLessThan(инвариант);
    expect(smoke.indexOf('purchase orders ==')).toBeLessThan(инвариант);
  });
});

describe('и не красит в красное чужой тариф', () => {
  it('отказ по тарифу узнаётся отдельно от поломки', () => {
    expect(smoke).toContain('function refusedByTariff(');
    expect(smoke).toMatch(/res\.status === 403 && \/тариф\/i\.test/);
  });

  it('каждый необязательный модуль пропускается, а не заваливается', () => {
    // Партии умели это с самого начала; ячейки и закупки — нет, и в этом была
    // вся разница между «шесть поломок» и «три модуля не куплены».
    for (const [name, call] of [
      ['ячейки', 'refusedByTariff(putaway)'],
      ['закупки', 'refusedByTariff(repl)'],
    ] as const) {
      expect(smoke, `${name}: тарифный отказ должен становиться пропуском`).toContain(call);
      expect(smoke).toContain(`skip('${name}'`);
    }
    expect(smoke, 'партии умели это и раньше').toContain("skip('партии'");
  });
});
