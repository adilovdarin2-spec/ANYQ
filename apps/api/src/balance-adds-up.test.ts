import { describe, it, expect } from 'vitest';
import { computeBalance } from './settlements';
import type { Charge } from './settlements';

/**
 * Сальдо складывается из двух чисел, и они сходятся.
 *
 * Экран расчётов показывал одно число: «Должен 8 500». По такому числу нельзя ни
 * спорить, ни соглашаться — а спорят по нему постоянно, это опт: у контрагента
 * своя тетрадь, и сверяют они её при каждой поставке.
 *
 * Теперь рядом стоит «начислено минус оплачено», и разность обязана давать
 * сальдо **в точности**. Иначе строка не помогает, а запутывает: владелец
 * складывает в уме, не получает числа из шапки и перестаёт верить обоим.
 *
 * Свойство держится на том, что `paid` считает и разнесённое, и принятое вперёд:
 * `charged − (settled + unapplied)` — это и есть `balance`. Разойдись они — и
 * строка соврёт молча.
 */

const начисление = (amount: number, settled = 0): Charge => ({
  documentId: `d${amount}-${settled}`,
  amount,
  settled,
  at: new Date('2026-09-01T10:00:00Z'),
});

describe('начислено минус оплачено', () => {
  it('даёт сальдо на обычном счёте', () => {
    const b = computeBalance([начисление(50000, 41500)]);
    expect(b.charged - b.paid).toBe(b.balance);
    expect(b.balance).toBe(8500);
  });

  it('и когда часть денег ещё не на что разнести', () => {
    /* Предоплата — самое опасное место для такой строки: сальдо её вычитает, а
       разбивка по срокам не показывает вовсе. */
    const b = computeBalance([начисление(10000, 0)], 2000);
    expect(b.charged - b.paid).toBe(b.balance);
    expect(b.balance).toBe(8000);
  });

  it('и при переплате, когда должны мы', () => {
    const b = computeBalance([начисление(1000, 1000)], 500);
    expect(b.charged - b.paid).toBe(b.balance);
    expect(b.balance).toBeLessThan(0);
  });

  it('и на пустом счёте', () => {
    const b = computeBalance([]);
    expect(b.charged - b.paid).toBe(b.balance);
    expect(b.balance).toBe(0);
  });

  it('и на любом наборе начислений подряд', () => {
    /* Проверяется свойством, а не подобранным примером: строка на экране обязана
       сходиться на всех счетах, а не на тех, которые попали в тест. */
    for (let сумма = 0; сумма <= 2000; сумма += 137) {
      for (let оплачено = 0; оплачено <= сумма; оплачено += 251) {
        for (const вперёд of [0, 1, 999]) {
          const b = computeBalance(
            [начисление(сумма, оплачено), начисление(сумма + 13, Math.min(оплачено, сумма + 13))],
            вперёд,
          );
          expect(b.charged - b.paid, `${сумма}/${оплачено}/${вперёд}`).toBe(b.balance);
        }
      }
    }
  });
});
