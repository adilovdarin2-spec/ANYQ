/**
 * Когда чек был пробит — по словам кассы, но не на слово.
 *
 * Касса обязана торговать неделю без сети, и всё это время чеки лежат в её
 * очереди. Пока время продажи не приходило с кассы, сервер ставил своё «сейчас»
 * в момент синхронизации: неделя торговли ложилась одним днём. Выручка по дням
 * считается по дате документа, поэтому дни без связи выходили пустыми, а день
 * возвращения — с недельной выручкой. Смена при этом определялась верно, по
 * своему идентификатору, и внутри смены сумма сходилась — расхождение видно
 * только в отчётах по датам, то есть именно там, куда владелец и смотрит.
 *
 * Верить планшету нельзя: часы на нём ставит человек, и ошибка здесь означает
 * выручку, уехавшую в прошлый месяц, — туда, где её уже никто не ищет. Поэтому
 * время принимается, только если оно лежит между открытием смены и текущим
 * моментом. Это не про злой умысел: сбитые часы на дешёвом планшете — обычное
 * дело, а в этих границах даже сбитые не могут испортить отчётность.
 *
 * Границы выбраны так:
 *
 * - **не в будущем** — иначе продажа попадает в отчёт, которого ещё не было, и
 *   исчезает из сегодняшнего;
 * - **не раньше открытия смены** — чек не может быть пробит до того, как касса
 *   открылась; смена — самый узкий надёжный предел, который сервер знает сам;
 * - **смены нет** — тогда единственный проверяемый предел это «не в будущем»:
 *   продажу без смены и так принимают, чтобы не потерять её, и отказ по дате
 *   здесь означал бы потерю данных ради аккуратности.
 */
export function soldAtOrNow(raw: unknown, shiftOpenedAt: Date | null, now: Date = new Date()): Date {
  if (typeof raw !== 'string' || !raw) return now;
  const parsed = new Date(raw);
  if (Number.isNaN(parsed.getTime())) return now;
  if (parsed > now) return now;
  if (shiftOpenedAt && parsed < shiftOpenedAt) return now;
  return parsed;
}
