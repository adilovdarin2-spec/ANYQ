import { KZ_OFFSET_HOURS } from './kz-time';

/**
 * Чеки одного дня магазина — окно в UTC по местной дате.
 *
 * Список чеков для возврата отдавал последние пятьдесят и ничего больше. В
 * продуктовом это до обеда: покупатель, пришедший через неделю, своего чека в
 * списке не находил, и сделать с этим было нечего — ни поиска, ни выбора дня.
 * А возврат по чеку недельной давности — обычный разговор у прилавка, он даже
 * записан отдельной строкой в плане запуска.
 *
 * Ключ — день, а не номер: на бумажке, которую приносит покупатель, есть дата и
 * сумма. Номер чека там тоже печатается, но человек называет день.
 *
 * Границы местные. День магазина кончается в местную полночь, а не в UTC:
 * вечерние чеки с семи до полуночи по Алматы в UTC уже следующего дня, и
 * окно по UTC отдало бы за «вчера» ровно те чеки, которых кассир не ждёт.
 */

const HOUR_MS = 60 * 60 * 1000;
const DAY_MS = 24 * HOUR_MS;

export interface DayWindow {
  gte: Date;
  lt: Date;
}

/** `2026-09-23` → окно в UTC. Пусто или мусор — `null`, и список отдаётся как раньше. */
export function receiptDayWindow(day: unknown): DayWindow | null {
  if (typeof day !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(day)) return null;
  const midnightUtc = Date.parse(`${day}T00:00:00.000Z`);
  if (!Number.isFinite(midnightUtc)) return null;
  // Местная полночь этого дня — это UTC-полночь минус смещение.
  const start = midnightUtc - KZ_OFFSET_HOURS * HOUR_MS;
  return { gte: new Date(start), lt: new Date(start + DAY_MS) };
}
