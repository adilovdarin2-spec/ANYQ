import { describe, it, expect } from 'vitest';
import { normaliseBarcode, hasValidCheckDigit, barcodeProblemMessage } from './barcode';

/**
 * Штрихкод из чужого файла — на настоящем мусоре, а не на придуманном.
 *
 * Каждый случай здесь взят из того, что бывает в выгрузках: апостроф Excel,
 * пробелы по три цифры, `.0` от числового формата, экспонента вместо
 * тринадцати цифр. До 25.09.2026 все они попадали в каталог дословно и молча.
 */

describe('контрольная цифра', () => {
  it('сходится у настоящих кодов', () => {
    // EAN-13, EAN-8, UPC-A, GTIN-14 — по одному живому примеру на длину.
    expect(hasValidCheckDigit('4006381333931')).toBe(true);
    expect(hasValidCheckDigit('96385074')).toBe(true);
    expect(hasValidCheckDigit('036000291452')).toBe(true);
    expect(hasValidCheckDigit('04006381333931')).toBe(true);
  });

  it('и не сходится, если цифру переставили или потеряли', () => {
    expect(hasValidCheckDigit('4006381333932')).toBe(false);
    expect(hasValidCheckDigit('4006381333921')).toBe(false);
    expect(hasValidCheckDigit('96385075')).toBe(false);
  });

  it('а у длин, где её не бывает, не выдумывается', () => {
    /* Семь цифр или одиннадцать — это не укороченный EAN, это внутренний код.
       Сказать про него «контрольная не сходится» значило бы придумать правило,
       которого нет, и напугать человека его же артикулом. */
    for (const код of ['1', '123', '1234567', '12345678901', '123456789012345']) {
      expect(hasValidCheckDigit(код), код).toBe(false);
    }
  });
});

describe('чистка штрихкода', () => {
  it('убирает косметику, оставляя цифры', () => {
    const чистые = [
      ["'4006381333931", 'апостроф Excel'],
      ['4006 3813 33931', 'пробелы по три'],
      ['4006-381-333931', 'дефисы'],
      ['4006381333931 ', 'неразрывный пробел'],
      ['  4006381333931  ', 'пробелы вокруг'],
      ['4006381333931.0', 'точка-ноль от числового формата'],
      ['4006381333931.', 'точка на конце'],
    ] as const;
    for (const [вход, что] of чистые) {
      const читано = normaliseBarcode(вход);
      expect(читано.barcode, что).toBe('4006381333931');
      expect(читано.problem, что).toBeNull();
    }
  });

  it('но экспоненту не чистит, а отказывает', () => {
    /* Самое важное место. `4.87012E+12` — это шесть значащих цифр из
       тринадцати, и вычистив точку с буквой мы получили бы «487012» или
       «4870120000000»: правдоподобный код, которого нет ни на одной пачке.
       Молча записать такой в каталог хуже, чем не записать ничего. */
    for (const вход of ['4.87012E+12', '4.87012e+12', '1.2E13', '4,87012E+12']) {
      const читано = normaliseBarcode(вход);
      expect(читано.barcode, вход).toBeNull();
      expect(читано.problem, вход).toBe('excel-notation');
    }
  });

  it('и про несходящуюся цифру говорит, но код оставляет', () => {
    // Товар настоящий, и заводить его надо. Штрихкод поправят по пачке.
    const читано = normaliseBarcode('4006381333932');
    expect(читано.barcode).toBe('4006381333932');
    expect(читано.problem).toBe('check-digit');
  });

  it('пустое и одни нули — это «штрихкода нет»', () => {
    /* Ноль в столбце штрихкода встречается в каждой второй выгрузке. Записав
       его, мы получили бы каталог, где сто товаров имеют один и тот же код. */
    for (const вход of ['', '   ', '0', '00', '0000000000000', '0.0']) {
      const читано = normaliseBarcode(вход);
      expect(читано.barcode, JSON.stringify(вход)).toBeNull();
      expect(читано.problem, JSON.stringify(вход)).toBeNull();
    }
  });

  it('а буквы оставляет молча', () => {
    /* Code 128 кодирует буквы, и внутренний артикул магазина — тоже штрихкод,
       если он напечатан на полке. Контрольной цифры у него нет, и жаловаться
       на её отсутствие значило бы ругать человека за исправный код. */
    for (const вход of ['ART-1024', 'ШК4006381333931', 'abc123']) {
      const читано = normaliseBarcode(вход);
      expect(читано.barcode, вход).toBeTruthy();
      expect(читано.problem, вход).toBeNull();
    }
  });

  it('и короткий числовой код не трогает', () => {
    // Весовой ярлык и внутренний номер бывают короткими. Это не ошибка.
    expect(normaliseBarcode('123')).toEqual({ barcode: '123', problem: null });
    expect(normaliseBarcode('1234567')).toEqual({ barcode: '1234567', problem: null });
  });
});

describe('что говорится человеку', () => {
  it('про экспоненту — что делать, а не что случилось', () => {
    const сказано = barcodeProblemMessage('excel-notation', 'Чай «Асем»', '4.87012E+12');
    expect(сказано).toContain('Чай «Асем»');
    // Виден исходный вид: человек найдёт эту ячейку глазами.
    expect(сказано).toContain('4.87012E+12');
    // И названо действие, а не диагноз.
    expect(сказано).toContain('как текст');
    expect(сказано).toContain('заново');
  });

  it('про контрольную цифру — что сканер не найдёт', () => {
    const сказано = barcodeProblemMessage('check-digit', 'Сигареты', '4006381333932');
    expect(сказано).toContain('Сигареты');
    expect(сказано).toContain('4006381333932');
    expect(сказано).toContain('сканер');
  });
});
