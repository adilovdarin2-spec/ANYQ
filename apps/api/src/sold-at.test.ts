import { describe, it, expect } from 'vitest';
import { soldAtOrNow } from './sold-at';

/**
 * Каким временем помечается чек, пролежавший в офлайн-очереди.
 *
 * Свойство двустороннее, и обе стороны стоят денег. Не брать время кассы —
 * значит складывать неделю офлайн-торговли в один день синхронизации: дни без
 * связи выходят пустыми, день возвращения — с недельной выручкой, и владелец
 * видит не свои цифры. Брать его без проверки — значит пустить выручку туда,
 * куда её отправят сбитые часы дешёвого планшета, в том числе в прошлый месяц,
 * где её уже никто не ищет.
 */

const сейчас = new Date('2026-09-11T18:00:00.000Z');
const сменаОткрыта = new Date('2026-09-11T09:00:00.000Z');

describe('soldAtOrNow', () => {
  it('берёт время кассы, если оно внутри смены', () => {
    // Ровно тот случай, ради которого всё: чек пробит в 14:00, очередь дошла в
    // 18:00, в отчёт он обязан попасть четырнадцатым часом.
    const пробит = '2026-09-11T14:00:00.000Z';
    expect(soldAtOrNow(пробит, сменаОткрыта, сейчас).toISOString()).toBe(пробит);
  });

  it('без времени от кассы — серверное', () => {
    expect(soldAtOrNow(undefined, сменаОткрыта, сейчас)).toEqual(сейчас);
    expect(soldAtOrNow('', сменаОткрыта, сейчас)).toEqual(сейчас);
  });

  it('мусор вместо даты — серверное, а не крах', () => {
    expect(soldAtOrNow('вчера вечером', сменаОткрыта, сейчас)).toEqual(сейчас);
    expect(soldAtOrNow(12345 as unknown, сменаОткрыта, сейчас)).toEqual(сейчас);
  });

  it('время из будущего не принимается', () => {
    // Иначе продажа попадает в отчёт, которого ещё не было, и пропадает из
    // сегодняшнего.
    expect(soldAtOrNow('2026-09-12T10:00:00.000Z', сменаОткрыта, сейчас)).toEqual(сейчас);
  });

  it('время раньше открытия смены не принимается', () => {
    // Чек не может быть пробит до того, как касса открылась. Это и есть защита
    // от планшета со сбитыми часами: выручка остаётся в своей смене вместо
    // того, чтобы уехать в прошлый месяц.
    expect(soldAtOrNow('2026-08-15T12:00:00.000Z', сменаОткрыта, сейчас)).toEqual(сейчас);
    expect(soldAtOrNow('2026-09-11T08:59:59.000Z', сменаОткрыта, сейчас)).toEqual(сейчас);
  });

  it('ровно в момент открытия смены — принимается', () => {
    // Граница включительна: первый чек можно пробить в ту же секунду, в которую
    // открыли смену, и это не повод отбрасывать его время.
    expect(soldAtOrNow(сменаОткрыта.toISOString(), сменаОткрыта, сейчас)).toEqual(сменаОткрыта);
  });

  it('без смены проверяется только «не в будущем»', () => {
    // Продажу без смены сервер и так принимает, чтобы не потерять её. Отказ по
    // дате здесь означал бы терять данные ради аккуратности.
    const давно = '2026-09-01T10:00:00.000Z';
    expect(soldAtOrNow(давно, null, сейчас).toISOString()).toBe(давно);
    expect(soldAtOrNow('2026-09-12T10:00:00.000Z', null, сейчас)).toEqual(сейчас);
  });
});
