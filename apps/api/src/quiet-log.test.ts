import { describe, it, expect } from 'vitest';
// @ts-expect-error — скрипт обслуживания на .mjs, типов у него нет и не нужно.
import { createQuietLog } from '../../../scripts/lib/quiet.mjs';

/**
 * Когда планировщик обслуживания молчит, а когда говорит.
 *
 * Проверяется здесь ровно одно свойство, и оно двустороннее. Лог, который
 * повторяет «всё спокойно» каждую минуту, никто не читает: четыре тысячи строк в
 * сутки, в которых настоящая одна. Лог, который замолчал навсегда, — хуже:
 * тишина остановившейся службы выглядит точно так же, как тишина спокойной ночи,
 * и узнают об этом в то утро, когда чек не ушёл в ОФД.
 *
 * Поэтому проверяется и то, что рутина затихает, и то, что она возвращается.
 * Часы передаются снаружи — иначе проверка «раз в час» длилась бы час.
 */

function harness(heartbeatMs = 60 * 60 * 1000) {
  const lines: string[] = [];
  let clock = 0;
  const log = createQuietLog({
    write: (line: string) => lines.push(line),
    heartbeatMs,
    now: () => clock,
  });
  return {
    lines,
    /** Один проход планировщика спустя `ms` после предыдущего. */
    tick(ms: number, body: () => void) {
      clock += ms;
      log.beginTick();
      body();
    },
    log,
  };
}

const MINUTE = 60_000;

describe('тихий лог обслуживания', () => {
  it('первый тик показывает состояние целиком', () => {
    // Человек, только что запустивший службу, должен увидеть, чем она занята, а
    // не пустой экран.
    const h = harness();
    h.tick(0, () => {
      h.log.routine('fiscal', 'очередь пуста');
      h.log.routine('summary', 'сводки не ко времени');
    });
    expect(h.lines).toEqual(['очередь пуста', 'сводки не ко времени']);
  });

  it('дальше повторять одно и то же не будет', () => {
    const h = harness();
    for (let i = 0; i < 30; i += 1) {
      h.tick(MINUTE, () => h.log.routine('fiscal', 'очередь пуста'));
    }
    expect(h.lines).toEqual(['очередь пуста']);
  });

  it('но через час скажет снова — иначе тишину не отличить от смерти', () => {
    const h = harness();
    for (let i = 0; i < 59; i += 1) {
      h.tick(MINUTE, () => h.log.routine('fiscal', 'очередь пуста'));
    }
    expect(h.lines).toHaveLength(1);

    h.tick(MINUTE, () => h.log.routine('fiscal', 'очередь пуста'));
    expect(h.lines).toHaveLength(2);
  });

  it('изменившаяся рутина видна сразу, а не через час', () => {
    // «Очередь пуста» → «в очереди три чека» это и есть то, за чем человек
    // пришёл в лог. Ждать часа здесь значило бы узнать новость с опозданием.
    const h = harness();
    h.tick(0, () => h.log.routine('fiscal', 'очередь пуста'));
    h.tick(MINUTE, () => h.log.routine('fiscal', 'в очереди три чека'));
    expect(h.lines).toEqual(['очередь пуста', 'в очереди три чека']);
  });

  it('ключи не заглушают друг друга', () => {
    // Состояния независимы: то, что очередь не менялась, не должно прятать
    // изменение по сводкам, и наоборот.
    const h = harness();
    h.tick(0, () => {
      h.log.routine('fiscal', 'очередь пуста');
      h.log.routine('summary', 'сводки не ко времени');
    });
    h.tick(MINUTE, () => {
      h.log.routine('fiscal', 'очередь пуста');
      h.log.routine('summary', 'сводка ушла владельцу');
    });
    expect(h.lines).toEqual([
      'очередь пуста',
      'сводки не ко времени',
      'сводка ушла владельцу',
    ]);
  });

  it('событие и сбой печатаются всегда', () => {
    // Главное, что не должно пострадать от тишины. Сбой, повторяющийся каждую
    // минуту, это не рутина, а минута за минутой, в которую продукт не работает.
    const h = harness();
    for (let i = 0; i < 10; i += 1) {
      h.tick(MINUTE, () => h.log.say('FAILED fiscal: 500'));
    }
    expect(h.lines).toHaveLength(10);
  });

  it('возврат к рутине после события снова виден', () => {
    // Иначе «сломалось и починилось» выглядело бы как «сломалось» до конца часа.
    const h = harness();
    h.tick(0, () => h.log.routine('fiscal', 'очередь пуста'));
    h.tick(MINUTE, () => h.log.say('fiscal: зарегистрирован 1 чек'));
    h.tick(MINUTE, () => h.log.routine('fiscal', 'очередь пуста'));
    // Последняя строка — та же рутина, но сказанная заново: между ними было
    // событие, и без повторения лог утверждал бы, что с начала часа ничего не
    // менялось.
    expect(h.lines).toEqual([
      'очередь пуста',
      'fiscal: зарегистрирован 1 чек',
      'очередь пуста',
    ]);
  });

  it('после сбоя видно, что снова заработало', () => {
    // Ради этого случая событие и сбрасывает память о рутине. Иначе лог
    // выглядел бы так: сбой — и тишина до конца часа, то есть «всё ещё
    // сломано», хотя починилось на следующей минуте.
    const h = harness();
    h.tick(0, () => h.log.routine('idempotency', 'удалено 0'));
    h.tick(MINUTE, () => h.log.say('FAILED idempotency: 500'));
    h.tick(MINUTE, () => h.log.routine('idempotency', 'удалено 0'));
    expect(h.lines).toEqual(['удалено 0', 'FAILED idempotency: 500', 'удалено 0']);
  });
});
