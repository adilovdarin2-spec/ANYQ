import { describe, it, expect } from 'vitest';
import { localDateTime, localDay, localHour, startOfLocalDay } from './kz-time';

/**
 * Время магазина, а не время сервера.
 *
 * База в Сан-Франциско, магазин в Казахстане, а «сегодня» бывает только одно —
 * то, которое у магазина. Ошибка здесь выглядит безобидно и стоит дорого:
 * сводка владельцу в три часа ночи, тариф, кончившийся на день раньше, и
 * вечерний чек, уехавший в выгрузке на предыдущую дату.
 */

describe('время по-казахстански', () => {
  it('час — местный', () => {
    expect(localHour(new Date('2026-09-08T03:00:00.000Z'))).toBe(8);
    // Через полночь по UTC: 21:00 там — два часа ночи здесь.
    expect(localHour(new Date('2026-09-08T21:00:00.000Z'))).toBe(2);
  });

  it('день — местный', () => {
    expect(localDay(new Date('2026-09-08T18:00:00.000Z'))).toBe('2026-09-08');
    expect(localDay(new Date('2026-09-08T19:30:00.000Z'))).toBe('2026-09-09');
  });

  it('полночь местного дня — в UTC это вчерашние 19:00', () => {
    expect(startOfLocalDay(new Date('2026-09-08T18:00:00.000Z')).toISOString()).toBe('2026-09-07T19:00:00.000Z');
  });

  it('момент времени — как его читает человек и понимает Excel', () => {
    expect(localDateTime(new Date('2026-09-08T10:00:00.000Z'))).toBe('08.09.2026 15:00');
    expect(localDateTime(new Date('2026-09-08T20:30:00.000Z'))).toBe('09.09.2026 01:30');
    // Однозначные день, месяц, час и минута — с ведущим нулём, иначе Excel
    // разбирает не всё, а колонка выглядит рваной.
    expect(localDateTime(new Date('2026-01-02T00:05:00.000Z'))).toBe('02.01.2026 05:05');
  });
});
