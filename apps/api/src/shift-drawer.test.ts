import { describe, it, expect } from 'vitest';
import { drawerShiftFor } from './shift-drawer';

/**
 * Возврат ложится в тот ящик, из которого достали деньги.
 *
 * Своих открытых смен у человека бывает две: забыл закрыть вчерашнюю, ушёл,
 * утром открыл новую — ровно тот случай, ради которого две открытые смены на
 * точке и разрешены. Выбор из них был «первая попавшаяся»: `findMany` без
 * сортировки отдаёт строки в порядке, который решает база.
 *
 * Найдено 30.09.2026 вторым прогоном дня магазина. Возврат на 198 ₸, выданный
 * сегодня, лёг в ящик позавчерашней смены: на закрытии касса потребовала от
 * кассира на 198 ₸ больше, чем он отдал. Недостачу кассир оплачивает.
 */

const at = (iso: string) => new Date(iso);

describe('в какой ящик легли деньги мимо чека', () => {
  it('в свою открытую смену', () => {
    const shifts = [
      { id: 'чужая', userId: 'вера', openedAt: at('2026-09-30T08:00:00Z') },
      { id: 'моя', userId: 'тимур', openedAt: at('2026-09-30T06:00:00Z') },
    ];
    expect(drawerShiftFor(shifts, 'тимур')).toBe('моя');
  });

  it('а из двух своих — в открытую последней', () => {
    /* Тот самый случай. Забытая вчерашняя стоит в списке первой, и выбор
       «первая попавшаяся» отправлял сегодняшний возврат в неё. */
    const shifts = [
      { id: 'вчерашняя', userId: 'тимур', openedAt: at('2026-09-29T15:16:00Z') },
      { id: 'сегодняшняя', userId: 'тимур', openedAt: at('2026-09-30T06:18:00Z') },
    ];
    expect(drawerShiftFor(shifts, 'тимур')).toBe('сегодняшняя');
  });

  it('и порядок строк на ответ не влияет', () => {
    // Свойством: база вправе отдать их как угодно, ответ обязан быть один.
    const вчера = { id: 'вчерашняя', userId: 'тимур', openedAt: at('2026-09-29T15:16:00Z') };
    const сегодня = { id: 'сегодняшняя', userId: 'тимур', openedAt: at('2026-09-30T06:18:00Z') };
    expect(drawerShiftFor([вчера, сегодня], 'тимур')).toBe('сегодняшняя');
    expect(drawerShiftFor([сегодня, вчера], 'тимур')).toBe('сегодняшняя');
  });

  it('при равном времени открытия — всегда одна и та же', () => {
    /* Одинаковый ответ здесь и в разборе записей без ссылки важнее
       «правильного»: разойдясь, они дали бы пару чисел про один ящик. */
    const одна = { id: 'aaa', userId: 'тимур', openedAt: at('2026-09-30T06:00:00Z') };
    const другая = { id: 'bbb', userId: 'тимур', openedAt: at('2026-09-30T06:00:00Z') };
    expect(drawerShiftFor([одна, другая], 'тимур')).toBe('aaa');
    expect(drawerShiftFor([другая, одна], 'тимур')).toBe('aaa');
  });

  it('владельцу без своей смены — в единственную открытую на точке', () => {
    // Владелец оформляет возврат со своего телефона, пока за кассой кассир.
    const shifts = [{ id: 'кассира', userId: 'вера', openedAt: at('2026-09-30T06:00:00Z') }];
    expect(drawerShiftFor(shifts, 'владелец')).toBe('кассира');
  });

  it('а если открытых несколько и ни одна не твоя — ни в какую', () => {
    /* У каждой кассы свой ящик, и угадывать, в какой из них положили деньги,
       не по чему: ошибка переносит деньги между ящиками разных людей. */
    const shifts = [
      { id: 'первая', userId: 'вера', openedAt: at('2026-09-30T06:00:00Z') },
      { id: 'вторая', userId: 'асель', openedAt: at('2026-09-30T07:00:00Z') },
    ];
    expect(drawerShiftFor(shifts, 'владелец')).toBeNull();
  });

  it('и когда открытых нет вовсе — тоже ни в какую', () => {
    expect(drawerShiftFor([], 'тимур')).toBeNull();
  });

  it('смена без кассира своей не считается', () => {
    // Поля `userId` когда-то не было; сверять его не с чем, а угадывать нельзя.
    const shifts = [
      { id: 'ничья', userId: null, openedAt: at('2026-09-30T06:00:00Z') },
      { id: 'чужая', userId: 'вера', openedAt: at('2026-09-30T07:00:00Z') },
    ];
    expect(drawerShiftFor(shifts, 'тимур')).toBeNull();
  });
});
