/**
 * Сдача с наличных.
 *
 * Экран подтверждения наличной оплаты состоял из иконки и строки «Наличные ·
 * 200 ₸»: касса принимала деньги, но не считала сдачу. Считал кассир — в уме,
 * при очереди, в конце смены. Ошибка на этом месте не теряется и не находится:
 * она становится той самой недостачей в ящике, про которую наутро спрашивает
 * владелец, и объяснить её к тому времени уже некому.
 *
 * Поле необязательное. Покупатель, давший без сдачи, — обычное дело, и
 * заставлять кассира вводить сумму ради формы значит добавить действие к
 * каждой продаже. Поэтому это калькулятор, а не шаг: ввели — посчитает, не
 * ввели — ничего не изменится. На сервер сумма не уходит: чек от неё не
 * зависит, а лишнее поле в документе пришлось бы поддерживать вечно.
 */

/** Банкноты, которые реально дают в руки. */
const NOTES = [200, 500, 1000, 2000, 5000, 10000, 20000];

const roundUpTo = (value: number, step: number) => Math.ceil(value / step) * step;

/**
 * Что покупатель, скорее всего, протянет за чек на эту сумму.
 *
 * Банкноты выше суммы плюс круглые числа над ней: чек на 3 400 гасят пятью
 * тысячами, но и «4 000» тремя бумажками — тоже обычный расчёт. Сама сумма
 * чека сюда не входит: «без сдачи» стоит на экране отдельной кнопкой и не
 * должна теряться среди остальных.
 */
export function suggestedCashAmounts(total: number, limit = 4): number[] {
  if (!Number.isFinite(total) || total <= 0) return [];
  const candidates = new Set<number>([
    ...NOTES,
    roundUpTo(total, 500),
    roundUpTo(total, 1000),
    roundUpTo(total, 5000),
  ]);
  return [...candidates]
    .filter((amount) => amount > total)
    .sort((a, b) => a - b)
    .slice(0, limit);
}

/**
 * Сколько отдать назад.
 *
 * `null` — когда считать нечего: поле пустое, введён мусор или денег дали
 * ровно. Ноль от `null` здесь отличается тем, что ноль пришлось бы показывать
 * строкой «Сдача: 0 ₸», а это шум на экране, который кассир видит на каждой
 * продаже.
 */
export function cashChange(total: number, received: number): number | null {
  if (!Number.isFinite(received) || received <= total) return null;
  return Math.round(received - total);
}

/**
 * Сколько не хватает, если дали меньше суммы чека.
 *
 * Не запрет, а подсказка: касса не мешает пробить чек — деньги могли добрать
 * картой или монетой из блюдца, и отказ здесь останавливал бы продажу ради
 * аккуратности калькулятора.
 */
export function cashShortfall(total: number, received: number): number | null {
  if (!Number.isFinite(received) || received <= 0 || received >= total) return null;
  return Math.round(total - received);
}

/** Строка из поля ввода — в число, с запятой вместо точки и пробелами внутри. */
export function parseCashInput(raw: string): number {
  const cleaned = raw.replace(/\s/g, '').replace(',', '.');
  if (cleaned === '') return NaN;
  return Number(cleaned);
}
