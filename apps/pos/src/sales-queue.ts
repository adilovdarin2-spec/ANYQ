import type { Sale } from './types';

/**
 * Что в очереди продаж лежит и почему.
 *
 * Три состояния, и путать их нельзя. Отправленная — это выручка, которую
 * владелец видит в сводке. Ожидающая — та, что уйдёт сама, как только будет
 * связь; про неё кассиру говорят «не отправлено» и больше ничего не требуют.
 * Отказанная — та, которую сервер посмотрел и не принял: деньги взяты, товар
 * унесли, а в учёте продажи нет. Она не уйдёт сама никогда, и пока её кто-то
 * не разберёт, смена не сойдётся.
 *
 * Разделено сюда, потому что раньше это был один и тот же фильтр, написанный
 * в трёх местах по памяти, и достаточно было в одном из них забыть
 * `&& !s.syncError`, чтобы отказанная продажа считалась ожидающей — то есть
 * чтобы касса каждые двадцать секунд обещала отправить то, что уже отвергли.
 */
export interface SalesQueue {
  /** Уйдут сами, как только будет связь. */
  pending: Sale[];
  /** Сервер отказал, с объяснением в `syncError`. Ждут человека. */
  stuck: Sale[];
}

export function splitQueue(sales: Sale[]): SalesQueue {
  const pending: Sale[] = [];
  const stuck: Sale[] = [];
  for (const sale of sales) {
    if (sale.synced) continue;
    if (sale.syncError) stuck.push(sale);
    else pending.push(sale);
  }
  return { pending, stuck };
}

/**
 * Забыть отказ и попробовать снова.
 *
 * Саму продажу не трогаем: у неё тот же идентификатор, та же корзина и то же
 * время, когда её пробили. Повтор для сервера — это тот же чек, а не новый,
 * и второй раз списать остаток он не может.
 */
export function clearRefusal(sales: Sale[], id: string): Sale[] {
  return sales.map((sale) => (sale.id === id ? { ...sale, syncError: undefined } : sale));
}
