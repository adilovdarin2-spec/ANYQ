/**
 * Сколько магазину осталось работать, и когда он об этом узнаёт.
 *
 * ANYQ работает локально и выходит в сеть иногда. Сервер здесь — не место, где
 * лежит товар, а место, где написано, оплачен ли месяц: касса спрашивает его
 * раз в час и живёт с последним ответом.
 *
 * Отсюда три правила, и все три — про то, чего делать нельзя.
 *
 * **Без сети касса торгует.** Магазин, переставший продавать из-за того, что у
 * него отвалился интернет, — это не защита лицензии, это сломанный магазин. Час
 * без ответа не отказ, а повод сказать «подключите интернет».
 *
 * **Дата, а не «пока работает».** До 15.09.2026 тариф читался один раз, на
 * входе, а токен кассы живёт тридцать дней. Магазин, у которого тариф кончился
 * в понедельник, узнавал об этом при следующем входе — то есть мог узнать через
 * неделю. Продление работало так же медленно и в обратную сторону: владелец
 * заплатил, а касса до утра считала, что нет.
 *
 * **Напоминание, которое не сливается с фоном.** Полоска «тариф заканчивается»
 * висит последние сутки поверх каждого экрана, и человек, видевший её сто раз,
 * перестаёт её видеть. Поэтому в последние сутки касса ещё и спрашивает — раз
 * в четыре часа, с кнопкой, которую надо нажать.
 *
 * Здесь только счёт времени: часы, а не запросы. Всё, что ходит в сеть, — в
 * `useLicence`.
 */

/** Раз в час. Записано в docs/DECISIONS.md как решение владельца. */
export const CHECK_EVERY_MS = 60 * 60 * 1000;

/**
 * Столько молчания — и касса говорит «подключите интернет».
 *
 * Ровно тот же час: касса спрашивает раз в час, и если час прошёл, а
 * подтверждения нет, значит один запрос уже не дошёл. Меньше — и полоска
 * замигает на каждом обрыве связи; больше — и магазин, у которого интернет
 * умер утром, узнает об этом к обеду.
 */
export const SILENCE_BEFORE_NOTICE_MS = 60 * 60 * 1000;

/** В последние сутки — каждые 4 часа. Тоже решение владельца. */
export const REMIND_EVERY_MS = 4 * 60 * 60 * 1000;

/** Последние сутки — это `daysLeft <= 1`: сегодня или завтра. */
export const REMIND_FROM_DAYS = 1;

/**
 * Пора ли спросить сервер.
 *
 * `null` — ещё ни разу: спрашиваем сразу. Это первый запуск кассы или сессия,
 * поднятая из хранилища после перезагрузки, и оба случая — повод узнать, что
 * изменилось, пока кассы не было.
 */
export function dueForCheck(now: number, lastCheckedAt: number | null): boolean {
  if (lastCheckedAt === null) return true;
  // Часы на планшете переводят, и назад тоже. Отрицательная разница означает,
  // что «последний раз» оказался в будущем, — спрашиваем, а не ждём молча до
  // тех пор, пока время не догонит.
  return now - lastCheckedAt >= CHECK_EVERY_MS || now < lastCheckedAt;
}

/**
 * Давно ли касса в последний раз говорила с сервером.
 *
 * Считается от подтверждения, а не от попытки: касса, которая раз в час
 * безуспешно стучится в мёртвый Wi-Fi, не «на связи».
 *
 * `null` — подтверждения не было вовсе. Это сессия, прожившая перезагрузку без
 * сети, и молчать про неё нельзя: касса не знает про магазин ничего свежего.
 */
export function outOfTouch(now: number, lastConfirmedAt: number | null): boolean {
  if (lastConfirmedAt === null) return true;
  if (now < lastConfirmedAt) return false;
  return now - lastConfirmedAt >= SILENCE_BEFORE_NOTICE_MS;
}

/**
 * Пора ли напомнить про конец тарифа.
 *
 * Только в последние сутки и только раз в четыре часа. Вне последних суток —
 * никогда: полоска за неделю уже сказана на открытии смены, и будить человека
 * окном каждые четыре часа всю неделю значит научить его закрывать это окно не
 * читая.
 *
 * `daysLeft < 0` — тариф уже кончился. Напоминать не о чем: касса к этому
 * моменту уже не пишет, и об этом ей скажет сервер, а не таймер.
 *
 * Переведённые назад часы здесь, в отличие от `dueForCheck`, означают «молчим»,
 * а не «спрашиваем». Разница намеренная и стоила одного живого бага: «сейчас»
 * в кассе пересчитывается раз в минуту, а «напомнили» ставится в момент
 * нажатия, то есть почти всегда оказывается чуть в будущем относительно него.
 * Правило «будущее — значит часы перевели, напоминай» превращало кнопку
 * «понятно» в кнопку, которая ничего не закрывает. Лишний запрос стоит ничего,
 * а окно, которое не закрывается, стоит смены.
 */
export function dueForReminder(
  daysLeft: number | null | undefined,
  now: number,
  lastRemindedAt: number | null,
): boolean {
  if (daysLeft === null || daysLeft === undefined) return false;
  if (daysLeft < 0 || daysLeft > REMIND_FROM_DAYS) return false;
  if (lastRemindedAt === null) return true;
  return now - lastRemindedAt >= REMIND_EVERY_MS;
}
