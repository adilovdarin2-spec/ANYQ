/**
 * Код маркировки: разобрать то, что прислал сканер. Копия серверного разбора.
 *
 * **Копия намеренная, и её держит проверка.** Касса разбирает код ради одного:
 * узнать по GTIN, какой товар положить в корзину, — сканер подносят к пачке
 * один раз, и отдельно искать штрихкод кассир не станет. Решает при этом всё
 * равно сервер: касса шлёт ему сырую строку, и если разборы разойдутся, сервер
 * ответит «код от другого товара», а не запишет чужую пачку.
 *
 * Общего пакета для такой мелочи в проекте нет, а заводить его ради одного
 * файла дороже, чем держать две копии под охраной. Так же здесь устроены
 * деньги: `cart.test.ts` гоняет кассовую и серверную арифметику по одним
 * данным. `marking-parity.test.ts` делает то же самое с этим разбором — если
 * копии разойдутся хоть на одном коде, он покажет, на каком.
 *
 * На пачке сигарет, коробке обуви и упаковке лекарства напечатан Data Matrix.
 * Внутри — строка GS1: пары «идентификатор применения + значение», без
 * разделителей там, где длина известна заранее, и с разделителем там, где нет.
 *
 * Нам из неё нужны две вещи и обе обязательны:
 *
 *   - **GTIN** (`01`, ровно 14 цифр) — что это за товар. По нему код
 *     связывается с карточкой: продать код от сигарет, пробив молоко, нельзя.
 *   - **Серийный номер** (`21`, до 20 знаков) — какая именно пачка. Он и
 *     делает код одноразовым: две пачки одного товара различаются только им.
 *
 * Остальное — цена (`8005`), криптохвост (`93`), дата (`17`) — читается и
 * выбрасывается. Хранить криптохвост нам незачем: проверяет его государственная
 * система, а у нас он занимал бы место и создавал ложное ощущение, что мы
 * что-то с ним делаем.
 *
 * **Чего этот разбор не делает и не должен.** Он не проверяет, что код
 * настоящий, — это умеет только ИС МПТ, и пока к ней нет доступа, мы честно
 * говорим о себе меньше, чем хотелось бы. Зато он полностью отвечает за то,
 * что в нашей собственной базе один код нельзя продать дважды и нельзя продать
 * тот, которого мы не принимали. Это не вся маркировка, но это та её часть,
 * которая каждый день стоит денег.
 */

/** Разделитель групп: им заканчиваются поля переменной длины. */
const GS = '';

/** У этих идентификаторов длина значения фиксирована — разделитель не нужен. */
const FIXED_LENGTH: Record<string, number> = {
  '00': 18,
  '01': 14,
  '02': 14,
  '11': 6,
  '12': 6,
  '13': 6,
  '15': 6,
  '17': 6,
  '20': 2,
};

export interface MarkedCode {
  /** Что за товар — 14 цифр. */
  gtin: string;
  /** Какая именно единица. */
  serial: string;
}

export type MarkingParse =
  | { ok: true; code: MarkedCode }
  | { ok: false; reason: 'empty' | 'noGtin' | 'noSerial' | 'malformed' };

/**
 * Разобрать строку из сканера.
 *
 * Сканер работает как клавиатура и присылает то, что напечатано, — включая
 * невидимый разделитель групп. Некоторые модели присылают вместо него ``,
 * другие ничего: во втором случае поле переменной длины тянется до следующего
 * знакомого идентификатора, и это единственное место, где разбор может ошибиться
 * на длинном серийнике. Поэтому серийник обрезается по разделителю, если он
 * есть, и по следующему известному идентификатору, если нет.
 */
export function parseMarkedCode(raw: unknown): MarkingParse {
  if (typeof raw !== 'string') return { ok: false, reason: 'empty' };
  // Некоторые сканеры оборачивают код в скобки по стандарту печати: (01)…(21)…
  const text = raw.trim().replace(/[()]/g, '');
  if (!text) return { ok: false, reason: 'empty' };

  let gtin: string | null = null;
  let serial: string | null = null;
  let i = 0;

  while (i < text.length) {
    // Идентификатор — две цифры; у некоторых он длиннее, но все, что нас
    // касаются, начинаются с двузначного, а длинные (`8005`, `240`) мы просто
    // пропускаем до следующего разделителя.
    const ai = text.slice(i, i + 2);
    if (!/^\d{2}$/.test(ai)) return { ok: false, reason: 'malformed' };
    i += 2;

    const fixed = FIXED_LENGTH[ai];
    if (fixed !== undefined) {
      const value = text.slice(i, i + fixed);
      if (value.length < fixed) return { ok: false, reason: 'malformed' };
      i += fixed;
      if (ai === '01') gtin = value;
      continue;
    }

    // Переменная длина: до разделителя, а если его нет — до конца строки.
    const end = text.indexOf(GS, i);
    const value = end === -1 ? text.slice(i) : text.slice(i, end);
    i = end === -1 ? text.length : end + 1;
    if (ai === '21') serial = value;
  }

  if (!gtin) return { ok: false, reason: 'noGtin' };
  if (!serial) return { ok: false, reason: 'noSerial' };
  // Серийник до двадцати знаков по стандарту; длиннее — это не серийник, а
  // склеенные поля, и принимать такое значит однажды объявить две разные пачки
  // одной.
  if (serial.length > 20) return { ok: false, reason: 'malformed' };

  return { ok: true, code: { gtin, serial } };
}

/**
 * Как код хранится и ищется — одной строкой.
 *
 * Не сырой текст со сканера: у одной и той же пачки он приходит по-разному —
 * со скобками, с разделителем и без, с криптохвостом и без него, если кассир
 * поднёс сканер дважды. Ключ — то, что делает пачку этой пачкой: товар и
 * серийник.
 */
export function markedCodeKey(code: MarkedCode): string {
  return `${code.gtin}:${code.serial}`;
}
