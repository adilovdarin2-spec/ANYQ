import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { withoutComments } from '../../../scripts/lib/source-text.mjs';

/**
 * Свой счёт ящика касса ведёт по числу, а не по способу возврата.
 *
 * Счёт нужен ей на закрытии смены без сети, и он обязан сойтись с серверным:
 * два числа про один ящик кассир объяснить не сможет, а отвечает за них он.
 *
 * Пока у возврата был один способ, хватало его: наличный — вычесть, в долг —
 * нет. С 25.09.2026 у возврата по разбитому чеку способ `mixed`, и счёт по
 * способу вычел бы ноль — то есть показал бы недостачу ровно на те наличные,
 * которые кассир отдал покупателю на глазах у всех. Ровно та ошибка, ради
 * которой этот счёт и заводили.
 *
 * Поэтому сервер присылает `cashRefunded` — сколько ушло из ящика, — и считает
 * его той же функцией, которой считает сверка. Касса берёт число.
 *
 * Поле необязательное: сервер и касса выкатываются по отдельности, и ответ
 * версии старше этого поля не несёт. Запасной путь — прежний счёт по способу.
 */

const APP = resolve(__dirname, 'App.tsx');
const API = resolve(__dirname, 'api.ts');

const read = (path: string) => withoutComments(readFileSync(path, 'utf8').replace(/\r\n/g, '\n'));

describe('счёт ящика в кассе', () => {
  const app = read(APP);
  const api = read(API);

  it('файлы вообще разобрались', () => {
    // Иначе первое, что докажет этот файл, — что он находит что угодно.
    expect(app.length).toBeGreaterThan(10000);
    expect(api).toContain('CreateReturnResult');
  });

  it('берёт число от сервера, а не выводит его из способа', () => {
    expect(api, 'сервер больше не обещает этого числа').toContain('cashRefunded?: number;');
    expect(app).toContain('made.cashRefunded ??');
  });

  it('и на старом ответе считает по-старому', () => {
    /* Выкат врозь: касса может получить ответ сервера, который этого поля ещё
       не знает. Убрать запасной путь значило бы перестать вычитать наличные
       возвраты вовсе — то есть вернуть ту же недостачу, только всем. */
    expect(app).toContain("made.paymentMethod === 'cash' ? made.refundAmount : 0");
  });

  it('а запись в ящик появляется только когда из него правда взяли', () => {
    // По чеку в долг денег не выдают: запись на ноль читалась бы как выдача.
    expect(app).toContain('if (shift && ушлоИзЯщика > 0) {');
    // И записывается она наличными — потому что это уже наличная часть.
    const запись = app.slice(app.indexOf('if (shift && ушлоИзЯщика > 0) {'));
    expect(запись.slice(0, запись.indexOf('});'))).toContain("method: 'cash'");
  });
});
