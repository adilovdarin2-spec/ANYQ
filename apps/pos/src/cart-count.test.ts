import { describe, it, expect } from 'vitest';
import { cartCount } from './cart';

/**
 * Счётчик корзины не складывает штуки с килограммами.
 *
 * Найдено 29.09.2026 прогоном дня магазина руками. Две бутылки воды и 350
 * граммов сыра давали на кнопке «2.35 в корзине»: сумма всех `qty` подряд, в
 * которой килограммы сложены со штуками. Деньги при этом считались верно —
 * поймать это можно было только глазами, и ни один тест этого не ловил.
 *
 * Число на кнопке кассир сверяет с тем, что лежит перед ним на прилавке.
 * Поэтому весовая строка считается за одну вещь — это один кусок сыра, сколько
 * бы он ни весил, — а штучные складываются как раньше.
 */

describe('сколько вещей в корзине', () => {
  it('штучные складываются', () => {
    expect(cartCount([{ qty: 2 }, { qty: 3 }])).toBe(5);
  });

  it('весовая строка — одна вещь, какой бы вес в ней ни стоял', () => {
    expect(cartCount([{ qty: 0.35, saleUnit: 'weight' }])).toBe(1);
    expect(cartCount([{ qty: 12.5, saleUnit: 'weight' }])).toBe(1);
  });

  it('и смешанная корзина даёт целое число', () => {
    /* Тот самый случай: две бутылки и кусок сыра — это три вещи на прилавке,
       а не «2.35». */
    const count = cartCount([
      { qty: 2, saleUnit: 'piece' },
      { qty: 0.35, saleUnit: 'weight' },
    ]);
    expect(count).toBe(3);
    expect(Number.isInteger(count), 'на кнопке снова дробное число').toBe(true);
  });

  it('и любая смесь остаётся целой', () => {
    /* Свойством, а не примером: дробное число на кнопке не должно появиться ни
       при каком наборе весовых строк. */
    for (const вес of [0.001, 0.35, 1.5, 12.345, 999.999]) {
      for (const штук of [0, 1, 7]) {
        const lines = [{ qty: штук, saleUnit: 'piece' }, { qty: вес, saleUnit: 'weight' }];
        expect(Number.isInteger(cartCount(lines)), `${штук} шт + ${вес} кг`).toBe(true);
      }
    }
  });

  it('пустая корзина — ноль', () => {
    // По этому нулю касса решает, показывать ли кнопку вообще.
    expect(cartCount([])).toBe(0);
  });

  it('строка без единицы считается штучной', () => {
    // Старые записи и всё, что пришло без `saleUnit`: вести себя как раньше.
    expect(cartCount([{ qty: 4 }])).toBe(4);
  });
});
