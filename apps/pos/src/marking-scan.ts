import { markedCodeKey, parseMarkedCode } from './marking';
import type { MarkedCode } from './marking';

/**
 * Data Matrix на пачке заменяет штрихкод, а не добавляется к нему.
 *
 * Кассир подносит сканер к пачке один раз. Просить его после этого найти на
 * той же пачке обычный штрихкод и поднести ещё раз — значит удвоить работу на
 * каждой пачке сигарет, а сигареты в продуктовом пробивают весь день.
 *
 * Поэтому код маркировки сам находит товар: внутри него есть GTIN, а GTIN — это
 * тот же штрихкод, дополненный нулями слева до четырнадцати знаков. Один
 * поднос сканера кладёт товар в корзину и прикладывает к нему код.
 *
 * **Почему сравнение по «дополненному нулями», а не по строке.** Магазин
 * заводит товар с тем штрихкодом, который напечатан на упаковке: тринадцать
 * знаков (EAN-13), иногда восемь (EAN-8), изредка двенадцать (UPC-A). В коде
 * маркировки он всегда четырнадцать. Сравнивать как есть — значит не найти ни
 * один товар и объявить всю маркировку неработающей, притом что данные верные.
 */

export interface ScannedMarking {
  code: MarkedCode;
  /** Товар, если он нашёлся по GTIN. */
  productId: string | null;
}

/** GTIN и штрихкод — одно и то же число; разной бывает только длина записи. */
function sameArticle(gtin: string, barcode: string): boolean {
  const left = gtin.replace(/^0+/, '');
  const right = barcode.trim().replace(/^0+/, '');
  // Пустой штрихкод у товара — это «не заполнили», и совпадать с ним не должно
  // ничего: иначе первый же товар без штрихкода станет ответом на любой код.
  if (!right) return false;
  return left === right;
}

/**
 * Разобрать то, что пришло со сканера, если это код маркировки.
 *
 * `null` — значит это не код маркировки, и обрабатывать ввод надо как раньше.
 * Отличать одно от другого по длине или по первым цифрам нельзя: код
 * маркировки начинается с `01`, и с тех же цифр начинается вполне настоящий
 * штрихкод. Единственный надёжный признак — разбирается ли строка целиком как
 * GS1, и это решает сам разбор.
 */
export function readScannedMarking(
  raw: string,
  products: { id: string; barcode: string }[],
): ScannedMarking | null {
  const parsed = parseMarkedCode(raw);
  if (!parsed.ok) return null;

  const match = products.find((p) => sameArticle(parsed.code.gtin, p.barcode));
  return { code: parsed.code, productId: match?.id ?? null };
}

/**
 * Одна ли это пачка — по смыслу, а не по строке.
 *
 * Кассир мог не понять, сработал ли сканер, и поднести его к той же пачке ещё
 * раз. Сравнивать сырые строки нельзя: один и тот же код приходит то со
 * скобками, то с разделителем, то с криптохвостом, и строки будут разные, а
 * пачка одна. Принять это за вторую пачку значит пробить товар, которого на
 * прилавке нет.
 */
export function sameMarkedCode(a: string, b: string): boolean {
  const left = parseMarkedCode(a);
  const right = parseMarkedCode(b);
  if (!left.ok || !right.ok) return false;
  return markedCodeKey(left.code) === markedCodeKey(right.code);
}
