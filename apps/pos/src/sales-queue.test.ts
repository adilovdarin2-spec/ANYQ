import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { clearRefusal, splitQueue } from './sales-queue';
import type { Sale } from './types';

/**
 * Продажа, которую сервер не принял, должна дойти до человека.
 *
 * Так это выглядело до сих пор. Кассир пробивает чек на последнюю пачку,
 * сервер отвечает «Недостаточно товара на складе» — потому что эту пачку уже
 * списали на другой кассе. Касса запоминает отказ вместе с причиной, рисует в
 * шапке «1 требует внимания» и на этом останавливается: причина лежит в
 * localStorage и не показывается нигде. Кассир не знает, какой из сегодняшних
 * тридцати чеков не прошёл; владелец слышит «что-то там не отправилось».
 * Деньги в ящике есть, в отчёте их нет, и разбирается это вечером вычитанием.
 *
 * Поэтому проверяется: ожидающая продажа и отказанная — разные вещи, отказ
 * несёт объяснение, а повтор отправляет тот же самый чек, а не новый.
 */

const продажа = (over: Partial<Sale>): Sale =>
  ({
    id: 's1',
    shiftId: 'shift-1',
    locationId: 'loc-1',
    items: [],
    total: 1200,
    discount: null,
    discountAmount: 0,
    paymentMethod: 'cash',
    createdAt: '2026-09-12T09:15:00.000Z',
    synced: false,
    ...over,
  }) as Sale;

describe('очередь продаж', () => {
  it('отправленных в очереди нет', () => {
    const { pending, stuck } = splitQueue([продажа({ id: 'a', synced: true })]);
    expect(pending).toEqual([]);
    expect(stuck).toEqual([]);
  });

  it('ожидающая — это не отказанная', () => {
    // Ровно то место, где их путали: отказанная попадала в «не отправлено»,
    // и касса обещала отправить то, что уже отвергли.
    const { pending, stuck } = splitQueue([
      продажа({ id: 'ждёт' }),
      продажа({ id: 'отказ', syncError: 'Недостаточно товара на складе' }),
    ]);
    expect(pending.map((s) => s.id)).toEqual(['ждёт']);
    expect(stuck.map((s) => s.id)).toEqual(['отказ']);
  });

  it('отказ несёт причину, а не только факт', () => {
    const { stuck } = splitQueue([продажа({ syncError: 'Цены изменились — выйдите и войдите в кассу заново' })]);
    expect(stuck[0].syncError).toBe('Цены изменились — выйдите и войдите в кассу заново');
  });

  it('повтор отправляет тот же чек', () => {
    // Идентификатор, время и корзина обязаны остаться прежними: по
    // идентификатору сервер узнаёт повтор и не проводит продажу дважды.
    const до = продажа({ id: 'чек-7', syncError: 'Товар разобрали на другой кассе — повторите продажу' });
    const [после] = clearRefusal([до], 'чек-7');

    expect(после.syncError).toBeUndefined();
    expect(после.id).toBe('чек-7');
    expect(после.createdAt).toBe(до.createdAt);
    expect(после.total).toBe(до.total);
    expect(после.synced).toBe(false);
  });

  it('повтор всех снимает отказ с каждой', () => {
    // Причина у них обычно общая — не хватило остатка, кончился тариф, — и
    // чинят её один раз. Нажимать «ещё раз» на каждом из тридцати чеков
    // офлайн-утра человек не станет.
    let списком = [
      продажа({ id: 'a', syncError: 'Недостаточно товара на складе' }),
      продажа({ id: 'b', syncError: 'Недостаточно товара на складе' }),
      продажа({ id: 'c', synced: true }),
    ];
    for (const s of splitQueue(списком).stuck) списком = clearRefusal(списком, s.id);

    expect(splitQueue(списком).stuck).toEqual([]);
    expect(splitQueue(списком).pending.map((s) => s.id)).toEqual(['a', 'b']);
  });

  it('повтор одной не трогает остальные', () => {
    const списком = [
      продажа({ id: 'a', syncError: 'Недостаточно товара на складе' }),
      продажа({ id: 'b', syncError: 'Баллы клиента изменились — повторите продажу' }),
    ];
    const после = clearRefusal(списком, 'a');
    expect(после[1].syncError).toBe('Баллы клиента изменились — повторите продажу');
  });
});

describe('отказ виден кассиру', () => {
  // Разбор исходника, потому что DOM в этих тестах нет. Проверяется не
  // вёрстка, а то, что причина вообще доходит до экрана: без этой строки
  // весь разбор выше — работа в стол.
  const профиль = readFileSync(join(__dirname, 'components/ProfileScreen.tsx'), 'utf8');

  it('на экране профиля печатается причина отказа', () => {
    expect(профиль).toContain('sale.syncError');
  });

  it('и кнопка отправить ещё раз', () => {
    expect(профиль).toContain('onRetryStuck(sale.id)');
  });

  it('чек не называет отказ ожиданием', () => {
    // «не синхронизирован» под отказанной продажей читается как «уйдёт само».
    const чек = readFileSync(join(__dirname, 'components/ReceiptScreen.tsx'), 'utf8');
    expect(чек).toContain('receipt.refused');
  });
});
