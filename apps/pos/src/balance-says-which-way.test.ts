import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { withoutComments } from '../../../scripts/lib/source-text.mjs';

/**
 * Сальдо названо по знаку, а не по вкладке.
 *
 * Магазин заплатил поставщику и вернул ему часть товара — долг ушёл в минус, и
 * карточка написала «МЫ ДОЛЖНЫ −100 ₸». Владелец читает «мы должны минус сто
 * тенге» и не понимает ничего, хотя новость простая и приятная: это поставщик
 * должен нам.
 *
 * С покупателем то же самое в другую сторону: заплатил вперёд или вернул
 * оплаченное — «ДОЛЖЕН −2 000 ₸».
 *
 * Подпись бралась по вкладке, на которой стоит человек, а вкладка про сторону
 * отношений, а не про то, кто кому должен сегодня. Возврат поставщику после
 * оплаты — обычное дело в продуктовом: брак замечают уже после расчёта.
 *
 * Найдено 30.09.2026 прогоном возврата поставщику руками.
 */

const SCREEN = withoutComments(
  readFileSync(resolve(__dirname, 'components', 'SettlementsScreen.tsx'), 'utf8'),
).replace(/\r\n/g, '\n');

describe('карточка расчётов', () => {
  it('исходник разобрался', () => {
    expect(SCREEN).toContain('card-answer');
    expect(SCREEN).toContain('account.balance');
  });

  it('смотрит на знак сальдо, а не только на вкладку', () => {
    expect(SCREEN, 'подпись снова зависит только от вкладки').toContain('account.balance < 0');
    expect(SCREEN, 'нечего сказать про долг поставщика перед нами').toContain("'settle.supplierOwesUs'");
    expect(SCREEN, 'нечего сказать про переплату покупателя').toContain("'settle.weOweCustomer'");
  });

  it('и показывает сумму без минуса', () => {
    /* «Мы должны −100 ₸» и «Поставщик должен нам −100 ₸» одинаково нечитаемы:
       знак уже сказан словами. */
    expect(SCREEN, 'сумма снова со знаком').toContain('formatMoney(Math.abs(account.balance))');
  });

  it('а поле платежа не подставляет ноль, который нечем провести', () => {
    /* При нулевом или отрицательном сальдо там стояло «0», и «Провести» молча
       не делала ничего: платёж в ноль сервер не принимает. */
    expect(SCREEN).toContain("account.balance > 0 ? String(account.balance) : ''");
  });
});
