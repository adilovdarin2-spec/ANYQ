/** Что заставило кассу задуматься об обновлении каталога. */
export type RefreshTrigger = 'open' | 'visible' | 'online' | 'tick';

export interface RefreshContext {
  /** Есть ли сеть по мнению устройства. */
  online: boolean;
  /** Смотрят ли сейчас на этот экран. */
  visible: boolean;
  /** Сколько строк в корзине. */
  cartLines: number;
  /** Сколько прошло с прошлого обновления, мс. */
  sinceLastMs: number;
}

/** Ближе, чем это, два обновления подряд ничего не добавляют. */
export const REFRESH_DEBOUNCE_MS = 5_000;

/**
 * Стоит ли перечитывать каталог прямо сейчас.
 *
 * Вопрос неочевидный, и каждое «нет» здесь стоит отдельно:
 *
 * **Нет сети** — обновлять нечем, а касса обязана работать неделю без неё.
 *
 * **В корзине что-то есть** — менять плитки под пальцем посреди чека значит
 * двигать цель в ту секунду, когда кассиру нужно, чтобы экран стоял на месте.
 * Итог чека от этого не зависит: цена запоминается в строке корзины, а продажу
 * сверх остатка всё равно отклонит сервер.
 *
 * **Таймер в свёрнутой вкладке** — трафик ради экрана, на который никто не
 * смотрит. А вот открытие кассы обновляет независимо от видимости: цифры
 * покажут, как только на них посмотрят, и они должны быть свежими.
 *
 * **Только что обновляли** — возвращение сети и возвращение видимости часто
 * случаются одной секундой, и второй запрос подряд не добавляет ничего.
 *
 * Зачем это вообще: сессия с товарами лежит в localStorage и переживает
 * перезагрузку — иначе касса не открылась бы без сети. Но пока каталог никто не
 * перечитывал, плитки показывают цифры того момента, когда эта касса последний
 * раз входила. Вторая касса продала последний хлеб — здесь по-прежнему «ост.
 * 39», и кассир обещает покупателю то, чего нет.
 */
export function shouldRefreshCatalog(trigger: RefreshTrigger, ctx: RefreshContext): boolean {
  if (!ctx.online) return false;
  if (ctx.cartLines > 0) return false;
  if (trigger === 'tick' && !ctx.visible) return false;
  if (ctx.sinceLastMs < REFRESH_DEBOUNCE_MS) return false;
  return true;
}
