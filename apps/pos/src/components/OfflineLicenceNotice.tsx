import { useTranslation } from '../i18n/useLanguage';

/**
 * «Подключите интернет».
 *
 * Не то же самое, что плашка «офлайн» в шапке. Та говорит про продажи: они
 * складываются в очередь и уйдут, когда сеть вернётся. Эта — про лицензию:
 * ANYQ уже час не может спросить, оплачен ли месяц, и значит продление,
 * заморозка и смена тарифа до этой кассы не дойдут, пока сеть не появится.
 *
 * Торговать при этом никто не мешает и мешать не должен: магазин без интернета
 * не перестаёт быть магазином. Поэтому здесь спокойная полоска, а не отказ.
 */
export function OfflineLicenceNotice() {
  const { t } = useTranslation();
  return (
    <div className="licence-offline" role="status">
      <strong>{t('licence.offline')}</strong>
      <span>{t('licence.offlineWhat')}</span>
    </div>
  );
}
