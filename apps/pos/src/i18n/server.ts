/**
 * What the server said, in the cashier's language.
 *
 * The register's own interface is translated key-by-key: the code holds a
 * `PhraseKey` and the dictionary decides the words. The server cannot work that
 * way. It does not know which language the device in front of the cashier is
 * set to — the switch lives on the device, and a request carries no language —
 * so it answers in Russian, and always has.
 *
 * The honest fix is for the server to answer with a reason code and let the
 * device choose the words. That is a real change to every route and a change to
 * the shape of the API, and it is not a translation. Until then, this: the
 * message the server sent *is* the key. The register recognises it and says the
 * same thing in Kazakh; anything it does not recognise is shown exactly as the
 * server wrote it.
 *
 * That fallback is what makes this safe. Changing a message on the server does
 * not break the register — it drops back to Russian for that one sentence. It
 * would do so silently, which is why `server.test.ts` reads the API's own
 * source and fails when a message appears here that this file does not cover.
 * The list cannot quietly rot; it can only fail the build.
 */

