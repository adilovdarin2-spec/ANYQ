import { describe, it, expect } from 'vitest';
import { pluralPhrase } from './index';
import { ru } from './ru';
import { kk } from './kk';

/**
 * Числительное и существительное после него.
 *
 * Русский требует трёх форм: «1 место», «2 места», «5 мест». Механизм для
 * этого есть — `pluralPhrase` и тройка фраз в словаре, — но он помогает только
 * там, где им воспользовались. Пользуются им не всегда: «{count} мест» под
 * каждым столиком в зале и «Поставщик недовёз по {count} позициям» дожили до
 * сегодняшнего дня, потому что по отдельности такая строка выглядит опечаткой,
 * а не ошибкой, и глазами её ловит только тот, кто специально ищет.
 *
 * Поэтому ищет тест. Правило простое и механическое: если сразу за числом
 * стоит слово, которое склоняется, фразе нужны три формы. Слова, которые после
 * числа не меняются, перечислены ниже — предлоги, частицы и сокращения.
 * Исключения из правила названы поимённо и с причиной: список, который просто
 * перечисляет всё найденное, охраняет ошибку вместо языка.
 */

/** Что может стоять после числа, не изменяясь. */
const НЕ_СКЛОНЯЕТСЯ = new Set([
  'в', 'во', 'на', 'под', 'по', 'из', 'за', 'к', 'ко', 'с', 'со', 'до', 'от',
  'у', 'о', 'об', 'при', 'для', 'через',
  'не', 'и', 'а', 'но', 'или', 'же', 'уже', 'ещё',
]);

/**
 * Фразы, где за числом стоит склоняемое слово, а трёх форм всё равно не надо.
 * Каждая — с причиной, а не потому, что так вышло.
 */
const БЕЗ_ТРЁХ_ФОРМ: Record<string, string> = {
  'search.stockReserved':
    'безличное «обещано» — оно не меняется ни при одном числе, как «продано» или «занято»',
};

type Ключ = keyof typeof ru;

/** Слово сразу за числом, либо null, если там знак препинания или конец фразы. */
function словоПослеЧисла(phrase: string): string | null {
  const at = phrase.indexOf('{count}');
  if (at < 0) return null;
  const tail = phrase.slice(at + '{count}'.length);
  const match = tail.match(/^\s+([A-Za-zА-Яа-яЁёӘәҒғҚқҢңӨөҰұҮүҺһІі.]+)/);
  if (!match) return null;
  const word = match[1];
  // Сокращение — «дн.», «поз.», «шт.» — на письме не меняется.
  if (word.endsWith('.')) return null;
  return word.toLowerCase();
}

const счётные = (Object.entries(ru) as [Ключ, string][])
  .filter(([, phrase]) => phrase.includes('{count}'));

describe('счётные фразы', () => {
  it('в словаре вообще есть счётные фразы', () => {
    // Иначе всё остальное здесь прошло бы ни на чём.
    expect(счётные.length).toBeGreaterThan(30);
  });

  it('фраза, где за числом стоит склоняемое слово, имеет три формы', () => {
    const виноватые: string[] = [];
    for (const [key, phrase] of счётные) {
      if (/(One|Few|Many)$/.test(key)) continue;
      if (key in БЕЗ_ТРЁХ_ФОРМ) continue;
      const word = словоПослеЧисла(phrase);
      if (word && !НЕ_СКЛОНЯЕТСЯ.has(word)) виноватые.push(`${key}: «${phrase}»`);
    }
    expect(виноватые).toEqual([]);
  });

  it('у каждой тройки есть все три формы', () => {
    // Половина тройки — это ключ, которого нет: касса покажет вместо фразы
    // «range.daysFew».
    const неполные: string[] = [];
    for (const [key] of счётные) {
      const m = key.match(/^(.*)(One|Few|Many)$/);
      if (!m) continue;
      for (const form of ['One', 'Few', 'Many']) {
        if (!(`${m[1]}${form}` in ru)) неполные.push(`${m[1]}${form}`);
      }
    }
    expect([...new Set(неполные)]).toEqual([]);
  });

  it('казахский не склоняет слово после числа', () => {
    // Здесь проверяется именно слово сразу за числом, а не фраза целиком.
    // Целиком фраза меняться вправе: у «{count} мән санға ұқсамайды» дальше
    // стоит «ол сақталмайды» при одном значении и «олар сақталмайды» при
    // нескольких — это правильный казахский, местоимение с числом согласуется.
    // А вот само существительное после числительного не меняется никогда, и
    // три разных слова в тройке означали бы, что кто-то перевёл русские формы
    // по очереди, не зная этого.
    const разные: string[] = [];
    for (const [key] of счётные) {
      const m = key.match(/^(.*)One$/);
      if (!m) continue;
      const слова = ['One', 'Few', 'Many']
        .map((form) => (kk as Record<string, string>)[`${m[1]}${form}`])
        .filter(Boolean)
        .map((phrase) => словоПослеЧисла(phrase));
      if (new Set(слова).size > 1) разные.push(m[1]);
    }
    expect(разные).toEqual([]);
  });

  it('список исключений не хранит того, чего в словаре уже нет', () => {
    for (const key of Object.keys(БЕЗ_ТРЁХ_ФОРМ)) {
      expect(key in ru, `исключение для несуществующего ключа: ${key}`).toBe(true);
    }
  });
});

describe('выбор формы', () => {
  it.each([
    [1, 'One'],
    [2, 'Few'],
    [4, 'Few'],
    [5, 'Many'],
    [11, 'Many'],
    [12, 'Many'],
    [14, 'Many'],
    [21, 'One'],
    [22, 'Few'],
    [25, 'Many'],
    [101, 'One'],
    [111, 'Many'],
    [0, 'Many'],
  ])('%i мест → %s', (count, форма) => {
    expect(pluralPhrase(count as number, 'One', 'Few', 'Many' as never)).toBe(форма);
  });

  it('на настоящих фразах из словаря', () => {
    const мест = (count: number) =>
      ru[pluralPhrase(count, 'floor.seatsOne', 'floor.seatsFew', 'floor.seatsMany')].replace(
        '{count}',
        String(count),
      );
    expect(мест(1)).toBe('1 место');
    expect(мест(2)).toBe('2 места');
    expect(мест(4)).toBe('4 места');
    expect(мест(6)).toBe('6 мест');
  });
});
