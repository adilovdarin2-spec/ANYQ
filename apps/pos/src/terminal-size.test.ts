import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * Размеры за прилавком.
 *
 * Касса стоит на двух разных устройствах, и это два разных способа в неё
 * тыкать. В телефон смотрят с двадцати сантиметров и держат его в руке. В
 * терминал — монитор или большой планшет — смотрят с вытянутой руки и жмут
 * пальцем по стеклу, часто не глядя: кассир смотрит на покупателя, а не на
 * экран. Цель меньше сантиметра на таком расстоянии — это промах, а промах на
 * кассе — это очередь.
 *
 * Здесь два разных условия.
 *
 * Первое — про ошибку, которую видно только линейкой. Карточка входа стоит в
 * `.pos-shell`, а это flex-колонка; горизонтальные поля `auto` в такой колонке
 * заставляют элемент сжаться до содержимого. Карточка выходила 200 пикселей
 * вместо своих 360, клавиши PIN — по 45 вместо 98, и так было на каждом
 * устройстве с первого дня. Явная ширина это чинит, и тест сторожит именно её.
 *
 * Второе — про терминал: перечисленные цели обязаны иметь свой, увеличенный
 * размер. Не «все шрифты крупнее» — экран, где крупное всё, читается хуже, —
 * а ровно то, во что целятся пальцем и что читают на ходу.
 */

const CSS = readFileSync(join(__dirname, 'styles/global.css'), 'utf8');

/** Тело @media-блока целиком, со счётом фигурных скобок, а не по отступам. */
function mediaBlocks(condition: string): string[] {
  const found: string[] = [];
  const marker = `@media ${condition}`;
  let at = CSS.indexOf(marker);
  while (at >= 0) {
    const open = CSS.indexOf('{', at);
    let depth = 0;
    let i = open;
    for (; i < CSS.length; i++) {
      if (CSS[i] === '{') depth += 1;
      else if (CSS[i] === '}') {
        depth -= 1;
        if (depth === 0) break;
      }
    }
    found.push(CSS.slice(open + 1, i));
    at = CSS.indexOf(marker, i);
  }
  return found;
}

describe('карточка входа', () => {
  it('имеет свою ширину, а не ширину содержимого', () => {
    const card = CSS.slice(CSS.indexOf('.form-card {'), CSS.indexOf('}', CSS.indexOf('.form-card {')));
    expect(card).toContain('max-width: 360px');
    // Вот эта строка и есть починка: без неё `margin: … auto` внутри
    // flex-колонки сжимает карточку до содержимого.
    expect(card).toContain('width: 100%');
  });
});

describe('кухонный экран', () => {
  // Он висит на стене кухни, и строка блюда — единственное, что на нём
  // нажимают: повар отмечает ею готовое, не глядя, мокрой рукой или в
  // перчатке. Она была тридцати пикселей высотой — меньше, чем что-либо ещё в
  // кассе, и меньше пальца. Здесь сторожится не терминальный размер, а
  // обычный: на кухонном планшете в десять дюймов правило `min-width: 900px`
  // не срабатывает, а рука у повара та же.
  it('строка блюда — цель под палец на любом устройстве', () => {
    // С начала строки — иначе нашлось бы `.pos-shell .kds-item-row`, то есть
    // терминальное правило вместо общего, и тест сторожил бы не то.
    const at = CSS.indexOf('\n.kds-item-row {');
    const rule = CSS.slice(at, CSS.indexOf('}', at));
    expect(rule).toContain('min-height: 48px');
  });

  it('готовое блюдо видно строкой, а не значком перед ней', () => {
    // «✓» и «○» с двух метров — одно и то же пятно.
    expect(CSS).toContain('.kds-item-row.ready');
  });
});

describe('терминал', () => {
  const blocks = mediaBlocks('(min-width: 900px)');

  it('в файле есть правила для широкого экрана', () => {
    // Иначе тест ниже прошёл бы ни на чём.
    expect(blocks.length).toBeGreaterThan(0);
  });

  const терминал = () => blocks.join('\n');

  it.each([
    ['клавиша PIN', '.pin-key'],
    ['главная кнопка', '.btn'],
    ['плитка товара', '.product-tile'],
    ['счётчик количества', '.qty-stepper button'],
    ['способ оплаты', '.payment-option'],
    ['чип категории и подсказки сдачи', '.category-chip'],
    ['подпись раздела внизу экрана', '.tab-bar-item'],
    ['значок раздела внизу экрана', '.tab-bar-icon svg'],
    ['строка каталога', '.product-manage-name'],
    ['столик в зале', '.table-tile'],
    ['блюдо на кухонном экране', '.kds-item-row'],
  ])('%s получает свой размер', (_название, selector) => {
    expect(терминал()).toContain(selector);
  });

  it('полоса разделов растёт переменной, а не собственной высотой', () => {
    // От `--tab-bar-h` считаются отступ снизу у страниц и высота выпадающих
    // панелей. Полоса, выросшая в обход переменной, легла бы поверх последней
    // строки списка — то есть закрыла бы собой ровно то, до чего кассир
    // домотал.
    expect(терминал()).toContain('--tab-bar-h');
  });

  it('клавиша PIN не раздувается на всю колонку', () => {
    // Круглая клавиша тянется по ширине ячейки грида: на широкой карточке она
    // вырастала до 115 пикселей, и кнопка «Войти» уходила под нижний край
    // монитора 1366×768 — того самого, который стоит на кассе.
    expect(терминал()).toContain('max-width: 100px');
  });
});
