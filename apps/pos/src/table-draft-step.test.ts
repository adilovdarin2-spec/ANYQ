import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { stepDraft } from './components/TableOrderScreen';
import type { DraftItem } from './components/TableOrderScreen';

/**
 * Лишнее нажатие снимается, и снимается вместе с кодом.
 *
 * Черновик за столом умел только расти: плитка прибавляла штуку, а убавить было
 * нечем. Выйти «назад» — потерять набранное целиком. То есть официант, нажавший
 * чай третий раз вместо второго, выбирал между лишней чашкой на кухне и
 * пятнадцатью позициями заново.
 *
 * Маркировка добавляет к этому условие, которое нельзя нарушить даже ради
 * удобства: штук в позиции ровно столько, сколько пачек поднесли к сканеру.
 * Кнопка «плюс» у такой позиции не рисуется, а «минус» снимает последний код
 * вместе со штукой — иначе в заказ попала бы пачка, которую нечем погасить.
 */

const SCREEN = resolve(__dirname, 'components', 'TableOrderScreen.tsx');

const чай: DraftItem = { productId: 'p-tea', name: 'Чай «Асем»', price: 550, qty: 3, codes: [] };
const сигареты: DraftItem = {
  productId: 'p-cig',
  name: 'Сигареты',
  price: 1400,
  qty: 3,
  codes: ['код-1', 'код-2', 'код-3'],
};

describe('шаг количества в черновике стола', () => {
  it('убавляет и прибавляет обычную позицию', () => {
    expect(stepDraft([чай], 'p-tea', -1)[0].qty).toBe(2);
    expect(stepDraft([чай], 'p-tea', 1)[0].qty).toBe(4);
  });

  it('на нуле убирает строку, а не оставляет её с нулём', () => {
    // Позиция с нулём в счёте гостя читается как что-то, за что он всё-таки
    // платит.
    expect(stepDraft([{ ...чай, qty: 1 }], 'p-tea', -1)).toEqual([]);
    expect(stepDraft([{ ...чай, qty: 1 }, сигареты], 'p-tea', -1)).toHaveLength(1);
  });

  it('и не трогает соседей', () => {
    const после = stepDraft([чай, сигареты], 'p-tea', -1);
    expect(после[1]).toEqual(сигареты);
    // Прежний массив остаётся прежним: черновик лежит в состоянии React.
    expect(чай.qty).toBe(3);
  });

  it('у маркированной позиции снимает код вместе со штукой', () => {
    const после = stepDraft([сигареты], 'p-cig', -1)[0];
    expect(после.qty).toBe(2);
    expect(после.codes, 'иначе в заказ уедет код без штуки').toEqual(['код-1', 'код-2']);
  });

  it('и штук у неё ровно столько, сколько кодов, сколько бы ни нажимали', () => {
    /* Инвариант целиком: каждое уменьшение оставляет пару «штуки — коды»
       согласованной. Проверяется до самого нуля, потому что ломается такое
       обычно на последнем шаге. */
    let текущий: DraftItem[] = [сигареты];
    const шаги: string[] = [];
    while (текущий.length) {
      const d = текущий[0];
      шаги.push(`${d.qty}:${d.codes.length}`);
      expect(d.codes.length, шаги.join(' ')).toBe(d.qty);
      текущий = stepDraft(текущий, 'p-cig', -1);
    }
    expect(шаги).toEqual(['3:3', '2:2', '1:1']);
  });

  it('а «плюса» у маркированной позиции на экране нет', () => {
    /* Функция сама прибавить может — её зовут и обычные позиции. Запрет живёт в
       разметке, и проверять его надо там же, иначе он однажды исчезнет вместе с
       условием. */
    const source = readFileSync(SCREEN, 'utf8').replace(/\r\n/g, '\n');
    expect(source).toContain('{d.codes.length === 0 && (');
    const плюс = source.indexOf("aria-label={t('cart.more')}");
    const условие = source.indexOf('{d.codes.length === 0 && (');
    expect(плюс, 'кнопка «больше» не нашлась').toBeGreaterThan(0);
    expect(условие, 'кнопка «больше» больше не под условием').toBeLessThan(плюс);
  });
});
