import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { markedCodeKey as tillKey, parseMarkedCode as tillParse } from './marking';
import { markedCodeKey as serverKey, parseMarkedCode as serverParse } from '../../api/src/marking';

/**
 * Две копии разбора кода обязаны отвечать одинаково.
 *
 * Касса разбирает код ради одного: узнать по GTIN, какой товар положить в
 * корзину. Решает всё равно сервер — касса шлёт ему сырую строку, и при
 * расхождении сервер ответит «код от другого товара», а не запишет чужую пачку.
 * То есть деньги от этой копии не зависят.
 *
 * Зависит другое: кассир. Разойдись копии — и он получает отказ на код, который
 * касса только что приняла, посреди очереди, без единой подсказки, что делать.
 * Такое расхождение не видно ни в одном экране и живёт до первого клиента.
 *
 * Тот же приём, что у денег: `cart.test.ts` гоняет кассовую и серверную
 * арифметику по одним данным. Здесь по одним данным гоняется разбор — и данные
 * не придуманы, а собраны из обоих наборов тестов сразу, чтобы список не
 * сузился до того, что удобно.
 */

const GS = '';

/**
 * Корпус: всё, на чём разбор проверяется по обе стороны, плюс пограничное.
 *
 * Список — часть проверки. Сузить его до пары примеров значит получить зелёный
 * тест, который ничего не держит.
 */
const CORPUS = [
  `010460717781362821AbCd12345${GS}93Zxy1`,
  '010460717781362821AbCd12345',
  '(01)04607177813628(21)AbCd12345',
  `0104607177813628172612312110ABC${GS}8005112000`,
  `010460717781362821SER1${GS}93dGVz`,
  '21ABC123',
  '0104607177813628',
  '4607177813628',
  '',
  '   ',
  '0104607177813628' + '21' + 'A'.repeat(21),
  '0104607177813628' + '21' + 'A'.repeat(20),
  '010460717',
  'не код вовсе',
  `01046071778136282100${GS}93x`,
  `0104607177813628211${GS}`,
  '010460717781362821SER/WITH-SIGNS_1',
];

describe('разбор кода: касса и сервер', () => {
  it('отвечают одинаково на каждой строке корпуса', () => {
    const разошлись: string[] = [];
    for (const raw of CORPUS) {
      const a = tillParse(raw);
      const b = serverParse(raw);
      if (JSON.stringify(a) !== JSON.stringify(b)) {
        разошлись.push(`«${raw}»: касса ${JSON.stringify(a)}, сервер ${JSON.stringify(b)}`);
      }
    }
    expect(разошлись).toEqual([]);
  });

  it('и ключ у них один', () => {
    for (const raw of CORPUS) {
      const a = tillParse(raw);
      const b = serverParse(raw);
      if (!a.ok || !b.ok) continue;
      expect(tillKey(a.code), raw).toBe(serverKey(b.code));
    }
  });

  it('и корпус правда что-то разбирает, а не весь отказной', () => {
    // Иначе «отвечают одинаково» проходило бы и на двух сломанных разборах:
    // оба вернули бы отказ на всё.
    const разобрано = CORPUS.filter((raw) => tillParse(raw).ok).length;
    expect(разобрано, 'в корпусе должны быть читаемые коды').toBeGreaterThan(5);
    const отказано = CORPUS.length - разобрано;
    expect(отказано, 'и нечитаемые тоже').toBeGreaterThan(3);
  });

  it('а сами файлы не разъехались как текст', () => {
    // Последняя линия: одинаковые ответы на корпусе не значат одинакового кода.
    // Правка, которую забыли перенести, может не попасть ни на одну строку
    // корпуса — и тогда разойдутся они завтра, на настоящей пачке.
    //
    // Сравнивается тело разбора, а не файл целиком: заголовочные комментарии у
    // копий разные намеренно — кассовый объясняет, почему он копия.
    const body = (path: string) => {
      const text = readFileSync(resolve(__dirname, path), 'utf8');
      return text.slice(text.indexOf('const GS =')).replace(/\r\n/g, '\n');
    };
    expect(body('./marking.ts')).toBe(body('../../api/src/marking.ts'));
  });
});
