/**
 * Число так, как его набирает человек за прилавком.
 *
 * `<input type="number">` для этого не годится, и это замерено, а не мнение.
 * Такое поле отдаёт **пустую строку**, когда содержимое не число по правилам
 * HTML, — а запятая и пробел ими не являются:
 *
 *   «1,5» → ""      «0,25» → ""      «1 200» → ""      «1.5» → "1.5"
 *
 * В управляемом поле React это хуже, чем пустота. Значение переписывается
 * обратно после каждого знака, поэтому набор «1», «2», «,», «5» даёт не «12,5»
 * и не пустоту, а **«5»**:
 *
 *   1 → "1"     2 → "12"     , → ""     5 → "5"
 *
 * Кладовщик, принимающий 12,5 кг сахара, принимал пять. Ошибка в остатке,
 * которая вылезет только на следующем пересчёте — необъяснимым излишком.
 *
 * А набирают именно так: десятичная клавиша на цифровом блоке с русской и
 * казахской раскладкой — запятая, тысячи тенге пишут через пробел.
 *
 * Поэтому в кассе числовое поле — это `type="text"` с `inputMode`: цифровой
 * блок под пальцем тот же, а строка доезжает целой. Разбирает её эта функция.
 */

/**
 * Строка из поля — в число. `NaN`, если набрано не число.
 *
 * `NaN`, а не ноль: ноль — это «набрали ноль», и путать его с «набрали чепуху»
 * нельзя. Именно на этом товар с незаполненной ценой уезжал в каталог даром.
 */
export function parseTyped(raw: unknown): number {
  // Число пропускается насквозь: те же места разбирают то строку из поля, то
  // уже разобранное значение из состояния, и второй разбор не должен его портить.
  if (typeof raw === 'number') return Number.isFinite(raw) ? raw : NaN;
  if (typeof raw !== 'string') return NaN;
  const cleaned = raw
    // Пробелы любого рода, включая неразрывный: так пишут тысячи.
    .replace(/[\s ]/g, '')
    // Запятая — десятичный разделитель, а не разделитель разрядов: «1,5» это
    // полтора. Так же считает и разбор выгрузки (`parseNumber` в импорте).
    .replace(',', '.');
  if (cleaned === '') return NaN;
  return Number(cleaned);
}

/** Набрано ли положительное число: то, что спрашивают у количества. */
export function isPositive(raw: string): boolean {
  const value = parseTyped(raw);
  return Number.isFinite(value) && value > 0;
}

/** Набрано ли неотрицательное число: то, что спрашивают у цены. */
export function isNonNegative(raw: string): boolean {
  const value = parseTyped(raw);
  return Number.isFinite(value) && value >= 0;
}
