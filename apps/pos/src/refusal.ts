import { ApiError } from './api';

/**
 * Про эту ли операцию отказ сервера.
 *
 * Очередь — продаж ли, складских ли команд — должна отличать две вещи. «Не
 * хватило остатка», «цены изменились», «смена уже закрыта» — это про саму
 * операцию: сколько ни повторяй, ответ будет тот же, пока человек чего-нибудь
 * не сделает. А «доступ отозван» и «тариф кончился» — это про кассу целиком:
 * операция хорошая, войти заново или заплатить — дело минуты, и после этого
 * уйдёт вся очередь сразу.
 *
 * Разница видна там, где очередь показывают человеку. Пометить тридцать
 * утренних чеков «отказано» из-за того, что владелец сменил кассиру роль,
 * значит отправить его разбирать каждый по одному — вместо одного входа в
 * кассу.
 */
export function refusalIsAboutThisRequest(err: unknown): err is ApiError {
  if (!(err instanceof ApiError)) return false;
  // Пятисотые — это про сервер, а не про запрос: он мог не дойти вовсе.
  if (err.status >= 500) return false;
  // Сессия и тариф — про кассу целиком.
  if (err.status === 401 || err.status === 403) return false;
  return err.status >= 400;
}
