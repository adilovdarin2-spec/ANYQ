/**
 * Единица измерения рядом с числом — в той форме, в какой её говорят.
 *
 * Витрина печатала единицу как есть: «4 упаковка», «2 мешок», «3 канистра». По
 * одной такой строке на каждую позицию корзины, и закупщик читает их подряд,
 * набирая заявку на сорок строк. «1 упаковка» при этом было верно — то есть
 * ошибка появлялась ровно тогда, когда заказывают всерьёз.
 *
 * Русский счёт трёхчастный: 1 — «упаковка», 2–4 — «упаковки», 5 и дальше —
 * «упаковок», и 11–14 идут с последней формой вопреки последней цифре. Та же
 * тройка, что в `pluralPhrase` кассы; здесь она применяется не к фразе из
 * словаря, а к слову, которое магазин написал сам в карточке товара.
 *
 * **Незнакомая единица возвращается как есть.** Склонять произвольное слово по
 * правилам — значит однажды выдать «3 бутыля» вместо «3 бутылей» и выглядеть
 * глупее, чем без склонения вовсе. Список закрыт и покрывает то, что встречается
 * в каталогах: их одиннадцать на всю базу.
 *
 * Найдено 30.09.2026 прогоном витрины: «Это весь остаток — 4 упаковка».
 */

/** Единица → [одна, две-четыре, пять и больше]. */
const FORMS: Record<string, [string, string, string]> = {
  штука: ['штука', 'штуки', 'штук'],
  упаковка: ['упаковка', 'упаковки', 'упаковок'],
  пачка: ['пачка', 'пачки', 'пачек'],
  бутылка: ['бутылка', 'бутылки', 'бутылок'],
  банка: ['банка', 'банки', 'банок'],
  коробка: ['коробка', 'коробки', 'коробок'],
  канистра: ['канистра', 'канистры', 'канистр'],
  мешок: ['мешок', 'мешка', 'мешков'],
  ящик: ['ящик', 'ящика', 'ящиков'],
  рулон: ['рулон', 'рулона', 'рулонов'],
  лоток: ['лоток', 'лотка', 'лотков'],
  порция: ['порция', 'порции', 'порций'],
  блок: ['блок', 'блока', 'блоков'],
  литр: ['литр', 'литра', 'литров'],
  метр: ['метр', 'метра', 'метров'],
};

/**
 * Какая из трёх форм нужна этому числу.
 *
 * Дробное считается по целой части: «1,5 мешка» — это форма для двух-четырёх,
 * как и говорят. Ноль идёт с формой «пять и больше»: «0 упаковок».
 */
function form(count: number): 0 | 1 | 2 {
  const whole = Math.floor(Math.abs(count));
  // Дробное: «0,5 мешка», «2,5 мешка» — всегда родительный единственного,
  // то есть та же форма, что у двух-четырёх.
  if (whole !== Math.abs(count)) return 1;
  const last = whole % 10;
  const lastTwo = whole % 100;
  if (lastTwo >= 11 && lastTwo <= 14) return 2;
  if (last === 1) return 0;
  if (last >= 2 && last <= 4) return 1;
  return 2;
}

export function unitFor(count: number, unit: string): string {
  const forms = FORMS[unit.trim().toLowerCase()];
  return forms ? forms[form(count)] : unit;
}

/** Число и единица вместе — то, что печатается рядом с ценой и остатком. */
export function withUnit(count: number, unit: string): string {
  return `${count.toLocaleString('ru-RU', { maximumFractionDigits: 3 })} ${unitFor(count, unit)}`;
}
