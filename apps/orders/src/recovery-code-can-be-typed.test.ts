import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { withoutComments } from '../../../scripts/lib/source-text.mjs';

/**
 * Код восстановления можно набрать на том устройстве, где его спрашивают.
 *
 * Поле второго фактора принимало и шесть цифр из приложения, и код
 * восстановления — `XZ7I-VOEM`, буквы и дефис, — и подсказка прямо это
 * предлагала. Но у поля стояло `inputMode="numeric"`, а на телефоне это
 * цифровая панель, на которой букв нет вовсе.
 *
 * Кабинет и есть экран телефона: так написано в соседнем предупреждении про
 * второй фактор — «эта ссылка открывается с телефона». То есть ровно в тот
 * единственный раз, когда код восстановления нужен — телефон потерян, человек
 * стоит с новым, — набрать его было нечем.
 *
 * Цифровую панель при этом терять незачем: шесть цифр набирают каждый вход, а
 * код восстановления — один раз в жизни. Поэтому не замена, а переключатель.
 *
 * Найдено 02.10.2026 прогоном кабинета владельца.
 */

const gate = withoutComments(
  readFileSync(resolve(__dirname, 'components', 'CabinetGate.tsx'), 'utf8'),
).replace(/\r\n/g, '\n');

describe('вход в кабинет со вторым фактором', () => {
  it('клавиатура зависит от того, что просят ввести', () => {
    expect(gate).toContain("inputMode={recovery ? 'text' : 'numeric'}");
  });

  it('и переключиться на код восстановления есть чем', () => {
    expect(gate).toContain('setRecovery((was) => !was)');
    expect(gate).toContain('Телефон потерялся');
  });

  it('переключение чистит поле — набранные цифры в коде восстановления не нужны', () => {
    const toggle = gate.slice(gate.indexOf('setRecovery((was) => !was)'));
    expect(toggle.slice(0, 120)).toContain("setCode('')");
  });

  it('подсказка в каждом положении говорит про своё', () => {
    // «Шесть цифр, а если телефон потерялся — то код восстановления» в одной
    // строке — это две разные инструкции человеку, который сейчас выбирает.
    expect(gate).toContain('Шесть цифр из приложения-аутентификатора.');
    expect(gate).toContain('XZ7I-VOEM');
  });

  it('а поле остаётся одним — запрос к серверу один и тот же', () => {
    /* Два поля означали бы два пути на сервер и вопрос «какое из них
       заполнять», который человеку задавать незачем: сервер и так принимает
       оба вида в одном поле. */
    expect(gate.match(/id="cab-code"/g) ?? []).toHaveLength(1);
    expect(gate).toContain('onSubmit(password, code.trim())');
  });
});
