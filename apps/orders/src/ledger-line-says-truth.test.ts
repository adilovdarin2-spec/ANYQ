import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pluralizeRu } from './utils';
// @ts-expect-error — общий разборщик написан на .mjs и типов не имеет.
import { withoutComments } from '../../../scripts/lib/source-text.mjs';

/**
 * Строка про учёт говорит то, что проверено.
 *
 * Рядом с ней в кабинете написано: «Проверка, а не обещание: остаток равен
 * сумме движений, и это пересчитано, а не заявлено». При нуле проверенных
 * позиций пересчитывать было нечего, а строка всё равно отвечала зелёным
 * «Остатки сходятся с журналом: проверено 0 позиций».
 *
 * Читает это владелец в первый день — товаров ещё нет, движений не было, — и
 * получает подтверждение, что учёт в порядке, хотя учёта пока никакого. Такое в
 * этом продукте уже правили: очередь дел отвечала пустому магазину «ничего не
 * требует вашего решения, хороший день», и это оказалось неправдой ровно по той
 * же причине.
 *
 * Вторая половина — счётное слово. «Проверено 1 позиций» по-русски не говорят.
 */

const SCREEN = resolve(__dirname, 'components', 'CabinetScreen.tsx');
const read = () => withoutComments(readFileSync(SCREEN, 'utf8')).replace(/\r\n/g, '\n');

describe('строка про учёт', () => {
  it('у нуля проверенных — свой ответ', () => {
    const src = read();
    /* Условие сразу за скобкой, а не где-нибудь в строке: `{false && …`
       содержит ту же подстроку и прошёл бы проверку на вхождение — это
       выяснилось поломкой, а не рассуждением. */
    expect(src).toContain('{summary.ledgerCheck.checked === 0');
    expect(src).toContain('Сверять пока нечего');
  });

  it('и он стоит раньше, чем «сходятся»', () => {
    /* Порядок и есть починка: развилка по нулю должна проверяться до развилки
       по расхождениям, иначе ноль снова попадёт в «сходятся». */
    const src = read();
    const ноль = src.indexOf('summary.ledgerCheck.checked === 0');
    const сходятся = src.indexOf('Остатки сходятся с журналом');
    expect(ноль, 'развилка по нулю не найдена').toBeGreaterThan(0);
    expect(ноль).toBeLessThan(сходятся);
  });

  it('а число позиций склоняется', () => {
    expect(read()).toContain("pluralizeRu(summary.ledgerCheck.checked, 'позиция', 'позиции', 'позиций')");
  });
});

describe('склонение', () => {
  it('одна, две, пять — и одиннадцать как пять', () => {
    const форма = (n: number) => `${n} ${pluralizeRu(n, 'позиция', 'позиции', 'позиций')}`;
    expect(форма(1)).toBe('1 позиция');
    expect(форма(2)).toBe('2 позиции');
    expect(форма(4)).toBe('4 позиции');
    expect(форма(5)).toBe('5 позиций');
    // Одиннадцать кончается на единицу и ведёт себя как много — на этом
    // наивное правило и ломается.
    expect(форма(11)).toBe('11 позиций');
    expect(форма(21)).toBe('21 позиция');
    expect(форма(112)).toBe('112 позиций');
    expect(форма(0)).toBe('0 позиций');
  });
});
