/**
 * Почему число перестало расти.
 *
 * Витрина ограничивает строку остатком — и это правильно: принять заказ на
 * большее значило бы пообещать за поставщика то, чего у него нет. Но делала
 * она это молча. Закупщик набирает мешками, вводит «100», поле показывает
 * «30», и объяснения нет нигде: метка об остатке появляется только когда его
 * совсем мало, а «+» просто перестаёт нажиматься.
 *
 * Молчание здесь дороже, чем кажется. Оптовик не перечитывает корзину по
 * строкам — он набирает заявку и отправляет; заказ уезжает урезанным, и
 * замечают это, когда приходит не та машина. Одна строка на месте ввода
 * отвечает и на «почему тридцать», и на «почему плюс не нажимается».
 */
export function capNote(stock: number, unit: string): string {
  return `Это весь остаток — ${stock} ${unit}`;
}
