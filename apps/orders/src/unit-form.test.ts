import { describe, it, expect } from 'vitest';
import { unitFor, withUnit } from './unit-form';

/**
 * «4 упаковка» — то, что витрина печатала на каждой строке заказа.
 *
 * Единица бралась из карточки товара и ставилась рядом с числом как есть. При
 * одной штуке это верно, а закупщик берёт мешками: «2 мешок», «3 канистра»,
 * «4 упаковка» — по строке на позицию, и он читает их подряд.
 *
 * Найдено 30.09.2026 прогоном витрины.
 */

describe('единица рядом с числом', () => {
  it('одна — как в карточке', () => {
    expect(unitFor(1, 'упаковка')).toBe('упаковка');
    expect(unitFor(1, 'мешок')).toBe('мешок');
  });

  it('две-четыре — родительный единственного', () => {
    expect(unitFor(2, 'упаковка')).toBe('упаковки');
    expect(unitFor(3, 'мешок')).toBe('мешка');
    expect(unitFor(4, 'канистра')).toBe('канистры');
  });

  it('пять и больше — родительный множественного', () => {
    expect(unitFor(5, 'упаковка')).toBe('упаковок');
    expect(unitFor(10, 'мешок')).toBe('мешков');
    expect(unitFor(100, 'ящик')).toBe('ящиков');
  });

  it('одиннадцать-четырнадцать идут вопреки последней цифре', () => {
    /* Тот самый случай, ради которого правило трёхчастное: 11 кончается на
       единицу, а говорят «одиннадцать упаковок». */
    expect(unitFor(11, 'упаковка')).toBe('упаковок');
    expect(unitFor(12, 'упаковка')).toBe('упаковок');
    expect(unitFor(13, 'мешок')).toBe('мешков');
    expect(unitFor(14, 'ящик')).toBe('ящиков');
  });

  it('а двадцать одна — снова как одна', () => {
    expect(unitFor(21, 'упаковка')).toBe('упаковка');
    expect(unitFor(101, 'мешок')).toBe('мешок');
    expect(unitFor(22, 'упаковка')).toBe('упаковки');
  });

  it('ноль — «упаковок», а не «упаковка»', () => {
    // «Осталось 0 упаковка» встречается ровно там, где товар кончился.
    expect(unitFor(0, 'упаковка')).toBe('упаковок');
  });

  it('дробное — как говорят: «полтора мешка»', () => {
    expect(unitFor(1.5, 'мешок')).toBe('мешка');
    expect(unitFor(0.5, 'мешок')).toBe('мешка');
    expect(unitFor(2.5, 'канистра')).toBe('канистры');
  });

  it('килограммы и штуки не склоняются вовсе', () => {
    // Сокращения так и пишутся при любом числе: «5 кг», «12 шт».
    for (const n of [1, 2, 5, 11, 21]) {
      expect(unitFor(n, 'кг')).toBe('кг');
      expect(unitFor(n, 'шт')).toBe('шт');
      expect(unitFor(n, 'уп')).toBe('уп');
    }
  });

  it('незнакомая единица возвращается как есть', () => {
    /* Склонять произвольное слово по правилам — значит однажды выдать
       «3 бутыля» и выглядеть глупее, чем без склонения вовсе. Магазин пишет
       единицу сам, и что он напишет, мы не знаем. */
    expect(unitFor(3, 'бутыль')).toBe('бутыль');
    expect(unitFor(5, 'паллета')).toBe('паллета');
    expect(unitFor(2, '')).toBe('');
  });

  it('и регистр с пробелами не мешает', () => {
    expect(unitFor(3, ' Упаковка ')).toBe('упаковки');
  });

  it('число печатается по-русски, с запятой', () => {
    // Точка в числе — это код, вылезший на экран; см. formatStock в кассе.
    expect(withUnit(1.5, 'мешок')).toBe('1,5 мешка');
    expect(withUnit(4, 'упаковка')).toBe('4 упаковки');
    expect(withUnit(1000, 'кг')).toContain('кг');
  });
});
