-- Точка, остатками которой торгует витрина заказов.
--
-- До сих пор витрина брала первую точку по списку, а список отсортирован по
-- названию: у компании с двумя точками она торговала той, чьё имя раньше по
-- алфавиту, и туда же ставила бронь под заказ. Переименовали точку — витрина
-- стала продавать другую, и нигде об этом не было сказано ни слова.
--
-- NULL означает ровно прежнее поведение, поэтому миграция ничего не меняет ни
-- для одной существующей компании.
