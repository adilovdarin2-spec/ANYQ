-- У кассы появляется номер, а у тарифа — сколько их можно.
--
-- «Пробей на второй», «в первой не сходится ящик», «сменный отчёт с какой
-- кассы» — магазин с двумя кассами на входе говорит номерами, а в базе были
-- только «Windows · Chrome» и «Android · Chrome». Два одинаковых планшета —
-- две неразличимые строки, и владелец, выключающий украденный, выключал
-- наугад.
--
-- Номер выдаётся один раз и не переиспользуется: сменный отчёт подписан
-- номером, и номер, доставшийся потом другому рабочему месту, сделал бы
-- вчерашний отчёт непроверяемым.
--
-- Уже работающим кассам номера раздаются по дате первого входа — в том
-- порядке, в котором магазин их и заводил.
ALTER TABLE "pos_devices" ADD COLUMN "number" INTEGER NOT NULL DEFAULT 1;

WITH numbered AS (
  SELECT "id", ROW_NUMBER() OVER (PARTITION BY "companyId" ORDER BY "firstSeenAt", "id") AS n
  FROM "pos_devices"
)
UPDATE "pos_devices" d
SET "number" = numbered.n
FROM numbered
WHERE d."id" = numbered."id";

-- Номер уникален внутри компании. Индекс, а не соглашение: два входа с разных
-- планшетов в одну секунду — это ровно тот случай, ради которого кассы и
-- нумеруют, и «оба стали второй» здесь недопустимо.
CREATE UNIQUE INDEX "pos_devices_companyId_number_key" ON "pos_devices"("companyId", "number");

-- Сколько касс допускает тариф. NULL — без ограничения, как и остальные лимиты:
-- пустое поле означает «решения нет», а не «ну наверное две».
ALTER TABLE "tariffs" ADD COLUMN "registerLimit" INTEGER;
