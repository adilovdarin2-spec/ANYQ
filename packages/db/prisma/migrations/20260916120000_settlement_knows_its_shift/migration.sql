-- Расчёт наличными знает свою смену.
--
-- Сверка смены отвечает на один вопрос: сколько денег должно быть в ящике на
-- закрытии. Чеки попадают в неё по ссылке на смену, записанной на самом чеке.
-- У расчётов с контрагентами такой ссылки не было — их относили к смене по
-- времени и по тому, кто провёл.
--
-- Пока за кассой один человек, это одно и то же. Как только их двое — а две
-- кассы в одной точке ANYQ умеет с 15.09.2026, — деньги проваливались:
-- владелец принимал у покупателя долг наличными, клал в общий ящик, и в сверке
-- кассира этих денег не было. На закрытии у кассира выходил излишек, которого
-- он не делал.
--
-- Старым строкам смену задним числом не приписываем: кто в каком ящике был
-- полгода назад, теперь не установить, а придуманная ссылка хуже пустой.
-- Считаются они по-прежнему по времени и автору.
ALTER TABLE "settlements" ADD COLUMN "shiftId" TEXT;

CREATE INDEX "settlements_shiftId_idx" ON "settlements"("shiftId");
