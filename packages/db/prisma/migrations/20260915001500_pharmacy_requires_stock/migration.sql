-- Аптеке дописывается учёт прихода, иначе у просрочки нет выхода.
--
-- Аптечный модуль делает ровно одно полезное дело: не даёт продать
-- просроченное. Проверено вживую 15.09.2026 на тарифе ["pharmacy","retail"] —
-- продажа отказала правильно, назвав 0 годных при остатке 12.
--
-- Но остановленный товар никуда не девается. Он остаётся на полке и в
-- остатке, и убрать его можно только списанием, инвентаризацией, карантином
-- или возвратом поставщику — а все четыре живут в `stock`. На аптечном тарифе
-- без него каждая из них отвечает «недоступно на вашем тарифе». То есть
-- модуль, купленный за то, что он останавливает просрочку, копил её без
-- всякой возможности списать.
--
-- Остаток, из которого нет выхода, — это не ограничение тарифа, а испорченная
-- книга: остаток не сходится с тем, чем можно торговать, и не сойдётся уже
-- никогда.
--
-- Тем же приёмом, что и раздел склада: дописывается ровно то, без чего
-- купленное не работает, и ни одним правом больше. Запрос идемпотентен —
-- второй запуск не меняет ничего.
UPDATE "tariffs"
SET "modules" = ("modules"::jsonb || '["stock"]'::jsonb)::text
WHERE "modules"::jsonb ? 'pharmacy'
  AND NOT ("modules"::jsonb ? 'stock');
