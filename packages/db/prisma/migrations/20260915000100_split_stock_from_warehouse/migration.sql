-- «Склад» разделён надвое, и у тех, кто уже подключён, ничего не должно
-- отвалиться.
--
-- До сегодняшнего дня модуль `warehouse` открывал всё сразу: и приёмку с
-- инвентаризацией, и ячейки с перемещениями, закупками и производством.
-- Из-за этого не существовало тарифа для обычного магазина — магазин без
-- приёмки не работает, товар приходит и остаток обязан подняться, — а
-- включить приёмку значило отдать заодно весь склад целиком.
--
-- Теперь приёмка, инвентаризация, списание, карантин и возврат поставщику
-- живут в модуле `stock`, а `warehouse` остался тем, чем и назывался: ячейки,
-- пересчёт по ячейкам, перемещения между точками, заказы поставщику и
-- производство.
--
-- Без этой строки первый же деплой отнял бы приёмку у каждого действующего
-- клиента: сервер спросил бы `stock`, а в тарифе записан `warehouse`. Поэтому
-- всем, у кого склад есть, дописывается и учёт прихода — это ровно то, чем
-- они пользовались вчера, и ни одним правом больше.
--
-- Порядок в списке не важен: он читается как множество.
UPDATE "tariffs"
SET "modules" = ("modules"::jsonb || '["stock"]'::jsonb)::text
WHERE "modules"::jsonb ? 'warehouse'
  AND NOT ("modules"::jsonb ? 'stock');
