-- Партия бывает дробной: сыр, колбаса, фасованное на месте.
--
-- Остаток хранится дробным, позиция документа — дробной, а количество в партии
-- было целым. Постгрес про это не спорил: он молча округлял всё, что туда
-- писали, и книги расходились в тот же момент.
--
-- Приёмка партии на 2.5 кг поднимала остаток на 2.5 и записывала в партию 2.
-- Продажа полутора килограммов из двух партий по килограмму уменьшала остаток
-- на 1.5 правильно, а из партий списывала один: вычитание 0.5 из целой колонки
-- не делало ничего. Магазин оставался с расхождением, которого не создавал, —
-- партий 1 при остатке 0.5, — и касса предлагала килограмм при полукилограмме
-- на полке, потому что доступное к продаже она считает по партиям.
--
-- Расширение типа: всё, что лежало, — целые числа, и они остаются собой.
-- Обратной миграции нет намеренно: сузить колонку обратно можно только
-- округлив чей-то настоящий остаток.
ALTER TABLE "product_batches" ALTER COLUMN "quantity" TYPE DOUBLE PRECISION;
