/**
 * Сколько соединений с базой держит одна служба.
 *
 * Запрос кассы — это не один запрос к базе. Сводка смены собирается из десяти
 * запросов сразу, подсказка пополнения — из шести: они уходят вместе, и
 * каждому нужно своё соединение. Без явного значения Prisma выводит размер
 * пула из числа процессоров машины — величины, которая в контейнере говорит не
 * о том. Она бывает меньше нужного: тогда десятизапросный экран встаёт в
 * очередь сам к себе и через `pool_timeout` отдаёт отказ. Бывает и больше:
 * тогда несколько экземпляров службы вместе упираются в `max_connections`
 * базы. Ни то, ни другое не похоже на неполадку с базой — на экране закрытия
 * смены просто «внутренняя ошибка», и ровно в тот час, когда смену закрывают
 * все сразу.
 *
 * Поэтому значение задано здесь, а не оставлено на того, кто будет набирать
 * адрес базы руками. Написанный в адресе `connection_limit` всё равно
 * побеждает — для случая, когда базу делят с кем-то ещё и сумму пулов надо
 * держать ниже `max_connections`.
 */
export const POOL_SIZE = 20;

/** Адрес базы с размером пула — своим, если он в адресе уже есть. */
export function withPoolSize(url: string | undefined, size: number = POOL_SIZE): string | undefined {
  if (!url) return undefined;
  if (/[?&]connection_limit=/.test(url)) return url;
  return `${url}${url.includes('?') ? '&' : '?'}connection_limit=${size}`;
}
