/**
 * Повтор запроса, который не доехал до базы.
 *
 * P1001 — это «не удалось открыть соединение»: запрос не дошёл до сервера, не
 * выполнился и ничего не изменил. Такой запрос можно послать заново без
 * оглядки на то, что он делал, — в отличие от запроса, оборвавшегося на
 * полпути, про который неизвестно, записался он или нет. Здесь повторяется
 * только первый случай, и это не осторожность ради осторожности: повторить
 * списание остатка «на всякий случай» — значит списать дважды.
 *
 * Зачем вообще: соединение до базы иногда не открывается с первого раза.
 * В production — секунда сетевой ряби или перезапуск базы; на машине
 * разработчика — Docker Desktop, который под залпом одновременных
 * подключений часть из них отбрасывает. Экран кассы, собирающий ответ из
 * десяти запросов сразу, — это как раз залп. Без повтора один такой случай
 * становится «внутренней ошибкой» посреди продажи.
 *
 * Три попытки и паузы в сотни миллисекунд: если база действительно лежит,
 * отказ всё равно придёт быстро и честно, а не через полминуты ожидания.
 */
export const ATTEMPTS = 3;
export const PAUSE_MS = 150;

/**
 * Запрос не дошёл до базы — в отличие от «дошёл и не понравился».
 *
 * Определяется по двум признакам сразу, и это не перестраховка. Первая версия
 * этой функции спрашивала только `errorCode === 'P1001'` — так написано в
 * документации, и так выглядит правдоподобно. У живой ошибки Prisma 6.19
 * `errorCode` равен `undefined`: код есть в тексте сообщения, но не в поле.
 * Функция не срабатывала никогда, повтор не повторял ничего, и тесты при этом
 * были зелёными — потому что проверяли объект, который я придумал сам.
 *
 * Поэтому здесь и поле (вдруг другая версия его заполняет), и то, чем ошибка
 * является на самом деле: неудача подключения с текстом про недоступный
 * сервер. Класс без текста брать нельзя — тем же классом приходит «неверный
 * пароль», а его повторять бессмысленно.
 */
export function unreachable(error: unknown): boolean {
  if (typeof error !== 'object' || error === null) return false;
  const e = error as { errorCode?: unknown; code?: unknown; name?: unknown; message?: unknown };
  if (e.errorCode === 'P1001' || e.code === 'P1001') return true;
  const text = typeof e.message === 'string' ? e.message : '';
  return e.name === 'PrismaClientInitializationError' && text.includes("Can't reach database server");
}

export async function retryUnreachable<T>(
  run: () => Promise<T>,
  pause: (ms: number) => Promise<void> = (ms) => new Promise((r) => setTimeout(r, ms)),
): Promise<T> {
  for (let attempt = 1; ; attempt++) {
    try {
      return await run();
    } catch (error) {
      if (attempt >= ATTEMPTS || !unreachable(error)) throw error;
      await pause(PAUSE_MS * attempt);
    }
  }
}
